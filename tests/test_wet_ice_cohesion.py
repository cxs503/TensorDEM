def test_criterion_c_enhancement_factor_vs_micro_mechanical_reference():
    wet = cohesion_cell.run_cohesion_cell(n_particles=250, gamma=0.3)
    dry = cohesion_cell.run_cohesion_cell(n_particles=250, gamma=0.0, n_pull=500)
    assert abs(dry.cohesion) < 1e-6
    bank = math.pi / 0.80                      # 2D area per particle, R = 1
    mean_bridge = wet.bridge_force_mean / wet.bridge_count
    c_ref = wet.coordination * mean_bridge / (math.pi * bank)
    sigma = 2.0
    f_dem = (sigma + wet.cohesion) / sigma
    f_ref = (sigma + c_ref) / sigma
    assert abs(f_dem - f_ref) / f_ref < 0.20, (
        f"enhancement deviation {abs(f_dem - f_ref) / f_ref:.3f} exceeds 20 %"
    )


def test_cohesion_grows_with_surface_tension():
    low = cohesion_cell.run_cohesion_cell(n_particles=180, gamma=0.15, n_pull=500, n_relax=250)
    high = cohesion_cell.run_cohesion_cell(n_particles=180, gamma=0.4, n_pull=500, n_relax=250)
    assert high.cohesion > low.cohesion > 0.0


