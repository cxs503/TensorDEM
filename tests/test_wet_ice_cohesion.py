"""Acceptance tests for the P35-N2 wet-ice cohesion capability.

Each criterion of the campaign node is one test (the criterion letter is in the
test name so the report can be traced to a runnable assertion):

* (a) ``test_criterion_a_*``  -- bridge peak force vs the exact Young-Laplace
  solution, < 5 %
* (b) ``test_criterion_b_*``  -- agglomerate mean size vs Smoluchowski, < 15 %
* (c) ``test_criterion_c_*``  -- ice-resistance enhancement factor vs the
  micro-mechanical reference, < 20 %
* (d) ``test_criterion_d_*``  -- ``gamma = 0`` negative control, dry behaviour
* (e) ``test_criterion_e_*``  -- time-step / system-size convergence, < 2 %
* (f) this file
* (g) ``test_criterion_g_*``  -- the seeded closed form is falsified

The heavy grid validation of the closed form is *pinned* in
``artifacts/wet_ice_cohesion/capillary_reference.json`` (regenerated by
``scripts/gen_wet_ice_capillary_reference.py``); the test reads the pin and also
runs a few live Young-Laplace solves so the pin cannot silently drift.
"""
from __future__ import annotations

import json
import math
import os

import numpy as np
import pytest

from tensordem.wet_ice_cohesion import (
    aggregation,
    capillary,
    cohesion_cell,
    ice_resistance,
)

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REFERENCE = os.path.join(REPO_ROOT, "artifacts", "wet_ice_cohesion", "capillary_reference.json")

R_REF = 5.0e-4
GAMMA_REF = 0.0759
F0 = 2.0 * math.pi * GAMMA_REF * R_REF


@pytest.fixture(scope="module")
def reference():
    with open(REFERENCE) as fh:
        return json.load(fh)


def _usable(rows, max_residual=1e-2):
    out = []
    for r in rows:
        if r.get("force_over_f0") is None or not np.isfinite(r["force_over_f0"]):
            continue
        if r.get("residual", 0.0) > max_residual:
            continue
        out.append(r)
    return out


# ---------------------------------------------------------------------------
# (a) peak force vs the exact reference
# ---------------------------------------------------------------------------

def test_criterion_a_peak_force_vs_pinned_reference(reference):
    """Held-out peak forces (s = 0) of the closed form vs the exact solution."""
    rows = _usable(reference["validate"])
    peaks = [r for r in rows if r["gap_over_R"] == 0.0]
    assert len(peaks) >= 5
    errs = []
    for r in peaks:
        model = capillary.capillary_force(
            R_REF, GAMMA_REF, r["volume_over_R3"] * R_REF ** 3, 0.0, r["theta_deg"]
        )
        errs.append(abs(model - r["force_over_f0"] * F0) / (r["force_over_f0"] * F0))
    assert max(errs) < 0.05, f"peak error {max(errs):.4f} exceeds 5 %"


def test_criterion_a_live_young_laplace_check():
    """Live solve: the closed form must match the solver, not just the pin."""
    for volume_over_r3 in (0.006, 0.06):
        sol = capillary.exact_force(
            R_REF, GAMMA_REF, volume_over_r3 * R_REF ** 3, 0.0, 0.0, n_steps=200
        )
        assert sol is not None and math.isfinite(sol.force)
        model = capillary.capillary_force(R_REF, GAMMA_REF, volume_over_r3 * R_REF ** 3, 0.0, 0.0)
        assert abs(model - sol.force) / sol.force < 0.05
        # the reference must stay below the classical small-bridge limit
        assert 0.7 < sol.force / capillary.small_bridge_limit(R_REF, GAMMA_REF) < 1.0


def test_reference_first_integral_is_self_consistent(reference):
    """The exact solution's own invariant: neck and contact-line forces agree."""
    rows = _usable(reference["train"]) + _usable(reference["validate"])
    errs = [
        abs(r["force_over_f0"] - r["force_contact_line_over_f0"]) / r["force_over_f0"]
        for r in rows
        if r.get("force_contact_line_over_f0")
    ]
    assert errs and max(errs) < 0.02


def test_criterion_a_curve_error_outside_peak_is_reported_honestly(reference):
    """The whole-curve error is *not* claimed < 5 %: assert the measured bound."""
    rows = _usable(reference["validate"])
    errs = []
    for r in rows:
        model = capillary.capillary_force(
            R_REF, GAMMA_REF, r["volume_over_R3"] * R_REF ** 3,
            r["gap_over_R"] * R_REF, r["theta_deg"],
        )
        errs.append(abs(model - r["force_over_f0"] * F0) / (r["force_over_f0"] * F0))
    # measured: ~1.5 % mean, <= 13 % worst case (small-volume / small-gap corner)
    assert np.mean(errs) < 0.05
    assert max(errs) < 0.20


# ---------------------------------------------------------------------------
# (g) the seeded campaign formula is falsified
# ---------------------------------------------------------------------------

def test_criterion_g_seeded_formula_is_never_attractive():
    """F(0) = 0 and F(s) < 0 for all s > 0 -> the seeded form cannot be a bridge law."""
    h = 0.3 * R_REF
    assert capillary.seeded_campaign_force(R_REF, GAMMA_REF, 0.0, h) == 0.0
    for s_over_h in (0.05, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0):
        assert capillary.seeded_campaign_force(R_REF, GAMMA_REF, s_over_h * h, h) < 0.0
    # and the exact solution does the opposite: max at contact, decay afterwards
    f_contact = capillary.capillary_force(R_REF, GAMMA_REF, 0.02 * R_REF ** 3, 0.0)
    f_gap = capillary.capillary_force(R_REF, GAMMA_REF, 0.02 * R_REF ** 3, 0.05 * R_REF)
    assert f_contact > 0.0 and f_gap < f_contact


