# (e) convergence
# ---------------------------------------------------------------------------

def test_criterion_e_timestep_convergence():
    base = aggregation.simulate_shear_aggregation(
        n_particles=300, shear_rate=1.0, total_strain=1.0, dt_fraction=0.02, seed=7
    )
    fine = aggregation.simulate_shear_aggregation(
        n_particles=300, shear_rate=1.0, total_strain=1.0, dt_fraction=0.01, seed=7
    )
    rel = np.max(np.abs(fine.mean_diameter - base.mean_diameter) / base.mean_diameter)
    assert rel < 0.02, f"time-step change {rel:.4f} exceeds 2 %"


def test_criterion_e_system_size_convergence():
    base = aggregation.simulate_shear_aggregation(
        n_particles=300, shear_rate=1.0, total_strain=1.0, dt_fraction=0.02, seed=7
    )
    big = aggregation.simulate_shear_aggregation(
        n_particles=600, shear_rate=1.0, total_strain=1.0, dt_fraction=0.02, seed=7
    )
    rel = np.max(np.abs(big.mean_diameter - base.mean_diameter) / base.mean_diameter)
    assert rel < 0.02, f"system-size change {rel:.4f} exceeds 2 %"


