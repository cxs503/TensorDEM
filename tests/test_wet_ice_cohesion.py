def test_timco_weeks_brine_volume_spot_value():
    vb = ice_resistance.timco_weeks_brine_volume(5.0, -5.0)
    assert vb == pytest.approx(0.0518, abs=2e-3)
    with pytest.raises(ValueError):
        ice_resistance.timco_weeks_brine_volume(5.0, 2.0)
    assert ice_resistance.timco_weeks_strength_factor(0.0) == pytest.approx(1.0)
    assert ice_resistance.timco_weeks_strength_factor(0.29) == 0.0


def test_bond_number_window():
    """Capillary cohesion matters below R ~ 3 mm for ice/water."""
    r_star = math.sqrt(ice_resistance.GAMMA_WATER_0C / (917.0 * 9.81))
    assert ice_resistance.bond_number(r_star) == pytest.approx(1.0, rel=1e-9)
    assert 2.0e-3 < r_star < 4.0e-3
    assert ice_resistance.bond_number(1e-5) < 0.01


def test_dugdale_equivalent_work_of_separation():
    """Maugis-Dugdale idealisation: equal peak and equal rupture work."""
    out = capillary.dugdale_equivalent(R_REF, GAMMA_REF, 0.05 * R_REF ** 3, n_samples=12)
    assert out["work_of_separation"] > 0.0
    assert out["peak_force"] > 0.0
    assert out["delta_c"] > 0.0
    assert out["coverage"] > 0.5      # the solver must converge on most samples


def test_model_rejects_bad_input():
    with pytest.raises(ValueError):
        capillary.capillary_force(-1.0, GAMMA_REF, 1e-12, 0.0)
    with pytest.raises(ValueError):
        capillary.capillary_force(R_REF, -1.0, 1e-12, 0.0)
    with pytest.raises(ValueError):
        capillary.capillary_force(R_REF, GAMMA_REF, -1e-12, 0.0)
    with pytest.raises(ValueError):
        capillary.capillary_force(R_REF, GAMMA_REF, 1e-12, -1.0)