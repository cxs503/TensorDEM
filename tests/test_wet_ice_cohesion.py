def test_criterion_d_gamma_zero_is_exactly_zero():
    V = 0.05 * R_REF ** 3
    assert capillary.capillary_force(R_REF, 0.0, V, 0.0) == 0.0
    assert capillary.capillary_force(R_REF, 0.0, V, 1e-5) == 0.0
    arr = capillary.capillary_force_array(
        np.array([1e-4, 5e-4]), 0.0, np.array([V, V]), np.array([0.0, 1e-6]), 0.0
    )
    assert np.all(arr == 0.0)
    assert ice_resistance.capillary_cohesion(R_REF, 0.0, 5.0) == 0.0


def test_criterion_d_dry_cell_has_no_cohesion():
    """The many-body control: a dry assembly cannot carry tension."""
    dry = cohesion_cell.run_cohesion_cell(n_particles=200, gamma=0.0, n_pull=500, n_relax=250)
    wet = cohesion_cell.run_cohesion_cell(n_particles=200, gamma=0.3, n_pull=500, n_relax=250)
    assert abs(dry.cohesion) <= 1e-6 * max(wet.cohesion, 1e-12)
    assert wet.cohesion > 0.0


def test_criterion_d_no_sticking_means_no_aggregation():
    res = aggregation.simulate_shear_aggregation(
        n_particles=300, shear_rate=1.0, total_strain=1.0, dt_fraction=0.02,
        sticking_probability=0.0, seed=3,
    )
    assert res.n_clusters[-1] == res.n_clusters[0]
    assert res.mean_diameter[-1] == pytest.approx(2.0, abs=1e-12)


# ---------------------------------------------------------------------------
# (b) agglomeration vs Smoluchowski
# ---------------------------------------------------------------------------

def test_criterion_b_aggregation_vs_smoluchowski():
    res = aggregation.simulate_shear_aggregation(
        n_particles=400, shear_rate=1.0, total_strain=1.5, dt_fraction=0.01, seed=11
    )
    sm = aggregation.smoluchowski_shear(
        n_particles=400, volume=res.params["box"] ** 3, shear_rate=1.0,
        times=res.times, n_classes=60,
    )
    rel = np.abs(res.mean_diameter - sm["mean_diameter"]) / sm["mean_diameter"]
    late = rel[len(rel) // 2:]
    assert np.max(late) < 0.15, f"<D> deviation {np.max(late):.3f} exceeds 15 %"
    # aggregation must actually happen
    assert res.mean_diameter[-1] > 1.05


def test_aggregation_is_reproducible():
    a = aggregation.simulate_shear_aggregation(n_particles=150, total_strain=0.5, dt_fraction=0.02)
    b = aggregation.simulate_shear_aggregation(n_particles=150, total_strain=0.5, dt_fraction=0.02)
    assert np.array_equal(a.mean_diameter, b.mean_diameter)


