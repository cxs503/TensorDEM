"""Verification tests for the Hertzian restitution target of ``tensordem.dem3d``.

Two levels are asserted, and the second one is the point of the file:

* the *reference* integration in :mod:`tensordem.hertz_restitution` must be
  step-converged, must recover the elastic limit, and must reproduce the
  closed-form linear identity in the limit it is derived for;
* the *shipped solver* must agree with that reference (so the reference is not
  validated against itself) and must honour a requested restitution once
  ``hertz_restitution_verified=True`` is set.

The reported numbers are regenerated by ``scripts/verify_hertz_restitution.py``
(see ``docs/dem3d_hertz_restitution_verification.md``).
"""
from __future__ import annotations

from dataclasses import replace
import math
import unittest

from tensordem.dem3d import DEM3DConfig
from tensordem.hertz_restitution import (
    HertzImpactSpec,
    classic_zeta_from_restitution,
    hertz_impact_restitution,
    hertz_prefactor,
    hertz_restitution_bias_table,
    hertz_zeta_for_target,
    measure_solver_impact,
)

E_TARGET = 0.5


def shipped_reference(e_target: float, *, v_in: float = 1.0, steps: int = 2_000) -> float:
    """COR the *shipped* (classic-zeta) mapping produces in the reference model."""
    zeta = classic_zeta_from_restitution(e_target)
    return hertz_impact_restitution(zeta, HertzImpactSpec(v_in=v_in, steps=steps))["e"]


class HertzReferenceModelTests(unittest.TestCase):
    def test_prefactor_matches_closed_form(self) -> None:
        e_star, r_eff = 5.494505494505494e8, 0.0125
        self.assertAlmostEqual(hertz_prefactor(e_star, r_eff),
                               (4.0 / 3.0) * e_star * math.sqrt(r_eff), places=6)
        with self.assertRaises(ValueError):
            hertz_prefactor(0.0, r_eff)
        with self.assertRaises(ValueError):
            hertz_prefactor(e_star, -1.0)

    def test_zero_damping_is_elastic(self) -> None:
        result = hertz_impact_restitution(0.0)
        self.assertLess(abs(result["e"] - 1.0), 2e-4)  # O(dt^2) exit-crossing error

    def test_peak_overlap_matches_energy_identity(self) -> None:
        spec = HertzImpactSpec()
        a = spec.prefactor
        analytic = (15.0 * spec.reduced_mass * spec.v_in**2 / (16.0 * a)) ** 0.4
        self.assertAlmostEqual(spec.peak_overlap(), analytic, places=15)
        # The recoverable energy at the peak must equal the incoming kinetic energy.
        self.assertAlmostEqual((8.0 / 15.0) * a * spec.peak_overlap() ** 2.5,
                               0.5 * spec.reduced_mass * spec.v_in**2, places=15)

    def test_step_convergence(self) -> None:
        zeta = hertz_zeta_for_target(E_TARGET)["zeta_eff"]
        coarse = hertz_impact_restitution(zeta, HertzImpactSpec(steps=1_000))["e"]
        fine = hertz_impact_restitution(zeta, HertzImpactSpec(steps=4_000))["e"]
        self.assertLess(abs(fine / coarse - 1.0), 1e-3)

    def test_shipped_mapping_bias_is_reproduced(self) -> None:
        """The reference must reproduce the reported bias (16.4 % at e_target=0.5)."""
        measured = shipped_reference(E_TARGET)
        self.assertLess(abs(measured / 0.5823 - 1.0), 5e-3)

    def test_bias_grows_as_target_falls(self) -> None:
        biases = []
        for e_target in (0.9, 0.8, 0.7, 0.5, 0.3):
            measured = shipped_reference(e_target)
            biases.append(measured / e_target - 1.0)
        self.assertTrue(all(b > 0.0 for b in biases), biases)
        self.assertEqual(biases, sorted(biases), biases)

    def test_bias_is_speed_independent(self) -> None:
        """Invariance of the dimensionless problem: a scalar re-mapping suffices."""
        slow = shipped_reference(E_TARGET, v_in=0.25)
        fast = shipped_reference(E_TARGET, v_in=8.0)
        self.assertLess(abs(fast / slow - 1.0), 1e-6)

    def test_corrected_mapping_hits_requested_restitution(self) -> None:
        for e_target in (0.9, 0.7, 0.5, 0.3):
            corrected = hertz_zeta_for_target(e_target)
            self.assertGreater(corrected["zeta_eff"], corrected["zeta_classic"])
            self.assertLess(abs(corrected["zeta_eff"] / corrected["zeta_classic"] - 1.0),
                            0.75)
            measured = hertz_impact_restitution(
                corrected["zeta_eff"], HertzImpactSpec(steps=2_000))["e"]
            self.assertLess(abs(measured / e_target - 1.0), 1e-3)
        self.assertEqual(hertz_zeta_for_target(1.0)["zeta_eff"], 0.0)

    def test_bias_table_reports_both_mappings(self) -> None:
        rows = hertz_restitution_bias_table((0.5,), speeds=(1.0,), steps=1_000)
        self.assertEqual(len(rows), 1)
        row = rows[0]
        self.assertGreater(row["bias_shipped_pct"], 15.0)
        self.assertLess(abs(row["bias_corrected_pct"]), 0.5)
        self.assertGreater(row["zeta_eff"], row["zeta_classic"])

    def test_invalid_inputs_rejected(self) -> None:
        with self.assertRaises(ValueError):
            hertz_impact_restitution(-0.1)
        with self.assertRaises(ValueError):
            hertz_zeta_for_target(0.0)
        with self.assertRaises(ValueError):
            HertzImpactSpec(steps=10)
        with self.assertRaises(ValueError):
            HertzImpactSpec(v_in=0.0)


class SolverHerzRestitutionTests(unittest.TestCase):
    """The shipped ``IceDEM3D`` must match the reference and honour the target."""

    def test_config_gate_requires_hertz_law(self) -> None:
        with self.assertRaises(ValueError):
            DEM3DConfig(contact_model="linear", hertz_restitution_verified=True)
        with self.assertRaises(ValueError):
            DEM3DConfig(contact_model="hertz", hertz_restitution_verified=True,
                        contact_damping_model="absolute")
        DEM3DConfig()  # default stays untouched

    def test_solver_reproduces_reference_bias(self) -> None:
        result = measure_solver_impact(e_target=E_TARGET, verified=False)
        reference = shipped_reference(E_TARGET, v_in=1.0)
        self.assertLess(abs(result["e_measured"] / reference - 1.0), 5e-3)
        self.assertGreater(result["e_measured"] / E_TARGET - 1.0, 0.15)

    def test_solver_honours_target_with_verified_mapping(self) -> None:
        for e_target in (0.8, 0.5):
            result = measure_solver_impact(e_target=e_target, verified=True)
            self.assertLess(abs(result["e_measured"] / e_target - 1.0), 0.01,
                            msg=f"e_target={e_target} e={result['e_measured']}")

    def test_shipped_and_verified_differ_only_through_the_mapping(self) -> None:
        """Same geometry, same dt; only the damping convention changed."""
        shipped = measure_solver_impact(e_target=E_TARGET, verified=False)
        verified = measure_solver_impact(e_target=E_TARGET, verified=True)
        self.assertEqual(shipped["dt_s"], verified["dt_s"])
        self.assertGreater(shipped["e_measured"] - verified["e_measured"], 0.07)


if __name__ == "__main__":
    unittest.main()