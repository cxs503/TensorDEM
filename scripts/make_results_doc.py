#!/usr/bin/env python
"""Render the results appendix from artifacts (no hand-typed numbers)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "artifacts" / "coupling_kernel"
OUT = ROOT / "docs" / "COUPLING_KERNEL_DEM_BACKEND_RESULTS.md"


def load(name):
    path = ART / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def f(value, digits=3):
    if value is None:
        return "n/a"
    try:
        v = float(value)
    except (TypeError, ValueError):
        return str(value)
    if v == 0.0:
        return "0"
    if abs(v) < 1e-3 or abs(v) >= 1e4:
        return f"{v:.{digits}e}"
    return f"{v:.{digits}f}"


def main() -> int:
    eq, dil, con, conv, st = (load(n) for n in ("equivalence", "dilution", "conservation", "convergence", "settling"))
    lines = ["# Coupling-kernel results appendix (generated)", "",
             "Generated by `scripts/make_results_doc.py` from `artifacts/coupling_kernel/*.json`.", ""]
    if eq:
        s = eq["state"]
        lines += ["## Backend equivalence (numpy vs torch, 1000 steps, contact-rich pack)", "",
                  "| quantity | value |", "|---|---|",
                  f"| particles | {s['particles']} |",
                  f"| position relative difference | {f(s['position_relative_diff'])} |",
                  f"| velocity relative difference | {f(s['velocity_relative_diff'])} |",
                  f"| positions bitwise equal | {s['positions_bitwise_equal']} |",
                  f"| velocities bitwise equal | {s['velocities_bitwise_equal']} |",
                  f"| worst ledger relative difference | {f(eq['worst_ledger_relative_diff'])} |",
                  f"| worst ledger absolute difference [J] | {f(eq['worst_ledger_abs_diff_J'])} |",
                  f"| all criteria pass | {eq['all_pass']} |", ""]
        lines += ["| ledger channel | numpy | torch | rel. diff |", "|---|---|---|---|"]
        for key, row in eq["ledger"].items():
            lines.append(f"| {key} | {f(row['numpy'])} | {f(row['torch'])} | {f(row['relative_diff'])} |")
        lines.append("")
    if dil:
        lines += ["## Dilute single-sphere settling", "", "| quantity | value |", "|---|---|",
                  f"| steps | {dil['steps']} |", f"| physical time [s] | {f(dil['time_s'])} |",
                  f"| measured terminal velocity [m/s] | {f(dil['measured_terminal_velocity_m_s'])} |",
                  f"| Stokes terminal velocity [m/s] | {f(dil['stokes_terminal_velocity_m_s'])} |",
                  f"| Oseen terminal velocity [m/s] | {f(dil['oseen_terminal_velocity_m_s'])} |",
                  f"| particle Reynolds | {f(dil['particle_reynolds'])} |",
                  f"| integrator error vs exact | {f(dil['integrator_relative_error_vs_exact'])} |",
                  f"| error vs Stokes | {f(dil['stokes_relative_error'])} |",
                  f"| error vs Oseen | {f(dil['oseen_relative_error'])} |",
                  f"| ledger closure (relative) | {f(dil['energy_closure_relative_residual'])} |", ""]
    if con:
        lines += ["## Elastic gas conservation, 1e5 steps", "", "| quantity | value |", "|---|---|",
                  f"| steps | {con['steps']} |", f"| physical time [s] | {f(con['time_s'])} |",
                  f"| baseline mechanical [J] | {f(con['baseline_mechanical_J'])} |",
                  f"| dissipation booked [J] | {f(con['dissipated_J'])} |",
                  f"| final relative residual | {f(con['final_relative_residual'])} |",
                  f"| energy swing (relative) | {f(con['energy_swing_relative'])} |",
                  f"| secular drift per step | {f(con['secular_drift_per_step_relative'])} |", ""]
    if st:
        cd = st.get("contact_diagnostics") or {}
        lines += ["## Dense bed, real kernel, 1e5 steps (three-field ledger)", "", "| quantity | value |", "|---|---|",
                  f"| particles / steps / time [s] | 512 / {st['steps']} / {f(st['time_s'])} |",
                  f"| solid volume fraction | {f(st['solid_volume_fraction'])} |",
                  f"| mean settling velocity [m/s] | {f(st['mean_vz_m_s'])} |",
                  f"| contacts at end | {cd.get('contacts', 'n/a')} |",
                  f"| mean coordination | {f(cd.get('mean_coordination'))} |",
                  f"| max overlap / radius | {f(cd.get('max_overlap_over_radius'))} |",
                  f"| pair dashpot dissipation [J] | {f(st['ledger_summary']['dem_damping_dissipated_J'])} |",
                  f"| wall dashpot dissipation [J] | {f(st['ledger_summary']['wall_damping_dissipated_J'])} |",
                  f"| drag dissipation [J] | {f(st['ledger_summary']['drag_dissipated_J'])} |",
                  f"| closure residual (relative) | {f(st['energy_closure_relative_residual'])} |", ""]
    if conv:
        lines += ["## Timestep refinement", "", "| dt [s] | steps | relative drift |", "|---|---|---|"]
        for run in conv["runs"]:
            lines.append(f"| {f(run['dt_s'])} | {run['steps']} | {f(run['final_relative_residual'])} |")
        lines += ["", f"observed order = {f(conv['observed_order'], 2)}", ""]
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())