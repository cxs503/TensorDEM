#!/usr/bin/env python
"""Figures for the wave-ice coupling verification campaign.

Reads the merged ``metrics.json`` (produced by
``scripts/run_wave_floe_validation.py``) and writes PNGs.  No number is retyped
by hand: every plotted value comes from the JSON artefact, which is generated by
the validation code path itself.
"""
from __future__ import annotations

import json
import os
import pathlib
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

METRICS = pathlib.Path(os.environ.get("_METRICS", "artifacts/wave_floe_validation/metrics.json"))
OUT = pathlib.Path(os.environ.get("_OUT", "artifacts/wave_floe_validation/figures"))


def _save(fig, name):
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / name
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    print("wrote", path)
    return str(path)


def fig_rao(c):
    cont = sorted(c["continuum_curve"], key=lambda r: r["kL"])
    disc = sorted(c["discrete_curve"], key=lambda r: r["kL"])
    td = sorted(c["td_points"], key=lambda r: r["kL"])
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    for a, key, ref_key, title in (
            (ax[0], "rao_heave", "rao_heave", "heave RAO $|z|/A$"),
            (ax[1], "rao_pitch", "rao_pitch", "pitch RAO $|\\theta|/(kA)$")):
        a.semilogx([r["kL"] for r in cont], [r[ref_key] for r in cont],
                   "-", label="frequency domain (continuum)")
        a.semilogx([r["kL"] for r in disc], [r[ref_key] for r in disc],
                   "s", ms=3.5, mfc="none", label="frequency domain (lattice sums)")
        a.semilogx([r["kL"] for r in td], [r[key] for r in td],
                   "o", ms=5, label="time domain RK4 (solver)")
        a.axhline(1.0, color="0.6", lw=0.8, ls=":")
        a.set_xlabel("$kL$ (floe length / wavelength)")
        a.set_ylabel(title)
        a.set_title(title)
        a.grid(alpha=0.3)
        a.legend(fontsize=8)
    ax[0].annotate(f"max curve error (0.1<kL<2) = "
                   f"{100 * c['max_curve_error_heave']:.2f}%\n"
                   f"peak amplitude error = {100 * c['peak_amplitude_error']:.2f}%\n"
                   f"long-wave $|RAO-1|$ = {c['long_wave_error']:.2e}",
                   xy=(0.03, 0.62), xycoords="axes fraction", fontsize=8,
                   bbox=dict(fc="white", ec="0.7"))
    return _save(fig, "fig1_rao.png")


def fig_transmission(c):
    sweep = sorted(c["sweep"], key=lambda r: r["k0_floe_length"])
    x = [r["k0_floe_length"] for r in sweep]
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    ax.plot(x, [r["transmission"] for r in sweep], "o-", label="$|T|$")
    ax.plot(x, [r["reflection"] for r in sweep], "s--", label="$|R|$")
    ax.plot(x, [r["energy_closure"] for r in sweep], ":", label="$|T|^2+|R|^2$")
    ax.set_xlabel("$k_0 L_f$ (floe length / wavelength)")
    ax.set_ylabel("coefficient")
    ax.set_title("floe-array scattering (long-wave slab model, 12 floes)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    ax.annotate(f"max energy closure error = {c['max_energy_closure_error']:.1e}\n"
                f"transfer matrix vs closed-form slab = "
                f"{c['slab_closed_form_error']:.1e}\n"
                f"experiment comparison: WITHHELD (no data)",
                xy=(0.03, 0.05), xycoords="axes fraction", fontsize=8,
                bbox=dict(fc="white", ec="0.7"))
    return _save(fig, "fig2_transmission.png")


def fig_breakup(c):
    curve = c["stress_vs_k"]
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    ax[0].semilogx([r["k_over_kc"] for r in curve], [r["sigma"] for r in curve],
                   "-", label="floating-plate closed form")
    ax[0].axvline(1.0, color="0.6", ls=":", lw=0.8)
    ax[0].set_xlabel("$k/k_c$")
    ax[0].set_ylabel("surface bending stress [Pa], $a=0.1$ m")
    ax[0].set_title("bending stress peaks at $k_c$")
    ax[0].grid(alpha=0.3)
    ax[0].legend(fontsize=8)

    corr = c["finite_length_correction"]
    ax[1].plot([r["L_over_Lc"] for r in corr], [r["ratio"] for r in corr], "o-")
    ax[1].axhline(1.0, color="0.6", ls=":")
    ax[1].set_xlabel("$L/L_c$")
    ax[1].set_ylabel("$\\sigma_{FEM}/\\sigma_{theory}$")
    ax[1].set_title("finite-floe edge correction")
    ax[1].grid(alpha=0.3)
    ax[1].annotate(f"$H_{{crit}}$ theory = {c['theory_H_crit']:.4f} m\n"
                   f"$H_{{crit}}$ FEM    = {c['fem_H_crit']:.4f} m\n"
                   f"error = {100 * c['relative_error']:.2f}%",
                   xy=(0.40, 0.05), xycoords="axes fraction", fontsize=9,
                   bbox=dict(fc="white", ec="0.7"))
    return _save(fig, "fig3_breakup.png")


def fig_spectrum(c):
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    ax[0].loglog(c["target_omega"], c["target_psd"], "-", label="target JONSWAP")
    ax[0].loglog(c["estimate_omega"], c["estimate_psd"], "-", lw=1.0,
                 label="ensemble Welch estimate")
    ax[0].set_xlabel("$\\omega$ [rad/s]")
    ax[0].set_ylabel("$S(\\omega)$ [m$^2$s]")
    ax[0].set_title("spectral input fidelity (C4)")
    ax[0].grid(alpha=0.3, which="both")
    ax[0].legend(fontsize=8)
    fid = c["fidelity_ensemble"]
    ax[0].annotate(f"$R^2$ = {fid['r2']:.4f}\n"
                   f"$H_s$ ratio = {fid['hs_ratio']:.4f}\n"
                   f"peak period error = {100 * fid['peak_omega_error']:.2f}%",
                   xy=(0.02, 0.60), xycoords="axes fraction", fontsize=8,
                   bbox=dict(fc="white", ec="0.7"))
    res = c["resolution_study"]
    ax[1].plot([r["segment_periods"] for r in res], [r["r2"] for r in res], "o-")
    ax[1].axhline(0.95, color="r", ls=":", label="$R^2$ = 0.95 criterion")
    ax[1].set_xlabel("Welch segment length [peak periods]")
    ax[1].set_ylabel("$R^2$ vs target spectrum")
    ax[1].set_title("resolution convergence of the estimator")
    ax[1].grid(alpha=0.3)
    ax[1].legend(fontsize=8)
    return _save(fig, "fig4_spectrum.png")


def fig_energy_and_refinement(c1, c5, c6):
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    led = c5["td_energy_ledger"]
    labels = ["$W_{explicit}$", "$\\Delta E$", "$W_{dissipated}$"]
    vals = [led["work_explicit"], led["delta_energy"], led["work_dissipated"]]
    ax[0].bar(labels, vals)
    ax[0].set_ylabel("energy [J]")
    ax[0].set_title("work-energy ledger of the solver (C5)")
    ax[0].grid(alpha=0.3, axis="y")
    ax[0].annotate(f"residual = {100 * c5['td_residual_fraction']:.2f}% of the work\n"
                   f"free-decay drift = {c5['free_decay_energy_drift']:.1e}\n"
                   f"$Ec_g$ vs $\\langle pu\\rangle$ = "
                   f"{c5['wave_energy_flux']['rel_error']:.1e}",
                   xy=(0.03, 0.72), xycoords="axes fraction", fontsize=8,
                   bbox=dict(fc="white", ec="0.7"))
    rows = c6["rao_rows"]
    x = np.arange(len(rows))
    ax[1].bar(x - 0.2, [r["rao_heave_coarse"] for r in rows], 0.4,
              label=f"coarse ({c6['lattice_coarse']['n_particles']} columns)")
    ax[1].bar(x + 0.2, [r["rao_heave_fine"] for r in rows], 0.4,
              label=f"fine x2 ({c6['lattice_fine']['n_particles']} columns)")
    ax[1].set_xticks(x, [f"T={r['period']:.2f}s" for r in rows])
    ax[1].set_ylabel("heave RAO")
    ax[1].set_title(f"refinement (C6): max change {100 * c6['max_rao_change']:.2f}%")
    ax[1].grid(alpha=0.3, axis="y")
    ax[1].legend(fontsize=8)
    return _save(fig, "fig5_energy_refinement.png")


def main():
    data = json.loads(METRICS.read_text())
    c = data["criteria"]
    made = []
    if "C1_single_floe_rao" in c:
        made.append(fig_rao(c["C1_single_floe_rao"]))
    if "C2_array_transmission" in c:
        made.append(fig_transmission(c["C2_array_transmission"]))
    if "C3_wave_breakup" in c:
        made.append(fig_breakup(c["C3_wave_breakup"]))
    if "C4_spectral_input" in c:
        made.append(fig_spectrum(c["C4_spectral_input"]))
    if all(k in c for k in ("C1_single_floe_rao", "C5_energy", "C6_refinement")):
        made.append(fig_energy_and_refinement(c["C1_single_floe_rao"],
                                              c["C5_energy"], c["C6_refinement"]))
    print("figures:", len(made))
    return made


if __name__ == "__main__":
    main()