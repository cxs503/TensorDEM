"""Re-derive and re-check the ice-ridge grounding numbers after the m2983 fix.

``docs/ice_ridge_pipeline_grounding.md`` publishes numbers from
``artifacts/ridge_grounding/*.json``.  Those artifacts were generated *before*
the undrained-capacity fix of ``docs/ridge_capacity_skempton_audit.md`` and were
never regenerated, so the published subgrade sweep (``73.8 / 221.5 / 442.9 kN/m``)
was 20 % too high.  This script

1. re-executes nothing itself (run ``scripts/run_ice_ridge_grounding.py`` first),
2. re-derives every closed-form quantity from the artifacts
   (:mod:`tensordem.ridge_grounding_verification`),
3. parses the numbers quoted in the narrative page and compares them with the
   artifacts, so a stale published number is a non-zero exit status, and
4. writes ``artifacts/ridge_grounding/rederivation.json`` plus an auto-generated
   markdown table (``--markdown`` path) so no number is transcribed by hand.

Usage::

    PYTHONPATH=src python scripts/verify_ridge_grounding_rederivation.py \
        --markdown docs/ice_ridge_grounding_rederivation.md
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from tensordem.ridge_grounding_verification import (  # noqa: E402
    build_report, parse_documented_numbers, render_markdown)

ARTIFACTS = os.path.join(ROOT, "artifacts", "ridge_grounding")
DOC = os.path.join(ROOT, "docs", "ice_ridge_pipeline_grounding.md")


PAGE_HEADER = """# Ice-ridge grounding: closed-form re-derivation after the m2983 fix

Auto-generated by `scripts/verify_ridge_grounding_rederivation.py`; every number
in the table below is read from `artifacts/ridge_grounding/*.json`, so this page
cannot drift from the artifacts. Narrative page: `{doc}`.

## Why this page exists

The undrained subgrade branch of `tensordem.ridge_geotech` double-counted the
depth effect (square-footing shape factor `1.2` on a strip model) until m2983.
The fix lowered undrained capacities by 20 % (up to 44 % where both caps bound),
but the campaign artifacts of `{doc}` were **not** regenerated, so the published
soil-strength sweep was 20 % too high while no code could reproduce it. The
campaign was therefore re-executed from scratch (main case {capacity:.1f} kN/m,
{steps} steps, {particles} particles), not rescaled, and the numbers in the
narrative page were rewritten from the new artifacts.

## Method

* Reference for the subgrade: `skempton_undrained_nc(z, B)` with `z = embedment + D`
  (pipe invert), evaluated outside the spring class so the check is not
  self-referential.
* Reference for the pipe: Hetenyi infinite beam-on-Winkler closed form, for both
  the standalone FE beam and the coupled run's own moment/deflection.
* Reference for the pre-fix numbers: `legacy_undrained_nc_pre_m2983`, which must
  reproduce the old page to exactly `1.200x` (identifies the double-counted
  factor rather than merely noting a difference).
* Documentation guard: the numbers quoted in the narrative page are parsed and
  compared with the artifacts, so a stale published number becomes a red test
  (`tests/test_ice_ridge_grounding_rederivation.py`).

## Verdict table

"""

PAGE_FOOTER = """## What is still open (honest list)

* The keel-depth/width sweeps are flat to ±0.6 %, i.e. the coupled system is
  subgrade-governed at this resolution; the DEM ice side is not the capacity
  driver in the compliant-pipe case.
* The lateral limit pressure `N_p = 2 + 1.5 z/D` is still **WITHHELD**: no offline
  primary reference for this pipe-soil practice was available in the worktree, and
  the test only pins the implemented formula.
* The Cross / DNV-OS-F101 empirical ice-ridge formulas remain **WITHHELD**
  (primary text unavailable), and the Vesic squeeze comparison stays a
  DERIVED reference, not an empirical validation.
* The `--stages` calibration in this re-execution still yields an unusable
  `(c, phi)` (negative friction angle), unchanged from before the fix; the
  capacity claim does not rest on it.
* The rigid-pipe ice-side study (`sensitivity_rigid.json`) is produced by a
  different script and is *not* affected by the subgrade fix (the pipe does not
  displace, so no subgrade reaction is mobilised), but it was not regenerated in
  this ticket either.
"""

def _load(name: str) -> dict:
    path = os.path.join(ARTIFACTS, name)
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--doc", default=DOC,
                        help="narrative page whose numbers are cross-checked")
    parser.add_argument("--markdown", default=os.path.join(
        ROOT, "docs", "ice_ridge_grounding_rederivation.md"),
        help="path for the generated markdown table")
    parser.add_argument("--json", default=os.path.join(ARTIFACTS, "rederivation.json"))
    args = parser.parse_args()

    artifacts = {
        "main_case": _load("main_case.json"),
        "sensitivity": _load("sensitivity.json"),
        "rate": _load("rate_study.json"),
        "beam": _load("beam_verification.json"),
    }
    with open(args.doc, "r", encoding="utf-8") as handle:
        documented = parse_documented_numbers(handle.read())

    scenario = artifacts["main_case"]["scenario"]
    diameter = float(scenario["section"]["outer_diameter"])
    embedment = float(scenario["cover_depth"])
    report = build_report(artifacts, documented, diameter=diameter, embedment=embedment)
    report["provenance"] = {
        "doc": os.path.relpath(args.doc, ROOT),
        "artifacts": os.path.relpath(ARTIFACTS, ROOT),
        "diameter": diameter,
        "embedment": embedment,
        "generator": "scripts/run_ice_ridge_grounding.py",
        "step_budget": artifacts["main_case"]["numerics"]["steps"],
        "particles": artifacts["main_case"]["numerics"]["particles"],
    }

    with open(args.json, "w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2)
    print(f"wrote {args.json}", flush=True)

    markdown = render_markdown(report)
    print(markdown, flush=True)

    if args.markdown:
        header = PAGE_HEADER.format(
            doc=report["provenance"]["doc"],
            steps=report["provenance"]["step_budget"],
            particles=report["provenance"]["particles"],
            capacity=report["main_case_capacity_per_length"] / 1e3,
            subgrade=report["subgrade_ultimate_capacity_per_length"] / 1e3,
            verdict=report["verdict"], failures=report["failure_count"])
        with open(args.markdown, "w", encoding="utf-8") as handle:
            handle.write(header + markdown + "\n\n" + PAGE_FOOTER)
        print(f"wrote {args.markdown}", flush=True)

    if report["missing_documented_numbers"]:
        print("WARNING: doc numbers not found: "
              + ", ".join(report["missing_documented_numbers"]), flush=True)
    return 0 if report["verdict"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())