#!/usr/bin/env python3
"""Render the clear-ice campaign results as markdown, straight from the artifact.

Every number in ``docs/CLEAR_ICE_DEM_RESULTS.md`` is produced here from
``artifacts/clear_ice_dem/result.json`` -- nothing is typed by hand (the
"no hand-copied numbers" rule).  Run after ``benchmarks/clear_ice_dem.py``::

    PYTHONPATH=src python scripts/clear_ice_results_md.py \
        --artifact artifacts/clear_ice_dem/result.json \
        --out docs/CLEAR_ICE_DEM_RESULTS.md
"""

from __future__ import annotations

import argparse
import json


def fmt(value, nd=3):
    if isinstance(value, bool):
        return "yes" if value else "no"
    if value is None:
        return "n/a"
    if isinstance(value, float):
        if value != value:            # NaN
            return "n/a"
        if value != 0.0 and abs(value) < 10.0 ** (-nd):
            return f"{value:.{max(nd, 6)}f}"
        return f"{value:.{nd}f}"
    return str(value)


def table(rows: list[tuple], header: tuple) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join(["---"] * len(header)) + "|"]
    for row in rows:
        out.append("| " + " | ".join(fmt(v) for v in row) + " |")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--artifact", default="artifacts/clear_ice_dem/result.json")
    ap.add_argument("--out", default="docs/CLEAR_ICE_DEM_RESULTS.md")
    args = ap.parse_args()

    with open(args.artifact) as fh:
        r = json.load(fh)

    kin = r["floe_kinematics"]
    rq = kin["resolution_quality"]
    ctrl = rq["negative_control"]
    chains = r["force_chain_stats"]
    por = r["porosity"]
    conv = r["convergence_report"]
    traj = conv["trajectory_order"]
    sweep = conv["ensemble_dt_sweep"]
    part = conv["particle_count"]
    uq = r["uncertainty_quantification"]
    prov = r["provenance"]

    lines: list[str] = []
    lines.append("# Clear-ice floe field -- generated results tables\n")
    lines.append("Generated by `scripts/clear_ice_results_md.py` from "
                 f"`{args.artifact}` (population hash `{prov['population_hash'][:16]}...`, "
                 f"wall time {fmt(prov.get('wall_time_s'), 1)} s). Do not edit by hand.\n")

    lines.append("## Floe kinematics (deliverable)\n")
    lines.append(table([
        ("drift velocity ux", kin["drift_velocity_m_per_s"][0], "m/s"),
        ("drift velocity uy", kin["drift_velocity_m_per_s"][1], "m/s"),
        ("mean speed", kin["mean_speed_m_per_s"], "m/s"),
        ("rms speed", kin["rms_speed_m_per_s"], "m/s"),
        ("max speed", kin["max_speed_m_per_s"], "m/s"),
        ("granular temperature", kin["granular_temperature_J_per_kg"], "J/kg"),
        ("mean per-floe displacement", kin["displacement_mean_m"], "m"),
        ("p95 per-floe displacement", kin["displacement_p95_m"], "m"),
        ("rms per-floe displacement", kin["per_floe_displacement_rms_m"], "m"),
    ], ("quantity", "value", "unit")))

    lines.append("\n## Resolution quality and negative control\n")
    lines.append(table([
        ("dt used", conv["dt_used_s"], "s"),
        ("dt configured", conv["dt_configured_s"], "s"),
        ("contact time (smallest floe)", conv["contact_time_s"], "s"),
        ("dt / t_contact", conv["dt_over_contact_time"], "-"),
        ("oscillation index (resolved)", rq["oscillation_index"], "-"),
        ("HF velocity energy fraction", rq["velocity_high_frequency_fraction"], "-"),
        ("max overlap / radius", rq["max_overlap_ratio"], "-"),
        ("negative control: dt / t_contact", ctrl["dt_over_contact_time"], "-"),
        ("negative control: oscillation index", ctrl["oscillation_index"], "-"),
        ("negative control: max overlap / radius", ctrl["max_overlap_ratio"], "-"),
        ("negative control: max speed", ctrl["max_speed_m_per_s"], "m/s"),
        ("negative control diverged", ctrl["diverged"], ""),
    ], ("quantity", "value", "unit")))

    lines.append("\n## Force-chain statistics\n")
    lines.append(table([
        ("contacts sampled", chains["n_contacts"], ""),
        ("mean normal force", chains["mean_force_N"], "N"),
        ("exponential scale f0", chains["f0_exponential"], "<F_n>"),
        ("R^2 exponential tail", chains["r2_exponential_tail"], ""),
        ("power-law exponent", chains["powerlaw_exponent"], ""),
        ("R^2 power-law tail", chains["r2_powerlaw_tail"], ""),
        ("d BIC (power law - exponential)", chains["delta_BIC_powerlaw_minus_exponential"], ""),
        ("weak-contact fraction P(f<0.5)", chains["weak_contact_fraction_below_0p5"], ""),
        ("load share of f > 3", chains["load_share_above_3x_mean"], ""),
        ("tail window", "{} - {}".format(*chains["tail_window"]), "<F_n>"),
        ("Z (all)", chains["coordination"]["Z_all_mean"], ""),
        ("Z (non-rattler)", chains["coordination"]["Z_non_rattler_mean"], ""),
        ("rattler fraction", chains["coordination"]["rattler_fraction_mean"], ""),
    ], ("quantity", "value", "unit")))

    lines.append("\n## Porosity\n")
    rows = []
    for region in ("domain_mean", "feed", "jam", "wake"):
        if region in por and isinstance(por[region], dict) and "areal_mean" in por[region]:
            rows.append((region, por[region]["areal_mean"], por[region]["voronoi_mean"],
                         por[region].get("n_floes_mean", por[region].get("n_samples"))))
    lines.append(table(rows, ("region", "areal n", "voronoi n", "floes / samples")))
    lines.append(f"\nEstimator gap on the domain mean: "
                 f"{fmt(por['domain_mean']['estimator_gap'], 4)}; "
                 f"target from the config: {fmt(por['domain_mean']['target_from_config'], 3)}.\n")

    lines.append("## Convergence (C1 / C4)\n")
    lines.append(table([
        (f"... t = {d:.5f} s".replace("...", "dt"), e, o)
        for d, e, o in zip(traj["dt_levels_s"], traj["l2_error_m"],
                           traj["observed_order_consecutive"] + [None])
    ], ("step size", "L2 position error (m)", "consecutive order")))
    lines.append(f"\nOrder by least-squares fit: **{fmt(traj['observed_order_fit'], 3)}** "
                 f"(criterion: >= 1).\n")

    lines.append("\nEnsemble step-size sweep (reported statistics):\n")
    lines.append(table([
        (row["dt_s"], row["dt_over_tc"], row["ambient_porosity"], row["jam_porosity"],
         row["Z"], row["f0"], row["r2"], row["wall_load_N"], row["max_overlap_ratio"])
        for row in sweep["rows"]
    ], ("dt (s)", "dt/t_c", "n domain", "n jam", "Z", "f0", "R^2", "hull load (N)", "overlap/r")))
    lines.append("\nPer-metric observed order and relative change coarse->fine:\n")
    lines.append(table([
        (key, val["relative_change_vs_finest"], val["observed_order"])
        for key, val in sweep["metrics"].items()
    ], ("metric", "relative change", "observed order")))

    lines.append("\nParticle-count study:\n")
    lines.append(table([
        (row["n_floes"], row["area_m2"], row["ambient_porosity"], row["ambient_voronoi"],
         row["jam_porosity"], row["Z"], row["f0"], row["r2"], row["wall_load_N"],
         row["n_contacts"])
        for row in part["rows"]
    ], ("N", "area (m2)", "n domain", "n voronoi", "n jam", "Z", "f0", "R^2",
        "hull load (N)", "contacts")))

    lines.append("\n## Uncertainty quantification (one-at-a-time, +-20 %)\n")
    lines.append(table([
        (row["parameter"], row["value"],
         row["metrics"]["ambient_porosity"], row["metrics"]["Z"],
         row["metrics"]["f0"], row["metrics"]["r2_exponential"],
         row["metrics"]["wall_load_N"], row["metrics"]["mean_speed"],
         row["relative_change"]["wall_load_N"])
        for row in uq["rows"]
    ], ("parameter", "value", "n domain", "Z", "f0", "R^2", "hull load (N)",
        "mean speed", "rel change load")))
    lines.append("\nSummary (baseline, spread over all variations, seed scatter):\n")
    lines.append(table([
        (key, val["baseline"], val["min"], val["max"],
         val["max_abs_relative_change"], val["seed_scatter_relative"])
        for key, val in uq["summary"].items()
    ], ("metric", "baseline", "min", "max", "max rel change", "seed scatter")))

    lines.append("\n## Hull load and momentum ledger\n")
    wl = conv["wall_load"]
    lines.append(table([
        ("ice load on hull face", wl["ice_load_on_hull_N"], "N"),
        ("load per metre of face", wl["per_metre_face_N_per_m"], "N/m"),
        ("load standard deviation", wl["ice_load_std_N"], "N"),
        ("total water drag", wl["total_drag_N"], "N"),
        ("momentum residual |wall+drag|/|drag|", wl["momentum_residual_relative"], "-"),
        ("mean kinetic energy", wl["kinetic_energy_mean_J"], "J"),
    ], ("quantity", "value", "unit")))

    lines.append("\n## Criterion verdicts\n")
    lines.append(table([
        ("C1 kinematics", r["floe_kinematics"]["check"]["deliverable"],
         f"order {fmt(traj['observed_order_fit'], 2)}, "
         f"osc {fmt(rq['oscillation_index'], 4)}, "
         f"overlap/r {fmt(rq['max_overlap_ratio'], 5)}"),
        ("C2 force chain", chains["check"]["pass"],
         f"R^2 {fmt(chains['check']['r2_exponential_tail'], 3)} > 0.9"),
        ("C3 porosity", por["check"]["pass"],
         f"domain areal {fmt(por['check']['domain_mean_areal'], 3)}, "
         f"voronoi {fmt(por['check']['domain_mean_voronoi'], 3)} in [0.30, 0.45]"),
        ("C4 maturity", r["convergence_report"]["checks"]["contract_checks_pass"],
         f"{len(r['convergence_report']['checks']['uq_parameters'])} UQ parameters, "
         f"contract {r['convergence_report']['checks']['contract_version']}"),
    ], ("criterion", "pass", "evidence")))

    text = "\n".join(lines) + "\n"
    with open(args.out, "w") as fh:
        fh.write(text)
    print(text[:2000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())