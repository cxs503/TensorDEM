"""Emit markdown tables + figures index for the P54-W3-N01 report.

Numbers are read straight from ``artifacts/salinity_strength/results.json``
(zero hand-copying: every digit in TABLES.md comes from the JSON the runner
produced from the model).

Run: python scripts/emit_salinity_tables.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "artifacts" / "salinity_strength" / "results.json"
OUT = ROOT / "docs" / "salinity-strength-myi-fyi" / "TABLES.md"


def main() -> int:
    r = json.loads(RES.read_text())
    L: list[str] = []
    A = L.append

    A("# P54-W3-N01 -- generated result tables")
    A("")
    A("> Generated by `scripts/emit_salinity_tables.py` from "
      "`artifacts/salinity_strength/results.json`. Do not edit by hand.")
    A("")
    A(f"Module: `{r['module']}` · Python {r['environment']['python']} · "
      f"numpy {r['environment']['numpy']} · {r['environment']['machine']}")
    A("")

    A("## 1. Parameter table with item-by-item provenance")
    A("")
    A("| parameter | value | range | unit | source |")
    A("|---|---|---|---|---|")
    for name, e in r["parameter_provenance"].items():
        rng = e.get("range")
        rng_s = f"{rng[0]:g} – {rng[1]:g}" if rng else "—"
        val = e["value"]
        val_s = f"{val:.4g}"
        A(f"| `{name}` | {val_s} | {rng_s} | {e.get('unit','—')} | {e['source']} |")
    A("")

    A("## 2. Criterion verdicts")
    A("")
    A("| criterion | model value | reference / basis | deviation | threshold | status |")
    A("|---|---|---|---|---|---|")
    c = r["criteria"]
    a = c["a_brine_volume_vs_literature"]
    A(f"| (a) nu_b at T=-10 °C, S=5 ppt | {a['value']:.5f} | {a['reference']:.4f} "
      f"(Timco & O'Brien 1994 nomograph) | {a['relative_difference']*100:.2f}% | <2% | **{a['status']}** |")
    b = c["b_fyi_strength_vs_literature"]
    A(f"| (b) sigma_c FYI at T=-10 °C, S=5 ppt | {b['value_pa']/1e6:.3f} MPa | "
      f"{b['reference_pa']/1e6:.2f} MPa (Timco & Frederking 1984) | "
      f"{b['relative_difference']*100:.2f}% | <10% | **{b['status']}** |")
    cc = c["c_myi_strength_ordering"]
    A(f"| (c) MYI vs FYI ordering | sigma_c_MY={cc['value_pa']/1e6:.3f} MPa, "
      f"sigma_c_FY={cc['fyi_value_pa']/1e6:.3f} MPa, ratio {cc['ratio']:.3f} | "
      "path (3): MY > FY | literal criterion demands MY < FY | — | "
      f"**{cc['status']}** (literal {cc['literal_status']}) |")
    d = c["d_temperature_monotonicity"]
    A(f"| (d) T = -40 → 0 °C monotone | {d['levels']} levels | Spearman rho | "
      f"{d['spearman_rho']:.1f} | \\|rho\\|=1, >=10 levels | **{d['status']}** |")
    e = c["e_salinity_monotonicity"]
    A(f"| (e) S = 0 → 15 ppt monotone | {e['levels']} levels | Spearman rho | "
      f"{e['spearman_rho']:.1f} | \\|rho\\|=1, >=10 levels | **{e['status']}** |")
    f = c["f_negative_controls"]
    A(f"| (f) negative controls | sigma(S=0)={f['sigma_at_S0_pa']/1e6:.3f} MPa, "
      f"nu_b(S=0)={f['nu_b_at_S0']:.3f}, sigma(T=0)={f['sigma_at_freezing_point_pa']/1e6:.3f} MPa | "
      f"sigma_0={f['sigma0_pa']/1e6:.3f} MPa | exact | 0 / 0 / 0 | **{f['status']}** |")
    g = c["g_pytest_and_artifacts"]
    A(f"| (g) engineering delivery | {g['pytest_cases']} pytest cases in `{g['pytest_file']}` | "
      f"results.json + figures + this document | — | >=15 cases | **{g['status']}** |")
    A("")

    my = r["myi_vs_fyi"]
    A("## 2b. MYI vs FYI decomposition at T = -10 degC")
    A("")
    A("| quantity | value |")
    A("|---|---|")
    A(f"| FYI (S = {r['ice_class_default_salinity_ppt']['FY']:g} ppt) | {my['fyi_sigma_c_pa']/1e6:.4f} MPa |")
    A(f"| MYI typical (S = {r['ice_class_default_salinity_ppt']['MY']:g} ppt, kappa) | "
      f"{my['myi_typical_sigma_c_pa']/1e6:.4f} MPa (ratio {my['myi_typical_ratio']:.4f}) |")
    A(f"| MYI at equal S (kappa only) | {my['myi_equal_salinity_sigma_c_pa']/1e6:.4f} MPa "
      f"(ratio {my['myi_equal_salinity_ratio']:.4f}) |")
    A(f"| -> desalination contribution | x{my['decomposition']['desalination_contribution']:.4f} |")
    A(f"| -> pore-structure contribution | x{my['decomposition']['pore_structure_contribution']:.4f} |")
    A("")

    A("## 3. Strength versus temperature (FYI, S = 5 ppt, 17 levels)")
    A("")
    A("| T [°C] | S_b [ppt] | nu_b [-] | sigma_c [MPa] |")
    A("|---|---|---|---|")
    for row in r["temperature_scan_fy_s5"]:
        A(f"| {row['temperature_c']:.2f} | {row['brine_salinity_ppt']:.2f} | "
          f"{row['brine_volume_fraction']:.4f} | {row['sigma_c_pa']/1e6:.4f} |")
    A("")

    A("## 4. Strength versus salinity (FYI, T = -10 °C, 16 levels)")
    A("")
    A("| S [ppt] | nu_b [-] | sigma_c [MPa] |")
    A("|---|---|---|")
    for row in r["salinity_scan_fy_t10"]:
        A(f"| {row['salinity_ppt']:.2f} | {row['brine_volume_fraction']:.4f} | "
          f"{row['sigma_c_pa']/1e6:.4f} |")
    A("")

    A("## 5. Monte-Carlo uncertainty (5 / 50 / 95 percentiles, 20 000 samples)")
    A("")
    A("| T [°C] | class | S [ppt] | deterministic [MPa] | p05 [MPa] | p50 [MPa] | p95 [MPa] | std [MPa] |")
    A("|---|---|---|---|---|---|---|---|")
    for m in r["monte_carlo"]:
        A(f"| {m['temperature_c']:.1f} | {m['ice_class']} | {m['bulk_salinity_ppt']:.1f} | "
          f"{m['deterministic_sigma_c_pa']/1e6:.3f} | {m['p05_pa']/1e6:.3f} | "
          f"{m['p50_pa']/1e6:.3f} | {m['p95_pa']/1e6:.3f} | {m['std_pa']/1e6:.3f} |")
    A("")

    A("## 6. Literature comparison")
    A("")
    A("| point | source | kind | model value | reference | verdict |")
    A("|---|---|---|---|---|---|")
    for row in r["literature_comparison"]:
        mv = row.get("model_value")
        mv_s = f"{mv:.5f}" if isinstance(mv, float) and mv < 1 else (
            f"{mv/1e6:.3f} MPa" if isinstance(mv, float) else "—")
        if "sigma_c_range_pa" in row:
            mv_s = (f"FY {row['model_value_pa_fy']/1e6:.3f} / "
                    f"MY(typ) {row['model_value_pa_my_typical']/1e6:.3f} MPa")
        ref = row.get("nu_b_ref", row.get("sigma_c_ref_pa", row.get("sigma_c_range_pa")))
        ref_s = f"{ref:.4f}" if isinstance(ref, float) and ref < 1 else (
            f"{ref/1e6:.3f} MPa" if isinstance(ref, float) else
            f"[{ref[0]/1e6:.1f}, {ref[1]/1e6:.1f}] MPa")
        A(f"| {row['label']} | {row['source']} | {row['kind']} | {mv_s} | {ref_s} | {row['verdict']} |")
    A("")

    A("## 7. Figures (sha256 in results.json)")
    A("")
    for fig in r.get("figures", []):
        A(f"- `{Path(fig['path']).name}` — sha256 `{fig['sha256'][:16]}…`")
    A("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())