#!/usr/bin/env python3
"""Render the campaign measurement tables from the JSON (no hand-copied numbers)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "artifacts/adhesion-contact-campaign/campaign_metrics.json").read_text())
OUT = ROOT / "docs/adhesion-contact-verification/MEASUREMENTS.md"


def fmt(x, digits=4):
    if isinstance(x, float):
        if x != x or x in (float("inf"), float("-inf")):
            return str(x)
        if x == 0.0:
            return "0"
        if abs(x) < 1e-3 or abs(x) >= 1e5:
            return f"{x:.{digits}e}"
        return f"{x:.{digits}g}"
    return str(x)


lines = []
w = lines.append
w("# Campaign measurements (auto-generated)\n")
w("Generated by `scripts/render_adhesion_campaign_docs.py` from")
w("`artifacts/adhesion-contact-campaign/campaign_metrics.json`.")
w("Do not edit by hand: re-run the campaign and re-render instead.\n")
w(f"- mission: {DATA['mission']} (id {DATA['mission_id']}), repo {DATA['repo']}")
w(f"- generated (UTC): {DATA['generated_at_utc']}, runtime {DATA['runtime_seconds']} s")
w(f"- overall status: **{DATA['overall_status']}**\n")

w("## Acceptance criteria\n")
w("| criterion | target | measured | status |")
w("|---|---|---|---|")
c = DATA["criteria"]
w(f"| C1 pull-off force | < 1 % | worst rel. error {fmt(c['C1_pull_off_vs_1.5pi_gamma_R']['worst_rel_error'])} | {c['C1_pull_off_vs_1.5pi_gamma_R']['status']} |")
w(f"| C2 F=0 contact radius | < 1 % | worst rel. error {fmt(c['C2_zero_load_radius_vs_analytic']['worst_rel_error'])} | {c['C2_zero_load_radius_vs_analytic']['status']} |")
c3 = c["C3_liquid_bridge_vs_young_laplace"]
w(f"| C3 bridge vs Young-Laplace | < 5 % at >= 3 points | {c3['points_within_5pct']}/{c3['converged_points']} points within 5 %, best {fmt(100 * c3['best_relative_difference'])} % | {c3['status']} |")
w(f"| C4 gamma floor vs Hertz | < 1e-9 | worst rel. error {fmt(c['C4_gamma_floor_vs_hertz_mindlin']['worst_rel_error'])} | {c['C4_gamma_floor_vs_hertz_mindlin']['status']} |")
c5 = c["C5_superquadric_vs_clump"]
w(f"| C5 superquadric vs clump | <= 5 % for >= 3 shapes | {c5['shapes_within_5pct_at_best_budget']}/{c5['shapes']} shapes at {max(c5['budgets'])} requested spheres | {c5['status']} |")
c6 = c["C6_energy_audit"]
w(f"| C6 energy audit | closure < 2 % | W/(pi gamma a_c^2) = {fmt(c6['universal_ratio_mean'])} (analytic 0.6), spread {fmt(c6['ratio_spread_across_parameter_sets'])}, impl. closure {fmt(c6['implementation_closure_error'])} | {c6['status']} |")
w(f"| C7 pytest | >= 15 tests | {c['C7_pytest']['tests_passing']} tests green | {c['C7_pytest']['status']} |")
w("")

w("## C1/C2/C4 parameter sets\n")
w("| set | R* [m] | E* [Pa] | K [Pa] | gamma [J/m2] | a_c [m] | a_p [m] | F_pull-off [N] | C1 rel | C2 rel | C4 rel |")
w("|---|---|---|---|---|---|---|---|---|---|---|")
for r in DATA["parameter_sets"]:
    w(f"| {r['name']} | {fmt(r['R_star'])} | {fmt(r['E_star'])} | {fmt(r['K'])} | {fmt(r['gamma'])} | "
      f"{fmt(r['a_c'])} | {fmt(r['a_p'])} | {fmt(r['pull_off_analytic'])} | {fmt(r['c1_rel_error'])} | "
      f"{fmt(r['c2_rel_error'])} | {fmt(r['c4_rel_error'])} |")
w("")

w("## C3 liquid bridge: closed form vs exact Young-Laplace\n")
w("| V/R^3 | h/R | theta [deg] | converged | residual | F_exact [N] | F_closed [N] | rel. diff | first-integral gap |")
w("|---|---|---|---|---|---|---|---|---|")
for r in DATA["liquid_bridge_table"]:
    w(f"| {fmt(r['V_over_R3'])} | {fmt(r['h_over_R'])} | {fmt(r['theta_deg'], 3)} | {r['converged']} | "
      f"{fmt(r['residual'])} | {fmt(r['force_exact'])} | {fmt(r['force_closed'])} | "
      f"{fmt(100 * r['relative_difference']) if r['relative_difference'] == r['relative_difference'] else 'nan'} % | "
      f"{fmt(r['first_integral_rel_gap']) if r['converged'] else 'n/a'} |")
w("")

w("## C5 superquadric vs sphere clump\n")
w("| n1 | n2 | a | b | c | requested spheres | used spheres | mean error / R_eq | max error / R_eq | max normal dev [deg] |")
w("|---|---|---|---|---|---|---|---|---|---|")
for r in DATA["superquadric_table"]:
    w(f"| {fmt(r['n1'], 3)} | {fmt(r['n2'], 3)} | {fmt(r['a'], 3)} | {fmt(r['b'], 3)} | {fmt(r['c'], 3)} | "
      f"{r['requested_spheres']} | {r['n_clump_spheres']} | {fmt(r['mean_error_over_R_equiv'])} | "
      f"{fmt(r['max_error_over_R_equiv'])} | {fmt(r['max_normal_deviation_deg'], 3)} |")
w("")

w("## C6 separation-work audit\n")
w("| set | W_sep [J] | pi gamma a_c^2 [J] | W/(pi gamma a_c^2) | W/(4 pi gamma R*^2) | 0.15 (a_c/R*)^2 | impl. closure |")
w("|---|---|---|---|---|---|---|")
for r in DATA["energy_audit_table"]:
    w(f"| {r['name']} | {fmt(r['work_separation'])} | {fmt(r['surface_energy_pi_gamma_ac2'])} | "
      f"{fmt(r['ratio_to_contact_area'])} | {fmt(r['ratio_to_free_sphere_4pi_gamma_R2'])} | "
      f"{fmt(r['analytic_scaling_0.15_ac_over_R_squared'])} | {fmt(r['implementation_closure_error'])} |")
w("")

w("## Figures\n")
for f in DATA["figures"]:
    w(f"- `{f}`")
w("")

OUT.write_text("\n".join(lines) + "\n")
print("wrote", OUT)