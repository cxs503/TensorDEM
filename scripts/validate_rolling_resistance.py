"""Validate the rolling-resistance contact laws against analytical references.

Three studies are run with an independent rigid-body integration of a single
sphere on an inclined plane (``tensordem.rolling_resistance``):

A. **Acceleration parity** -- for supercritical inclines the simulated downhill
   acceleration is compared with the closed-form pure-rolling result
   ``a = g (sin t - mu_r cos t) / (1 + I/mR^2)``.
B. **Static threshold** -- the incline angle at which the sphere starts to
   move is compared with ``theta_c = arctan(mu_r)`` for a grid of ``mu_r``.
C. **Model character** -- CDT, viscous and EPSD branches compared on the same
   subcritical/supercritical setups, including the creep that the memoryless
   models develop because they have no static branch.

Outputs (JSON, CSV and PNG) are written under ``--output``; all reported numbers
in docs/artifacts are generated by this script, never by hand.

Example:
    python scripts/validate_rolling_resistance.py
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import platform
import sys
from pathlib import Path
from typing import Any, Sequence

import torch

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from tensordem.rolling_resistance import (
    MODELS,
    RollingResistanceConfig,
    SphereInclineConfig,
    critical_incline_angle_deg,
    fit_acceleration,
    incline_rolling_acceleration,
    incline_sliding_acceleration,
    pure_rolling_feasible,
    rolling_resistance_torque,
    simulate_sphere_on_incline,
)

DT = 1.0e-4
K_N = 2.0e4
RADIUS = 0.01
DURATION = 0.10
SETTLE = 0.03
DRIFT_TOLERANCE_RADII = 1e-3  # a displacement of 0.001 R counts as "at rest"


def _k_r(mu_r: float, *, k_n: float = K_N, radius: float = RADIUS) -> float:
    return 2.25 * mu_r * k_n * radius ** 2


def _epsd(mu_r: float) -> RollingResistanceConfig:
    return RollingResistanceConfig(model="epsd", mu_r=mu_r, k_r=_k_r(mu_r))


def _harness() -> SphereInclineConfig:
    return SphereInclineConfig(radius=RADIUS, k_n=K_N, dt=DT)


def _run(angles: Sequence[float], rolling: RollingResistanceConfig) -> dict[str, Any]:
    return simulate_sphere_on_incline(
        angles, rolling, config=_harness(), duration=DURATION, settle_time=SETTLE
    )


# ----------------------------------------------------------------------
# A. Acceleration parity (rolling and sliding regimes)
# ----------------------------------------------------------------------

SLIDE_MU = 0.9          # sliding friction coefficient used by the harness
MOTION_TOL_ACCEL = 1e-3  # m/s^2: late-window acceleration that counts as motion
THRESH_DURATION = 0.12
THRESH_SETTLE = 0.06


def study_acceleration(mu_r_values: Sequence[float]) -> list[dict[str, Any]]:
    """Compare simulated and analytical downhill acceleration.

    Two analytical references are used, selected by the friction-cone condition
    of :func:`tensordem.rolling_resistance.pure_rolling_feasible`:

    * pure rolling: ``a = g(sin t - mu_r cos t)/(1 + I/mR^2)``
    * steady sliding: ``a = g(sin t - mu cos t)`` with ``mu = SLIDE_MU``

    Inclines below the critical angle are reported separately (the analytical
    rolling acceleration is negative there, i.e. the sphere is at rest and the
    formula is not a motion reference).
    """
    rows: list[dict[str, Any]] = []
    for mu_r in mu_r_values:
        theta_c = critical_incline_angle_deg(mu_r)
        angles = sorted({
            1.25 * theta_c, 1.5 * theta_c, 2.0 * theta_c,
            max(3.0 * theta_c, 8.0), 12.0, 18.0,
        })
        result = _run(angles, _epsd(mu_r))
        accel, r_squared = fit_acceleration(result)
        for index, theta in enumerate(angles):
            if theta <= theta_c:
                continue
            rolling_ok = pure_rolling_feasible(theta, mu_r, SLIDE_MU)
            analytic = (
                incline_rolling_acceleration(theta, mu_r) if rolling_ok
                else incline_sliding_acceleration(theta, SLIDE_MU)
            )
            simulated = float(accel[index])
            rows.append(
                {
                    "mu_r": mu_r,
                    "theta_deg": theta,
                    "theta_over_theta_c": theta / theta_c,
                    "regime": "rolling" if rolling_ok else "sliding",
                    "a_simulated_m_s2": simulated,
                    "a_analytic_m_s2": analytic,
                    "relative_error": abs(simulated - analytic) / analytic,
                    "comparable": bool(analytic >= 0.05),
                    "fit_r_squared": float(r_squared[index]),
                    "contact_slip_ratio": float(
                        (result["slip_velocity"][-1, index]).abs()
                        / result["v"][-1, index].abs().clamp_min(1e-30)
                    ),
                    "omega_radius_over_v": float(
                        result["omega"][-1, index] * RADIUS / result["v"][-1, index]
                    ),
                }
            )
    return rows


# ----------------------------------------------------------------------
# B. Static threshold vs arctan(mu_r)
# ----------------------------------------------------------------------

def _displacement(result: dict[str, Any], column: int) -> float:
    return abs(float(result["x"][-1, column]))


def _late_motion(angles: Sequence[float], rolling: RollingResistanceConfig):
    """Late-window acceleration for a batch of angles (the motion detector)."""
    result = simulate_sphere_on_incline(
        angles, rolling, config=_harness(),
        duration=THRESH_DURATION, settle_time=THRESH_SETTLE,
    )
    accel, r_squared = fit_acceleration(result)
    return result, accel, r_squared


def study_threshold(mu_r_values: Sequence[float], *, grid_half_width: float = 0.10,
                    grid_points: int = 9) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Locate the static/rolling transition on a bracketing angle grid.

    A column counts as moving when its late-window acceleration exceeds
    ``MOTION_TOL_ACCEL``; the undamped rolling oscillation of a resting contact
    produces a residual velocity but no sustained acceleration, so this detector
    is sharper than a displacement threshold.
    """
    rows: list[dict[str, Any]] = []
    summary: dict[str, Any] = {}
    for mu_r in mu_r_values:
        theta_c = critical_incline_angle_deg(mu_r)
        angles = [
            theta_c * (1.0 - grid_half_width + 2.0 * grid_half_width * i / (grid_points - 1))
            for i in range(grid_points)
        ]
        result, accel, r_squared = _late_motion(angles, _epsd(mu_r))
        measured = None
        for index, theta in enumerate(angles):
            acceleration = float(accel[index])
            moved = acceleration > MOTION_TOL_ACCEL
            rows.append(
                {
                    "mu_r": mu_r,
                    "theta_deg": theta,
                    "theta_c_analytic_deg": theta_c,
                    "a_late_m_s2": acceleration,
                    "a_analytic_m_s2": incline_rolling_acceleration(theta, mu_r),
                    "fit_r_squared": float(r_squared[index]),
                    "displacement_m": _displacement(result, index),
                    "moved": int(moved),
                }
            )
            if moved and measured is None and index > 0:
                measured = 0.5 * (theta + angles[index - 1])
        cell = angles[1] - angles[0]
        summary[str(mu_r)] = {
            "theta_c_analytic_deg": theta_c,
            "theta_transition_measured_deg": measured,
            "grid_cell_deg": cell,
            "relative_error": (abs(measured - theta_c) / theta_c if measured else None),
            "within_one_grid_cell": (
                measured is not None and abs(measured - theta_c) <= cell
            ),
        }
    return rows, summary


def bisect_threshold(mu_r: float, *, iterations: int = 6,
                     half_width: float = 0.15) -> list[dict[str, Any]]:
    """Refine the transition angle for one ``mu_r`` by bisection."""
    theta_c = critical_incline_angle_deg(mu_r)
    low = theta_c * (1.0 - half_width)
    high = theta_c * (1.0 + half_width)
    trace: list[dict[str, Any]] = []
    for step in range(iterations):
        mid = 0.5 * (low + high)
        _, accel, _ = _late_motion([mid], _epsd(mu_r))
        acceleration = float(accel[0])
        moved = acceleration > MOTION_TOL_ACCEL
        trace.append(
            {
                "iteration": step,
                "theta_deg": mid,
                "a_late_m_s2": acceleration,
                "moved": int(moved),
            }
        )
        if moved:
            high = mid
        else:
            low = mid
    measured = 0.5 * (low + high)
    trace.append(
        {
            "iteration": iterations,
            "result": "transition",
            "theta_deg": measured,
            "theta_c_analytic_deg": theta_c,
            "relative_error": abs(measured - theta_c) / theta_c,
        }
    )
    return trace


# ----------------------------------------------------------------------
# C. Model character on the same setup
# ----------------------------------------------------------------------

def _model_config(model: str, mu_r: float) -> RollingResistanceConfig:
    return (
        RollingResistanceConfig(model=model, mu_r=mu_r, k_r=_k_r(mu_r))
        if model == "epsd"
        else RollingResistanceConfig(model=model, mu_r=mu_r)
    )


def study_models(mu_r: float) -> list[dict[str, Any]]:
    """Same incline, three models: only EPSD can hold a static contact."""
    theta_c = critical_incline_angle_deg(mu_r)
    cases = {"subcritical": 0.85 * theta_c, "supercritical": 1.5 * theta_c}
    rows: list[dict[str, Any]] = []
    for case, theta in cases.items():
        analytic = incline_rolling_acceleration(theta, mu_r)
        for model in MODELS:
            result, accel, r_squared = _late_motion([theta], _model_config(model, mu_r))
            rows.append(
                {
                    "case": case,
                    "model": model,
                    "theta_deg": theta,
                    "theta_over_theta_c": theta / theta_c,
                    "a_late_m_s2": float(accel[0]),
                    "a_analytic_m_s2": analytic if case == "supercritical" else None,
                    "fit_r_squared": float(r_squared[0]),
                    "displacement_over_radius": _displacement(result, 0) / RADIUS,
                    "end_speed_m_s": float(result["v"][-1, 0]),
                }
            )
    return rows


def study_torque_laws(mu_r: float) -> list[dict[str, Any]]:
    """Law-level characteristic curves: |M| versus relative rolling speed."""
    f_n = torch.tensor([1.5], dtype=torch.float64)
    r_eff = torch.tensor([RADIUS], dtype=torch.float64)
    limit = mu_r * float(f_n) * RADIUS
    rows: list[dict[str, Any]] = []
    for speed in (0.05, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0):
        omega = torch.tensor([[0.0, 0.0, -speed]], dtype=torch.float64)
        row: dict[str, Any] = {"omega_rad_s": speed, "limit_Nm": limit}
        for model in MODELS:
            config = (
                RollingResistanceConfig(model=model, mu_r=mu_r, k_r=_k_r(mu_r))
                if model == "epsd"
                else RollingResistanceConfig(model=model, mu_r=mu_r)
            )
            state = torch.zeros(1, 3, dtype=torch.float64)
            # 400 steps of prescribed spin: EPSD reaches its plastic plateau.
            magnitude = 0.0
            for _ in range(400):
                torque, state = rolling_resistance_torque(
                    omega, f_n, r_eff, config, torque_state=state, dt=1e-4
                )
                magnitude = float(torque.norm())
            row[model] = magnitude
        rows.append(row)
    return rows


# ----------------------------------------------------------------------
# Representative time history
# ----------------------------------------------------------------------

def history_rows(mu_r: float, theta_deg: float) -> list[dict[str, Any]]:
    result = simulate_sphere_on_incline(
        [theta_deg], _epsd(mu_r), config=_harness(),
        duration=DURATION, settle_time=0.0,
    )
    rows = []
    stride = max(1, result["time"].numel() // 200)
    for index in range(0, result["time"].numel(), stride):
        rows.append(
            {
                "time_s": float(result["time"][index]),
                "speed_m_s": float(result["v"][index, 0]),
                "spin_rad_s": float(result["omega"][index, 0]),
                "slide_velocity_m_s": float(result["slip_velocity"][index, 0]),
                "normal_force_N": float(result["normal_force"][index, 0]),
                "rolling_torque_Nm": float(result["torque"][index, 0]),
                "displacement_m": float(result["x"][index, 0]),
            }
        )
    return rows


# ----------------------------------------------------------------------
# Figures and serialisation
# ----------------------------------------------------------------------

def make_figures(output: Path, *, accel_rows: list[dict[str, Any]],
                 threshold_rows: list[dict[str, Any]], threshold_summary: dict[str, Any],
                 torque_rows: list[dict[str, Any]], history: list[dict[str, Any]],
                 mu_r: float) -> list[str]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    produced: list[str] = []

    # 1. Law-level characteristic curves.
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    speeds = [row["omega_rad_s"] for row in torque_rows]
    for model, style in (("cdt", "o-"), ("viscous", "s--"), ("epsd", "^-")):
        ax.plot(speeds, [row[model] for row in torque_rows], style, label=model.upper())
    ax.axhline(
        torque_rows[0]["limit_Nm"], color="k", ls=":", lw=1.0,
        label=r"$\mu_r |F_n| R$",
    )
    ax.set_xscale("log")
    ax.set_xlabel(r"relative rolling speed $|\omega|\ \mathrm{[rad/s]}$")
    ax.set_ylabel(r"|rolling torque| [N$\cdot$m]")
    ax.set_title(f"Rolling-resistance models ($\\mu_r$={mu_r}, $|F_n|$=1.5 N)")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    path = output / "fig_torque_laws.png"
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
    produced.append(path.name)

    # 2. Acceleration parity.
    fig, ax = plt.subplots(figsize=(5.6, 5.0))
    analytic = [row["a_analytic_m_s2"] for row in accel_rows]
    simulated = [row["a_simulated_m_s2"] for row in accel_rows]
    ax.plot(analytic, simulated, "o", ms=5, label="EPSD simulation")
    band = [0.0, max(analytic) * 1.05]
    ax.plot(band, band, "k-", lw=1.0, label="1:1")
    ax.plot(band, [b * 1.03 for b in band], "k--", lw=0.8, label=r"$\pm3\%$")
    ax.plot(band, [b * 0.97 for b in band], "k--", lw=0.8)
    ax.set_xlabel(r"analytic $a=g(\sin\theta-\mu_r\cos\theta)/(1+I/mR^2)$ [m/s$^2$]")
    ax.set_ylabel(r"simulated $a$ [m/s$^2$]")
    ax.set_title("Rolling acceleration parity on the incline")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    path = output / "fig_acceleration_parity.png"
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
    produced.append(path.name)

    # 3. Static threshold.
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    mus = sorted({row["mu_r"] for row in threshold_rows})
    for mu in mus:
        subset = [row for row in threshold_rows if row["mu_r"] == mu]
        ax.plot(
            [row["theta_deg"] for row in subset],
            [row["displacement_m"] / RADIUS for row in subset],
            "o-", ms=3.5, lw=1.0, label=f"$\\mu_r$={mu}",
        )
    ax.set_yscale("log")
    ax.set_xlabel(r"incline angle $\theta$ [deg]")
    ax.set_ylabel(r"displacement after 0.1 s [$R$]")
    ax.set_title("Static-to-rolling transition (EPSD)")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8)
    path = output / "fig_threshold.png"
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
    produced.append(path.name)

    # 4. Representative history.
    fig, axes = plt.subplots(3, 1, figsize=(6.4, 6.4), sharex=True)
    times = [row["time_s"] for row in history]
    axes[0].plot(times, [row["speed_m_s"] for row in history], label="speed $v$")
    axes[0].plot(times, [-row["spin_rad_s"] * RADIUS for row in history],
                 "--", label=r"$-\omega R$ (pure rolling)")
    axes[0].set_ylabel("m/s")
    axes[0].legend(fontsize=8)
    axes[1].plot(times, [row["slide_velocity_m_s"] for row in history], color="C2")
    axes[1].set_ylabel("contact slip [m/s]")
    axes[2].plot(times, [row["rolling_torque_Nm"] for row in history], color="C3")
    axes[2].set_ylabel(r"$M_r$ [N$\cdot$m]")
    axes[2].set_xlabel("time [s]")
    for axis in axes:
        axis.grid(alpha=0.3)
    axes[0].set_title(f"Supercritical run ($\\mu_r$={mu_r}, $\\theta$=12 deg)")
    path = output / "fig_history.png"
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)
    produced.append(path.name)
    return produced


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", default=str(ROOT / "docs" / "rolling_resistance_validation")
    )
    parser.add_argument("--mu-grid", nargs="+", type=float, default=[0.05, 0.1, 0.2, 0.3, 0.5])
    parser.add_argument("--bisect-mu", type=float, default=0.2)
    parser.add_argument("--seed-mu", type=float, default=0.05)
    parser.add_argument("--no-figures", action="store_true")
    args = parser.parse_args(argv)

    torch.set_num_threads(1)
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)

    accel_rows = study_acceleration(args.mu_grid)
    threshold_rows, threshold_summary = study_threshold(args.mu_grid)
    bisection = bisect_threshold(args.bisect_mu)
    model_rows = study_models(0.05)
    torque_rows = study_torque_laws(0.05)
    history = history_rows(0.05, 12.0)

    figures: list[str] = []
    if not args.no_figures:
        figures = make_figures(
            output, accel_rows=accel_rows, threshold_rows=threshold_rows,
            threshold_summary=threshold_summary, torque_rows=torque_rows,
            history=history, mu_r=0.05,
        )

    write_csv(output / "acceleration_sweep.csv", accel_rows)
    write_csv(output / "threshold_sweep.csv", threshold_rows)
    write_csv(output / "model_comparison.csv", model_rows)
    write_csv(output / "torque_laws.csv", torque_rows)
    write_csv(output / "history.csv", history)

    comparable = [row for row in accel_rows if row["comparable"]]
    worst_error = max(row["relative_error"] for row in comparable)
    min_r_squared = min(row["fit_r_squared"] for row in comparable)
    regimes = sorted({row["regime"] for row in comparable})
    bisect_result = bisection[-1]
    summary = {
        "schema": "tensordem.rolling-resistance-validation/1",
        "generated_by": "scripts/validate_rolling_resistance.py",
        "environment": {
            "python": platform.python_version(),
            "torch": torch.__version__,
            "device": "cpu",
        },
        "harness": {
            "radius_m": RADIUS,
            "k_n_N_m": K_N,
            "dt_s": DT,
            "duration_s": DURATION,
            "settle_time_s": SETTLE,
            "sliding_friction_mu": SLIDE_MU,
            "drift_tolerance_over_radius": DRIFT_TOLERANCE_RADII,
            "rolling_stiffness_rule": "k_r = 2.25 * mu_r * k_n * R^2",
        },
        "analytic_references": {
            "critical_angle_deg": "arctan(mu_r)",
            "rolling_acceleration": "g (sin t - mu_r cos t) / (1 + I/(m R^2)), I/mR^2 = 2/5",
        },
        "acceleration_parity": {
            "supercritical_rows": len(accel_rows),
            "comparable_rows": len(comparable),
            "min_analytic_reference_m_s2": 0.05,
            "regimes": regimes,
            "max_relative_error": worst_error,
            "min_fit_r_squared": min_r_squared,
            "passes_3pct": bool(worst_error < 0.03),
        },
        "motion_detector": {
            "criterion": "late-window acceleration > MOTION_TOL_ACCEL",
            "motion_tol_accel_m_s2": MOTION_TOL_ACCEL,
            "threshold_duration_s": THRESH_DURATION,
            "threshold_settle_s": THRESH_SETTLE,
        },
        "threshold": threshold_summary,
        "bisection": bisect_result,
        "model_character": model_rows,
        "torque_laws": torque_rows,
        "figures": figures,
        "limitations": [
            "The validation harness is an independent rigid-body integration of a "
            "single sphere, not the bonded-particle solver: IceDEM3D tracks no "
            "particle rotation, so wiring rolling resistance into DEM3D requires "
            "adding angular degrees of freedom (not part of this change).",
            "Only the rolling component of the relative spin is resisted; "
            "drilling/spin friction about the contact normal is out of scope.",
            "k_r is a modelling choice (scaled with k_n), not a measured material "
            "constant; no experimental ice repose-angle calibration is included "
            "because no such dataset exists in this repository.",
            "The CDT and viscous branches have no static branch, so a resting "
            "particle creeps; only EPSD reproduces a true static equilibrium.",
        ],
    }
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    print(json.dumps(
        {
            "max_acceleration_relative_error": worst_error,
            "min_fit_r_squared": min_r_squared,
            "passes_3pct": summary["acceleration_parity"]["passes_3pct"],
            "bisection": bisect_result,
            "threshold": threshold_summary,
            "figures": figures,
        },
        indent=2,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())