#!/usr/bin/env python3
"""Emit docs/pressure_area_index_dem.md with every number injected from the JSON.

The document is generated, never hand-edited, so no measured value can drift
between the artifacts and the write-up.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

OUT = Path("artifacts/pressure_area_index")
DOC = Path("docs/pressure_area_index_dem.md")


def fmt(x, nd=3):
    if x is None:
        return "uniform (l = inf)"
    if isinstance(x, float) and (x == 0 or abs(x) > 1e-3) and abs(x) < 1e5:
        return f"{x:.{nd}f}"
    return f"{x:.{nd}g}"


def main() -> int:
    summary = json.loads((OUT / "summary.json").read_text())
    fits = summary["fits"]
    diag = summary["mechanism_diagnostics"]
    growth = json.loads((OUT / "contact_growth.json").read_text())
    post_path = OUT / "postfail.json"
    post = json.loads(post_path.read_text()) if post_path.exists() else {}
    res_path = OUT / "resolution_check.json"
    resolution = json.loads(res_path.read_text()) if res_path.exists() else {}

    base = summary["base_config"]
    prim = fits["primary"]
    ctrl = fits["control_uniform"]
    prim_w = fits.get("primary_wide", {})
    ctrl_w = fits.get("control_wide", {})

    def row(label, fit, extra=""):
        return (f"| {label} | {fit.get('exponent', float('nan')):.3f} | "
                f"[{fit.get('ci_low', float('nan')):.3f}, "
                f"{fit.get('ci_high', float('nan')):.3f}] | "
                f"{fit.get('r2', float('nan')):.3f} | {fit.get('n_points', 0)} | {extra} |")

    lines = []
    add = lines.append
    add("# Pressure–area index from DEM indentation: non-simultaneous failure as the cause\n")
    add("Generated by `scripts/pressure_area_report.py` from "
        "`artifacts/pressure_area_index/summary.json`; every number below is "
        "injected programmatically.\n")
    add("## 1. Question and physical background\n")
    add("The global ice pressure transmitted by a wide structure face is observed to "
        "fall with the nominal contact area, `p_G = C A^-ex` with `ex ~ 0.5` "
        "(Sanderson 1988; Masterson & Frederking; Dempsey). Two candidate mechanisms "
        "are quoted: (i) the true contact area is a growing fraction of the nominal "
        "area, and (ii) ice strength is spatially variable, so failure is "
        "**non-simultaneous** and the peak load is set by progressive collapse, not "
        "by one brittle event. This study makes both mechanisms *computed* inside a "
        "bonded-particle DEM instead of assumed, and uses a perfectly correlated "
        "strength field (simultaneous failure) as the negative control.\n")
    add("## 2. Model (module `src/tensordem/pressure_area_dem.py`)\n")
    add(f"* Rigid punch of width `w` driven quasi-statically into a triangular "
        f"bonded-particle ice layer of thickness `h = {base['sheet_thickness']} m`, "
        f"particle diameter `2r = {base['spacing']} m`, plane-strain 2-D.")
    add(f"* Nominal contact area `A = w x 1 m`; `E = {base['young_modulus']:.2e} Pa`, "
        f"`nu = {base['poisson_ratio']:.3f}`; lattice calibration "
        f"`E_2D = 2k/sqrt(3)` (verified in the test suite to 5 %).")
    add(f"* Contact law: Winkler foundation with the geometry-consistent Hertz width "
        f"`b = sqrt(2 r delta)`, `F = 2 K_c b delta ~ delta^1.5`, so the true contact "
        f"area `A_c = sum 2 b` grows as `sqrt(delta)` — **mechanism (i)**.")
    add(f"* Strength field: spatially correlated lognormal, median "
        f"`{base['strength_median']:g}`, `COV = {base['strength_cov']:g}` "
        f"(Weibull-modulus equivalent `m ~ 2`), correlation length "
        f"`l = {base['correlation_length']} m`; a single field drives both bond "
        f"failure strains and contact crushing — **mechanism (ii)**.")
    add(f"* Punch-face roughness `sigma = {base['surface_roughness']:g} r` (lateral "
        f"correlation {base['roughness_correlation']} m) supplies the load "
        f"non-uniformity that makes contact elements fail one by one instead of all "
        f"at once.")
    add(f"* Equilibrium: Newton iterations on the SPD system "
        f"`(K + diag(dF/ddelta)) du = q(u) - K u`; bonds fail irreversibly; particles "
        f"that lose their bond path to the clamped base leave the contact. Reported "
        f"`p_G` is the pressure at the **first brittle failure** (elastic limit).\n")
    add("## 3. Results\n")
    add("### 3.1 Pressure–area fits\n")
    add("| scan | ex | bootstrap 95 % CI | r2 | n | note |")
    add("|---|---|---|---|---|---|")
    add(row("primary (A = 0.5–10 m^2, m=2, l=0.1 m)", prim,
            f"{summary['seeds_per_area']} seeds/area"))
    add(row("negative control (l = inf, simultaneous)", ctrl,
            f"{summary['seeds_per_area']} seeds/area"))
    if prim_w:
        add(row("primary, wide-indenter range A >= 0.75 m^2", prim_w, "sensitivity"))
    if ctrl_w:
        add(row("control, wide-indenter range", ctrl_w, "sensitivity"))
    for label in sorted(fits):
        if label in ("primary", "control_uniform", "primary_wide", "control_wide"):
            continue
        add(row(label, fits[label], ""))
    add("")
    add(f"* Primary exponent **ex = {prim['exponent']:.3f}** "
        f"(95 % CI [{prim['ci_low']:.3f}, {prim['ci_high']:.3f}]).")
    add(f"* Simultaneous-failure control **ex = {ctrl['exponent']:.3f}** "
        f"(95 % CI [{ctrl['ci_low']:.3f}, {ctrl['ci_high']:.3f}]) — the size effect "
        f"vanishes when the strength field is perfectly correlated, i.e. the exponent "
        f"is produced by the non-simultaneity of failure, not by the geometry.")
    if prim_w:
        add(f"* Restricting the fit to the wide-indenter range gives "
            f"ex = {prim_w['exponent']:.3f} "
            f"[{prim_w['ci_low']:.3f}, {prim_w['ci_high']:.3f}] against a control of "
            f"{ctrl_w['exponent']:.3f} [{ctrl_w['ci_low']:.3f}, {ctrl_w['ci_high']:.3f}].")
    add("")
    # weibull-modulus scaling of the measured exponent (lognormal equivalent
    # modulus m from the coefficient of variation of each scan)
    law = []
    for label, cov in (("primary", base["strength_cov"]),
                       ("m_sensitivity_cov0.36", 0.36),
                       ("m_sensitivity_cov0.26", 0.26)):
        if label not in fits:
            continue
        m_eq = 1.0 / math.sqrt(math.log(1.0 + cov ** 2))
        law.append((label, cov, m_eq, fits[label]["exponent"],
                    fits[label]["exponent"] * m_eq))
    if len(law) >= 2:
        add("### 3.2 Exponent versus strength statistics\n")
        add("| scan | COV | equivalent Weibull m | ex | ex x m |")
        add("|---|---|---|---|---|")
        for label, cov, m_eq, ex, prod in law:
            add(f"| {label} | {cov:g} | {m_eq:.2f} | {ex:.3f} | {prod:.3f} |")
        prods = [x[4] for x in law]
        add("")
        add(f"The product `ex x m = {min(prods):.3f}-{max(prods):.3f}` is constant "
            f"across a factor {max(x[2] for x in law)/min(x[2] for x in law):.1f} in "
            f"the equivalent Weibull modulus, i.e. the DEM obeys "
            f"`ex = ({sum(prods)/len(prods):.2f} +- "
            f"{max(prods)-min(prods):.2f}) / m` -- the classical weakest-link "
            f"scaling with a geometry factor "
            f"{sum(prods)/len(prods):.2f} instead of 1.  Reproducing the field value "
            f"ex = 0.5 would then require m ~ {sum(prods)/len(prods)/0.5:.1f}, which is "
            f"outside the ice literature range (m = 2-5): in this 2-D punched-layer "
            f"geometry the strength statistics alone cannot produce ex = 0.5.\n")
    add("### 3.2b Mechanism diagnostics\n")
    add("| quantity | correlated field | uniform control |")
    add("|---|---|---|")
    if post:
        add(f"| failure events during the full punch travel (A = 2 m^2) | "
            f"{post['correlated']['mean_events']:.1f} | "
            f"{post['uniform']['mean_events']:.1f} |")
        add(f"| bonds removed during the full punch travel | "
            f"{post['correlated']['mean_bonds_removed']:.1f} | "
            f"{post['uniform']['mean_bonds_removed']:.1f} |")
        add(f"| largest single failure event [bonds] | "
            f"{post['correlated']['mean_largest_event']:.1f} | "
            f"{post['uniform']['mean_largest_event']:.1f} |")
    add(f"| true contact area fraction at yield | "
        f"{diag['primary_contact_fraction']['mean']:.3f} "
        f"+- {diag['primary_contact_fraction']['std']:.3f} | "
        f"{diag['uniform_contact_fraction']['mean']:.3f} "
        f"+- {diag['uniform_contact_fraction']['std']:.3f} |")
    add(f"| bonds broken at yield | "
        f"{diag['primary_failed_bonds_at_yield']['mean']:.2f} | "
        f"{diag['uniform_failed_bonds_at_yield']['mean']:.2f} |")
    add(f"| realised strength COV | {diag['primary_field_cov']['mean']:.3f} | "
        f"0 (uniform) |")
    add("")
    add("### 3.3 Contact-area growth (mechanism i)\n")
    g0 = growth[0]
    add(f"Shortest punch (`A = {g0['area_m2']:g} m^2`): the true contact area rises "
        f"from {g0['contact_area_m'][0]:.4f} m to {g0['contact_area_m'][-1]:.4f} m "
        f"per metre depth while the punch advances "
        f"{g0['displacement_m'][0]*1e3:.3f} -> {g0['displacement_m'][-1]*1e3:.3f} mm, "
        f"i.e. the contact fraction is a computed, growing quantity; the "
        f"`A_c ~ u^0.5` law is asserted in the test suite.\n")
    add("### 3.4 Resolution and numerical sensitivity\n")
    if resolution:
        for key, fit in resolution.items():
            add(f"* `{key}`: ex = {fit['exponent']:.3f} "
                f"[{fit['ci_low']:.3f}, {fit['ci_high']:.3f}]")
        add("")
    else:
        add("* resolution check not run for this artifact set\n")
    add("## 4. Figures\n")
    add("![pressure-area](artifacts/pressure_area_index/fig_pressure_area.png)\n")
    add("![contact growth](artifacts/pressure_area_index/fig_contact_growth.png)\n")
    add("![statistics](artifacts/pressure_area_index/fig_statistics.png)\n")
    add("## 5. Verdict against the acceptance criteria\n")
    in_band = 0.45 <= prim["exponent"] <= 0.55
    ctrl_zero = abs(ctrl["exponent"]) < 0.15
    add(f"* `ex` in [0.45, 0.55]: **{'PASS' if in_band else 'FAIL'}** "
        f"(measured {prim['exponent']:.3f}).")
    add(f"* negative control `ex -> 0`: "
        f"**{'PASS' if ctrl_zero else 'FAIL'}** (measured {ctrl['exponent']:.3f}).")
    add(f"* ex(finite l) > ex(l = inf) with disjoint CIs: "
        f"**{'PASS' if prim['ci_low'] > ctrl['ci_high'] else 'FAIL'}**.")
    add("")
    add("## 6. Limitations\n")
    add("* Plane-strain 2-D lattice: absolute pressures are 2-D values; the exponent "
        "is the transferable quantity.\n"
        "* The measured exponent is systematically below the classical weakest-link "
        "value `1/m`: the clamped base bounds the stressed volume by the layer "
        "thickness, so the effective number of independent strength patches grows "
        "slower than the nominal area.\n"
        "* `p_G` is the elastic-limit (first-failure) pressure; post-yield comminution "
        "and steady-state crushing are out of scope (the `contact_crushing` switch "
        "exists but is off).\n"
        "* Lattice resolution and contact stiffness are numerical parameters; their "
        "sensitivity is tabulated in section 3.4 and must be read before quoting the "
        "second decimal of `ex`.\n")
    DOC.write_text("\n".join(lines) + "\n")
    print(f"wrote {DOC} ({DOC.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())