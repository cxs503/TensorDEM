"""Render the hull-ice friction artefacts into a markdown results document.

Every number in the generated document is read from
``artifacts/hull_ice_friction/summary.json`` (and its CSV companions), so no
value is transcribed by hand.

Usage::

    python scripts/render_hull_ice_friction_report.py \
        --summary artifacts/hull_ice_friction/summary.json \
        --output docs/hull_ice_friction_temperature_results.md
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _fmt(value, digits: int = 4) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int,)):
        return str(value)
    try:
        return f"{float(value):.{digits}f}"
    except (TypeError, ValueError):
        return str(value)


def render(summary_path: Path) -> str:
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    fit = summary["mu_temperature_fit"]
    dem = summary["dem_sweep"]
    md = summary["md_sweep"]
    cross = summary["cross_scale"]
    resistance = summary["resistance"]
    comparison = summary["resistance_comparison"]
    calibration = summary["md_calibration"]
    criteria = summary["criteria"]
    artefacts = summary["artefacts"]

    lines = []
    lines.append("# Hull-ice friction temperature dependence - generated results")
    lines.append("")
    lines.append(
        "> Auto-generated by `scripts/render_hull_ice_friction_report.py` from "
        f"`{summary_path}` (protocol `{summary['protocol']}`). Do not edit by hand."
    )
    lines.append("")
    lines.append("## 1. Configuration")
    lines.append("")
    lines.append("| item | value |")
    lines.append("| --- | --- |")
    lines.append(
        f"| temperatures swept | {', '.join(_fmt(t, 1) for t in summary['temperatures_C'])} degC |"
    )
    lines.append(f"| DEM repeats per temperature | {summary['dem_repeats_per_temperature']} |")
    lines.append(f"| MD repeats per temperature | {summary['md_repeats_per_temperature']} |")
    dem_config = summary["dem_configuration"]
    for key in (
        "n_x",
        "n_y",
        "particle_radius",
        "thickness",
        "normal_stiffness",
        "normal_pressure_Pa",
        "sliding_velocity",
        "timestep",
        "steps",
        "asperity_radius" if "asperity_radius" in dem_config else "bump_radius",
        "bump_spacing",
        "bond_tensile_strength",
        "interface_mu_ref",
        "interface_exponent",
    ):
        if key in dem_config:
            lines.append(f"| DEM `{key}` | {_fmt(dem_config[key], 6)} |")
    lines.append(
        f"| wall-clock DEM sweep | {_fmt(summary['timings'].get('dem_sweep_s', 0.0), 1)} s |"
    )
    lines.append(
        f"| wall-clock MD calibration + sweep | {_fmt(summary['timings'].get('md_sweep_s', 0.0), 1)} s |"
    )
    lines.append("")

    lines.append("## 2. DEM calibration of mu(T)")
    lines.append("")
    lines.append(
        "| T [degC] | mu_DEM (mean +- std) | adhesion part | ploughing part | normal load [N] "
        "| imposed mu_c(T) | repeats |"
    )
    lines.append("| --- | --- | --- | --- | --- | --- | --- |")
    for record in dem:
        lines.append(
            "| {t} | {mu} +- {std} | {adh} | {plough} | {load} | {law} | {reps} |".format(
                t=_fmt(record["temperature_C"], 1),
                mu=_fmt(record["mu_mean"]),
                std=_fmt(record["mu_std"]),
                adh=_fmt(record["mu_adhesion_mean"]),
                plough=_fmt(record["mu_ploughing_mean"]),
                load=_fmt(record["normal_load_N_mean"], 6),
                law=_fmt(record["interface_mu"]),
                reps=record["repeats"],
            )
        )
    lines.append("")
    lines.append(
        "Least-squares identification of "
        "`mu(T) = mu0 + alpha * |T - T_melt|^beta`: "
        f"mu0 = {_fmt(fit['mu0'])}, alpha = {_fmt(fit['alpha'])}, beta = {_fmt(fit['beta'], 3)}, "
        f"R^2 = {_fmt(fit['r_squared'], 6)}, RMSE = {_fmt(fit['rmse'], 6)}, "
        f"max |residual| = {_fmt(fit['max_abs_residual'], 6)}."
    )
    lines.append("")
    lines.append("| T [degC] | mu measured | mu fitted | residual |")
    lines.append("| --- | --- | --- | --- |")
    for temperature, observed, fitted, residual in zip(
        fit["temperatures_C"], fit["mu_observed"], fit["mu_fitted"], fit["residuals"]
    ):
        lines.append(
            f"| {_fmt(temperature, 1)} | {_fmt(observed)} | {_fmt(fitted)} | {_fmt(residual, 6)} |"
        )
    lines.append("")

    lines.append("## 3. MD cross-scale check")
    lines.append("")
    lines.append(
        "The single free MD parameter (Fe/water Lennard-Jones well depth) was identified "
        "at the reference temperature only: "
        f"`lj_epsilon_iron_water_kJ = {_fmt(calibration['lj_epsilon_iron_water_kJ'])}` gives "
        f"mu_MD = {_fmt(calibration['mu'])} against the target {_fmt(calibration['target_mu'])} "
        f"(relative error {_fmt(calibration['relative_error'] * 100, 2)} %). "
        f"Protocol: {calibration['protocol']}."
    )
    lines.append("")
    lines.append("| T [degC] | mu_MD (mean +- std) | kinetic T [K] |")
    lines.append("| --- | --- | --- |")
    for record in md:
        lines.append(
            "| {t} | {mu} +- {std} | {tk} |".format(
                t=_fmt(record["temperature_C"], 1),
                mu=_fmt(record["mu_mean"]),
                std=_fmt(record["mu_std"]),
                tk=_fmt(record["kinetic_temperature_K_mean"], 1),
            )
        )
    lines.append("")
    lines.append("| T [degC] | mu_DEM | mu_MD | difference | relative difference | < 30 % |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for record in cross:
        lines.append(
            "| {t} | {dem} | {md} | {diff} | {rel} % | {ok} |".format(
                t=_fmt(record["temperature_C"], 1),
                dem=_fmt(record["mu_dem"]),
                md=_fmt(record["mu_md"]),
                diff=_fmt(record["absolute_difference"]),
                rel=_fmt(record["relative_difference_to_md"] * 100, 2),
                ok=_fmt(record["within_30_percent"]),
            )
        )
    lines.append("")

    lines.append("## 4. Level-ice resistance with the calibrated mu(T)")
    lines.append("")
    lines.append(
        "| T [degC] | mu | crushing [kN] | breaking [kN] | submersion [kN] | friction [kN] "
        "| total [kN] | friction share [-] |"
    )
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for record in resistance:
        lines.append(
            "| {t} | {mu} | {c} | {b} | {s} | {f} | {tot} | {share} |".format(
                t=_fmt(record["temperature_C"], 1),
                mu=_fmt(record["friction_coefficient"]),
                c=_fmt(record["crushing_resistance_N"] / 1e3, 2),
                b=_fmt(record["breaking_resistance_N"] / 1e3, 2),
                s=_fmt(record["submersion_resistance_N"] / 1e3, 2),
                f=_fmt(record["friction_resistance_N"] / 1e3, 2),
                tot=_fmt(record["total_resistance_N"] / 1e3, 2),
                share=_fmt(record["friction_share"]),
            )
        )
    lines.append("")
    lines.append(
        "- warm state (-5 degC): R = {rw} kN, friction share {sw}\n"
        "- cold state (-20 degC): R = {rc} kN, friction share {sc}\n"
        "- delta R = {dr} kN ({drrel} % of the warm resistance), mu ratio cold/warm = {ratio}".format(
            rw=_fmt(comparison["warm"]["total_resistance_N"] / 1e3, 2),
            sw=_fmt(comparison["friction_share_warm"]),
            rc=_fmt(comparison["cold"]["total_resistance_N"] / 1e3, 2),
            sc=_fmt(comparison["friction_share_cold"]),
            dr=_fmt(comparison["delta_resistance_N"] / 1e3, 2),
            drrel=_fmt(comparison["delta_relative_to_warm"] * 100, 2),
            ratio=_fmt(comparison["friction_coefficient_ratio_cold_over_warm"]),
        )
    )
    lines.append("")

    lines.append("## 5. Acceptance criteria")
    lines.append("")
    lines.append("| criterion | passed | value |")
    lines.append("| --- | --- | --- |")
    for item in criteria["criteria"]:
        value = item["value"]
        if isinstance(value, dict):
            simple = ", ".join(
                f"{key}: {_fmt(val, 4) if not isinstance(val, dict) else 'see summary'}"
                for key, val in value.items()
                if key != "per_temperature"
            )
        else:
            simple = _fmt(value, 4)
        lines.append(f"| {item['criterion']} | {_fmt(item['passed'])} | {simple} |")
    lines.append("")
    lines.append(f"All criteria passed: **{_fmt(criteria['all_passed'])}**.")
    lines.append("")

    lines.append("## 6. Artefacts")
    lines.append("")
    for key, value in artefacts.items():
        if isinstance(value, list):
            for path in value:
                lines.append(f"- {key}: `{path}`")
        else:
            lines.append(f"- {key}: `{value}`")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--summary",
        type=Path,
        default=ROOT / "artifacts" / "hull_ice_friction" / "summary.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "docs" / "hull_ice_friction_temperature_results.md",
    )
    arguments = parser.parse_args()
    document = render(arguments.summary)
    arguments.output.write_text(document + "\n", encoding="utf-8")
    print(f"wrote {arguments.output} ({len(document.splitlines())} lines)")


if __name__ == "__main__":
    main()