def main() -> int:
    text = SRC.read_text()
    if "lees_edwards" in text:
        print("already patched, nothing to do")
        return 0
    for old, new in EDITS:
        n = text.count(old)
        if n != 1:
            print(f"ANCHOR COUNT {n} != 1 for:\n{old[:120]}", file=sys.stderr)
            return 2
        text = text.replace(old, new)
    SRC.write_text(text)
    print(f"patched {SRC} ({len(EDITS)} edits)")
    return 0


