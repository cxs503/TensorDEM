"""Figure for GAP-DEM-AUTOCALIB round 2 gate 1 (m14868).

Four panels, all numbers read from the artefacts (no hand-copying):

(a) theta_r versus system size at fixed parameters, one marker per seed, the dry
    sand literature band 30-37 deg shaded, and the plateau tolerance window of
    the two largest sizes;
(b) the two sensitivities that decide the verdict: material knob (grain
    friction) versus protocol-geometry knob (injection radius), each with the
    seed noise floor and its signal-to-noise ratio;
(c) a deposit cross-section of the N = 960 case (position cloud coloured by
    speed) next to the layer count implied by its height - the deposit is a
    sheet, not a heap;
(d) bulk solid fraction versus N against the 0.30 gate.

Usage: ``PYTHONPATH=src python scripts/m14868_autocalib_r2_figure.py``
"""
from __future__ import annotations

import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

OUT_DIR = os.path.join("artifacts", "gap_dem_autocalib_r2")
SUMMARY = os.path.join(OUT_DIR, "qualification.json")
SNAPSHOT = os.path.join(OUT_DIR, "snapshot_n960.json")
FIGURE = os.path.join("docs", "verification", "figures", "autocalib_r2_gate1.png")

LIT_BAND = (30.0, 37.0)

#: generated by scripts.m14868_autocalib_r2_sweep.design()
MU_TRUTH, IRF_DEFAULT = 0.52, 7.0


def main() -> None:
    with open(SUMMARY) as fh:
        rep = json.load(fh)
    cells = rep["cells"]

    nominal = [c for c in cells
               if c["mu"] == MU_TRUTH and c["inject_radius_factor"] == IRF_DEFAULT]
    fig, axes = plt.subplots(2, 2, figsize=(12.5, 9.0))
    ax = axes[0, 0]
    ax.axhspan(*LIT_BAND, color="0.85", zorder=0,
               label=f"dry sand literature band {LIT_BAND[0]:.0f}-{LIT_BAND[1]:.0f} deg")
    by_n: dict[float, list[float]] = {}
    for c in nominal:
        by_n.setdefault(float(c["n_grains"]), []).append(float(c["theta_r_deg"]))
    ns = sorted(by_n)
    for i, n in enumerate(ns):
        vals = by_n[n]
        ax.scatter([n] * len(vals), vals, s=46, color="C0", zorder=3,
                   label="individual seeds" if i == 0 else None)
        ax.scatter([n], [np.mean(vals)], marker="_", s=420, color="C3", zorder=4,
                   label="seed mean" if i == 0 else None)
    if len(ns) >= 2:
        tol = rep["gates"]["G3_size_convergence"]["threshold"]
        m_prev, m_max = np.mean(by_n[ns[-2]]), np.mean(by_n[ns[-1]])
        ax.annotate(f"|d theta| = {abs(m_max - m_prev):.1f} deg  (tolerance {tol:.1f})",
                    xy=(ns[-1], m_max), xytext=(ns[-1] * 0.35, 72),
                    arrowprops=dict(arrowstyle="->", color="C3"), color="C3", fontsize=9)
    ax.set_xscale("log")
    ax.set_xlabel("grains N [-]")
    ax.set_ylabel(r"$\theta_r$ [deg]")
    ax.set_title("(a) shipped pluviation response vs system size\n"
                 f"seed spread at N={ns[0]:.0f}: {max(by_n[ns[0]]) - min(by_n[ns[0]]):.1f} deg"
                 if ns else "(a) size sweep")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8, loc="upper left")

    ax = axes[0, 1]
    dom = rep["dominance"]
    sigma = rep["seed_sigma_deg"]
    labels = [f"material knob\n(mu 0.30->0.70,\nIRF={3.5:g})",
              f"protocol knob\n(IRF 3.5->14,\nmu=0.30)"]
    vals = [dom["delta_signal"], dom["delta_geometry"]]
    ax.bar(labels, vals, color=["C2", "C1"], width=0.55)
    ax.axhline(sigma, color="C3", ls="--", label=f"seed noise sigma = {sigma:.2f} deg")
    ax.axhline(3 * sigma, color="C3", ls=":", label="resolvable (3 sigma)")
    for x, v, snr in zip(range(2), vals, [dom["snr_signal"], dom["snr_geometry"]]):
        ax.text(x, v + 0.03 * max(vals + [1.0]), f"{v:.2f} deg\nSNR {snr:.1f}",
                ha="center", fontsize=9)
    ax.set_ylabel(r"$|\Delta\theta_r|$ [deg]")
    ax.set_title("(b) material signal vs protocol-geometry artefact\n"
                 f"ratio {dom['ratio']:.2f} (gate >= 3)")
    ax.grid(alpha=0.3, axis="y")
    ax.legend(fontsize=8)

    ax = axes[1, 0]
    if os.path.exists(SNAPSHOT):
        with open(SNAPSHOT) as fh:
            snap = json.load(fh)
        x = np.asarray(snap["x_m"]) * 1e3
        z = np.asarray(snap["z_m"]) * 1e3
        sp = np.asarray(snap["speed"])
        sc = ax.scatter(x, z, c=sp, s=9, cmap="viridis")
        plt.colorbar(sc, ax=ax, label="speed [m/s]")
        ax.set_title(f"(c) N=960 deposit cross-section: {snap['layers']:.1f} grain layers, "
                     f"footprint r={snap['footprint_radius_m']*1e3:.0f} mm\n"
                     f"theta={snap['theta_r_deg']:.1f} deg, r2={snap['r2']:.2f}")
    else:
        ax.text(0.5, 0.5, "snapshot missing", ha="center")
        ax.set_title("(c) deposit cross-section")
    ax.set_xlabel("x [mm]")
    ax.set_ylabel("z [mm]")
    ax.set_aspect("equal", adjustable="datalim")

    ax = axes[1, 1]
    for i, n in enumerate(ns):
        phis = [float(c["phi_solid"]) for c in nominal if float(c["n_grains"]) == n]
        ax.scatter([n] * len(phis), phis, color="C0", s=40)
        ax.scatter([n], [np.mean(phis)], marker="_", s=420, color="C3")
    ax.axhline(0.30, color="C4", ls="--", label="gate G2: phi_solid >= 0.30")
    ax.axhline(0.55, color="0.5", ls=":", label="loose random packing ~0.55-0.60")
    ax.set_xscale("log")
    ax.set_xlabel("grains N [-]")
    ax.set_ylabel(r"bulk solid fraction $\phi$ [-]")
    ax.set_title("(d) the deposit is a monolayer sheet at every size")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8)

    fig.suptitle("GAP-DEM-AUTOCALIB round 2, gate 1: is theta_r(N) a material "
                 f"function?  verdict = {rep['verdict']}", fontsize=13)
    fig.tight_layout(rect=(0, 0, 1, 0.96))
    os.makedirs(os.path.dirname(FIGURE), exist_ok=True)
    fig.savefig(FIGURE, dpi=150)
    print("wrote", FIGURE)


if __name__ == "__main__":
    main()