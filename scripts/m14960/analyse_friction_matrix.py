"""Analyse the m14960 shear-cell matrix: size scan, mu_p calibration, experiment gap.

Reads ``artifacts/shear_cell_m14960/*.json`` (written by
``scripts/m14960/run_friction_matrix.py``) and emits

* ``artifacts/shear_cell_m14960/summary.json``  (machine-readable table)
* ``docs/SHEAR_CELL_M14960_tables.md``          (programmatically injected tables)
* ``docs/figures/shear_cell_m14960.png``        (figure)

Anchor: quasi-static effective friction of a dense, dry, rounded-sphere packing
(Jop, Forterre & Pouliquen, Nature 441, 727 (2006): mu_s = 0.36-0.40, I_0 ~ 0.3;
GDR MiDi, Eur. Phys. J. E 14, 341 (2004)).  Value carried in ``MU_LIT`` with the
band in ``MU_LIT_BAND``; the gate is |mu_DEM/mu_lit - 1| < 10 %.
"""
from __future__ import annotations

import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, "artifacts", "shear_cell_m14960")
DOCS = os.path.join(ROOT, "docs")
FIGS = os.path.join(DOCS, "figures")

MU_LIT = 0.38          # central literature value, quasi-static limit
MU_LIT_BAND = (0.36, 0.40)
GATE = 0.10


def load() -> dict:
    out = {}
    for p in sorted(glob.glob(os.path.join(ART, "*.json"))):
        if os.path.basename(p) == "summary.json":
            continue
        d = json.load(open(p))
        out[d["tag"]] = d
    return out


def err(mu: float) -> float:
    return mu / MU_LIT - 1.0


def main() -> None:
    data = load()
    os.makedirs(FIGS, exist_ok=True)
    summary = {"mu_lit": MU_LIT, "mu_lit_band": MU_LIT_BAND, "gate_rel": GATE,
               "runs": {k: {"case": v["case"], "bed": v["bed"],
                            "levels": [{kk: vv for kk, vv in l.items()
                                        if kk not in ("shear_strain_history",
                                                      "shear_stress_history",
                                                      "normal_stress_history")}
                                       for l in v["levels"]]}
                        for k, v in data.items()}}
    with open(os.path.join(ART, "summary.json"), "w") as fh:
        json.dump(summary, fh, indent=1)

    lines = ["<!-- generated by scripts/m14960/analyse_friction_matrix.py; do not hand-edit -->",
             "### 表 1 有限尺寸扫描（mu_p = 0.5, sigma_n = 4000 Pa, gamma = 0.6）", "",
             "| 几何 | N | 堆积率 | sigma 实测 [Pa] | tau [Pa] | mu_macro | mu/mu_lit-1 | I | 有效 |",
             "|---|---|---|---|---|---|---|---|---|"]
    size = []
    for tag in ("size_small", "size_medium", "size_large"):
        d = data.get(tag)
        if not d:
            lines.append("| %s | (未完成) | | | | | | | |" % tag)
            continue
        l = d["levels"][0]
        size.append((tag, d["bed"]["n_particles"], l["mu"]))
        lines.append("| %s | %d | %.3f | %.1f | %.1f | **%.4f** | %+.1f%% | %.4f | %s |"
                     % (tag, d["bed"]["n_particles"], d["bed"]["packing_fraction"],
                        l["sigma_pa"], l["tau_pa"], l["mu"], 100 * err(l["mu"]),
                        l["inertial_number"], "PASS" if l["valid"] else l["invalid_reason"][:28]))

    lines += ["", "### 表 2 微摩擦标定矩阵（medium 几何, gamma = 1.0, 稳态门 0.15）", "",
              "| mu_p | sigma 目标 [Pa] | sigma 实测 [Pa] | 相对误差 | tau [Pa] | mu_macro | mu/mu_lit-1 | 漂移 | 有效 |",
              "|---|---|---|---|---|---|---|---|---|"]
    for tag in ("mu030", "mu050", "mu070"):
        d = data.get(tag)
        if not d:
            lines.append("| %s | (未完成) | | | | | | | |" % tag)
            continue
        for l in d["levels"]:
            lines.append("| %.2f | %.0f | %.1f | %+.2f%% | %.1f | **%.4f** | %+.1f%% | %+.2f | %s |"
                         % (d["case"]["mu"], l["sigma_target_pa"], l["sigma_pa"],
                            100 * l["sigma_rel_err"], l["tau_pa"], l["mu"],
                            100 * err(l["mu"]), l["drift_rel"],
                            "PASS" if l["valid"] else l["invalid_reason"][:26]))
    with open(os.path.join(DOCS, "SHEAR_CELL_M14960_tables.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n")

    # ---- figure ---------------------------------------------------------
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        fig, ax = plt.subplots(1, 3, figsize=(13.5, 4.0))
        # A: size scan
        if size:
            ax[0].plot([s[1] for s in size], [s[2] for s in size], "o-", label="DEM")
            ax[0].axhspan(*MU_LIT_BAND, color="0.8", label="literature band")
            ax[0].set_xscale("log")
            ax[0].set_xlabel("number of beads in the cell")
            ax[0].set_ylabel(r"$\mu_{macro}$")
            ax[0].set_title("A finite-size scan ($\\mu_p=0.5$)")
            ax[0].legend(fontsize=8)
        # B: mu_p calibration
        for tag, c in (("mu030", "C0"), ("mu050", "C1"), ("mu070", "C2")):
            d = data.get(tag)
            if not d:
                continue
            ax[1].plot([l["sigma_target_pa"] for l in d["levels"]],
                       [l["mu"] for l in d["levels"]], "o-", color=c,
                       label=r"$\mu_p=%.1f$" % d["case"]["mu"])
        ax[1].axhspan(*MU_LIT_BAND, color="0.8")
        ax[1].set_xlabel(r"$\sigma_n$ [Pa]")
        ax[1].set_ylabel(r"$\mu_{macro}$")
        ax[1].set_title("B stress dependence vs experiment")
        ax[1].legend(fontsize=8)
        # C: tau history of the steady window
        for tag, c in (("mu030", "C0"), ("mu050", "C1"), ("mu070", "C2")):
            d = data.get(tag)
            if not d:
                continue
            for l in d["levels"]:
                if abs(l["sigma_target_pa"] - 4000.0) < 1e-6:
                    ax[2].plot(l["shear_strain_history"], l["shear_stress_history"],
                               color=c, label=r"$\mu_p=%.1f$" % d["case"]["mu"])
        ax[2].set_xlabel(r"$\gamma$")
        ax[2].set_ylabel(r"$\tau$ [Pa]")
        ax[2].set_title(r"C $\tau(\gamma)$ at $\sigma_n=4000$ Pa")
        ax[2].legend(fontsize=8)
        for a in ax:
            a.grid(alpha=0.3)
        fig.tight_layout()
        fig.savefig(os.path.join(FIGS, "shear_cell_m14960.png"), dpi=130)
        print("wrote figure")
    except Exception as exc:      # pragma: no cover
        print("figure skipped:", exc)

    print("\n".join(lines))


if __name__ == "__main__":
    main()