#!/usr/bin/env python3
"""Rebuild the m4804 negative-control evidence (table + figure).

The sibling script ``scripts/negative_controls_m4804.py`` proves the
negative controls are not vacuous by mutating them and requiring red.  This
script produces the *quantitative* evidence they rely on: it drives the
measurement helpers of
``tests/test_dem2d_energy_fracture_ledger_negative.py`` directly, records the
relative residual induced by every channel corruption, and renders

* ``artifacts/m4804_negative_controls/margins.json``   (machine-readable table)
* ``docs/figures/m4804_negative_control_margins.png``  (margin/tolerance bars)
* the Markdown table between the markers in
  ``docs/dem2d_energy_fracture_ledger_negative_controls_m4804.md``

so no number in the document is typed by hand.

Usage::

    TORCH_DEVICE_BACKEND_AUTOLOAD=0 python3 scripts/plot_m4804_ledger_negative_margins.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

import test_dem2d_energy_fracture_ledger_negative as controls  # noqa: E402

OUT = ROOT / "artifacts" / "m4804_negative_controls"
FIGURE = ROOT / "docs" / "figures" / "m4804_negative_control_margins.png"
DOC = ROOT / "docs" / "dem2d_energy_fracture_ledger_negative_controls_m4804.md"
BEGIN = "<!-- BEGIN:margins (generated by scripts/plot_m4804_ledger_negative_margins.py) -->"
END = "<!-- END:margins -->"

UNLOADED = [
    ("fracture_release_J", 0.0),
    ("fracture_release_J", 3.0),
    ("fracture_release_J", -1.0),
    ("pair_contact_acquired_J", 0.0),
    ("pair_contact_acquired_J", 3.0),
    ("tool_work_J", 0.0),
    ("tool_work_J", 3.0),
    ("damping_dissipation_J", 0.0),
    ("damping_dissipation_J", 3.0),
]
LOADED = [("external_work_J", -1.0)]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    FIGURE.parent.mkdir(parents=True, exist_ok=True)

    indentation = controls._run_indentation()
    loaded = controls._run_indentation(controls.LOAD_Y_N)

    rows = []
    for channel, factor in UNLOADED:
        rows.append(
            dict(
                channel=channel,
                factor=factor,
                relative_residual=controls._relative_residual(
                    controls._corrupt(indentation, channel, factor)
                ),
                margin=controls._sensitivity_margin(indentation, channel, factor),
                scenario="unloaded",
            )
        )
    for channel, factor in LOADED:
        rows.append(
            dict(
                channel=channel,
                factor=factor,
                relative_residual=controls._relative_residual(
                    controls._corrupt(loaded, channel, factor)
                ),
                margin=controls._sensitivity_margin(loaded, channel, factor),
                scenario="loaded",
            )
        )

    payload = dict(
        tolerance=controls.TOL,
        positive_control=dict(
            unloaded_rel_residual=controls._relative_residual(indentation),
            unloaded_scale_J=controls._energy_scale(indentation),
            loaded_rel_residual=controls._relative_residual(loaded),
            loaded_scale_J=controls._energy_scale(loaded),
            loaded_external_work_J=loaded.accounting["external_work_J"],
            broken_bonds_unloaded=indentation.broken_bonds,
            broken_bonds_loaded=loaded.broken_bonds,
        ),
        pristine_channels_J=dict(indentation.accounting),
        corruptions=rows,
        min_margin=min(row["margin"] for row in rows),
    )
    (OUT / "margins.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    labels = [f"{row['channel'].replace('_J', '')}\n×{row['factor']:g}"
              f"{' (loaded)' if row['scenario'] == 'loaded' else ''}" for row in rows]
    values = [row["margin"] for row in rows]
    fig, ax = plt.subplots(figsize=(9.6, 4.0))
    bars = ax.bar(range(len(values)), values, color="#2b6cb0")
    ax.set_yscale("log")
    ax.axhline(1.0, color="crimson", linestyle="--", linewidth=1.2,
               label=f"closure tolerance = {controls.TOL:.1%} of energy scale")
    ax.axhline(3.0, color="darkorange", linestyle=":", linewidth=1.2,
               label="required control margin (3×tol)")
    for bar, value in zip(bars, values):
        ax.text(bar.get_x() + bar.get_width() / 2, value * 1.1, f"{value:.1f}×",
                ha="center", va="bottom", fontsize=8)
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, fontsize=7)
    ax.set_ylabel("corrupted residual / tolerance  [–]")
    ax.set_title("2-D energy/fracture ledger: sensitivity of the balance check to single-channel corruption")
    ax.legend(loc="upper right", fontsize=8)
    ax.grid(axis="y", which="both", alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIGURE, dpi=100)
    plt.close(fig)

    table = [
        BEGIN,
        "| scenario | corrupted channel | factor | corrupted relative residual | margin / tol |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        table.append(
            f"| {row['scenario']} | `{row['channel']}` | ×{row['factor']:g} "
            f"| {row['relative_residual']:.4f} | {row['margin']:.1f} |"
        )
    table += [
        "",
        f"Pristine (unloaded) relative residual {payload['positive_control']['unloaded_rel_residual']:.4g} "
        f"on an energy scale of {payload['positive_control']['unloaded_scale_J']:.4f} J; "
        f"loaded {payload['positive_control']['loaded_rel_residual']:.4g} "
        f"on {payload['positive_control']['loaded_scale_J']:.4f} J "
        f"(external work {payload['positive_control']['loaded_external_work_J']:.4g} J). "
        f"Tolerance {controls.TOL:.1%}; minimum margin {payload['min_margin']:.1f}×tol.",
        END,
    ]
    if DOC.exists():
        text = DOC.read_text(encoding="utf-8")
        head, _, rest = text.partition(BEGIN)
        _, _, tail = rest.partition(END)
        DOC.write_text(head + "\n".join(table) + tail, encoding="utf-8")
        print(f"table injected into {DOC.relative_to(ROOT)}")
    else:
        print(f"NOTE: {DOC.relative_to(ROOT)} missing — table not injected")
    print(f"wrote {OUT.joinpath('margins.json').relative_to(ROOT)} and {FIGURE.relative_to(ROOT)}")
    print(f"min margin {payload['min_margin']:.2f}×tol")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())