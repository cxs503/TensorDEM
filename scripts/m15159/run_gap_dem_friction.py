"""GAP-DEM-FRICTION (m15159) entry point.

Single point (what ``study.run_point`` writes) or the whole aggregate study
(benchmark row vs the external anchor, Mohr-Coulomb envelope, tables, figure).

Usage
-----
    # one point (this is the repro_cmd recorded in every artifact)
    PYTHONPATH=src python scripts/m15159/run_gap_dem_friction.py \
        --tag headline_mu050_g100_s4000 --mu 0.5 --gamma 1.0 --sigma 4000

    # aggregate everything already in artifacts/gap_dem_friction_m15159/
    PYTHONPATH=src python scripts/m15159/run_gap_dem_friction.py --aggregate

Outputs
-------
    artifacts/gap_dem_friction_m15159/<tag>.json     (per-point run artifact)
    artifacts/gap_dem_friction_m15159/benchmark.json (ref / got / error / repro_cmd)
    docs/GAP_DEM_FRICTION_M15159_TABLES.md           (tables, programmatic)
    docs/figures/gap_dem_friction_m15159.png         (histories + material axis)
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src"))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

from scripts.m15159.study import (  # noqa: E402
    OUT_DIR, REF_BAND, REF_MU, REPO, TOLERANCE, benchmark, envelope, load_points, run_point,
)


def _headline(points):
    for p in points:
        if p["tag"].startswith("headline"):
            return p
    for p in points:
        lv, cs = p["level"], p["case"]
        if cs["mu_p"] == 0.5 and abs(cs["gamma"] - 1.0) < 1e-12 and cs["sigma_target_pa"] == 4000.0:
            return p
    return points[0] if points else None


def aggregate():
    points = [p for p in load_points() if not p["tag"].startswith("smoke")]
    if not points:
        print("no run artifacts in %s" % OUT_DIR)
        return 1
    head = _headline(points)
    rows = [benchmark(p) for p in points]
    payload = {
        "anchor": {"ref": REF_MU, "band": list(REF_BAND), "tolerance": TOLERANCE,
                   "source": rows[0]["ref_source"] if rows else ""},
        "headline_tag": head["tag"],
        "headline": benchmark(head),
        "envelope": envelope(points),
        "rows": rows,
        "n_points": len(points),
    }
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "benchmark.json"), "w") as fh:
        json.dump(payload, fh, indent=1)

    _tables(points, payload)
    _figure(points, payload)
    h = payload["headline"]
    print("headline %s: mu=%.4f ref=%.2f err=%+.2f%% usable=%s degenerate=%s pass=%s"
          % (head["tag"], h["got"], h["ref"], 100 * h["signed_rel_error"], h["usable"],
             h["degenerate"], h["pass"]))
    return 0 if h["pass"] else 2


def _tables(points, payload):
    lines = ["# GAP-DEM-FRICTION m15159: programmatic tables", "",
             "Generated by `scripts/m15159/run_gap_dem_friction.py --aggregate` from the",
             "committed run artifacts. Do not edit by hand.", "",
             "## Table 1 — per-point levels", "",
             "| tag | mu_p | gamma | sigma_n target [Pa] | sigma_n got [Pa] | rel err | tau [Pa] | "
             "mu_macro | mu/mu_p | drift_rel | n | steps | usable | degenerate |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in points:
        lv = p["level"]
        lines.append("| %s | %.2f | %.2f | %.0f | %.2f | %+.2f%% | %.2f | **%.4f** | %.3f | "
                     "%+.3f | %d | %d | %s | %s |"
                     % (p["tag"], p["case"]["mu_p"], p["case"]["gamma"], lv["sigma_target_pa"],
                        lv["sigma_pa"], 100 * lv["sigma_rel_err"], lv["tau_pa"],
                        lv["mu_macro"], lv["mu_over_mu_p"], lv["drift_rel"],
                        lv["n_particles"], lv["total_steps"],
                        "yes" if lv["usable"] else "no:" + "; ".join(lv["reject_reasons"]),
                        "yes" if lv["degenerate"] else "no"))
    env = payload["envelope"]
    lines += ["", "## Table 2 — Mohr-Coulomb envelope (mu_p = 0.5, steady levels only)", ""]
    if env.get("status") != "ok":
        lines.append("insufficient steady levels (%d) — envelope not fitted." % env["n_levels"])
    else:
        lines += ["| n levels | sigma levels [Pa] | tau [Pa] | tan(phi) | phi [deg] | c [Pa] | R^2 |",
                  "|---|---|---|---|---|---|---|",
                  "| %d | %s | %s | %.4f | %.2f | %.2f | %.4f |"
                  % (env["n_levels"], ", ".join("%.0f" % v for v in env["sigmas_pa"]),
                     ", ".join("%.2f" % v for v in env["taus_pa"]), env["tan_phi"],
                     env["phi_deg"], env["cohesion_pa"], env["r_squared"])]
    h = payload["headline"]
    lines += ["", "## Table 3 — benchmark (ref vs got), headline point", "",
              "| quantity | ref | got | signed err | \\|err\\| | tolerance | <10%? | usable |",
              "|---|---|---|---|---|---|---|---|",
              "| mu_macro (%s) | %.2f (band %.2f-%.2f) | %.4f | %+.2f%% | %.2f%% | %.0f%% | %s | %s |"
              % (h["case"]["geom"] + ", mu_p=%.2f" % h["case"]["mu_p"], h["ref"],
                 h["ref_band"][0], h["ref_band"][1], h["got"], 100 * h["signed_rel_error"],
                 100 * h["abs_rel_error"], 100 * h["tolerance"],
                 "**YES**" if h["within_tolerance"] else "**NO**",
                 "yes" if h["usable"] else "no"),
              "", "repro_cmd:", "", "```", h["repro_cmd"], "```", ""]
    path = os.path.join(REPO, "docs", "GAP_DEM_FRICTION_M15159_TABLES.md")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    print("tables ->", path)


def _figure(points, payload):
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:                              # pragma: no cover
        print("figure skipped:", exc)
        return
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2))
    ax = axes[0]
    for p in points:
        if p["case"]["mu_p"] != 0.5:
            continue
        ax.plot(p["history"]["strain"], p["history"]["tau_pa"], lw=1.0,
                label="%s (drift %+.2f)" % (p["tag"].split("_")[0], p["level"]["drift_rel"]))
    h = payload["headline"]
    ax.axhline(h["ref"] * h["case"]["sigma_n_pa"], ls="--", c="k", lw=0.8,
               label="ref mu=%.2f x sigma_n=%.0f Pa" % (h["ref"], h["case"]["sigma_n_pa"]))
    ax.set_xlabel("shear strain gamma [-]")
    ax.set_ylabel("platen traction tau [Pa]")
    ax.set_title("(a) tau(gamma), mu_p=0.5, sigma_n=4 kPa")
    ax.legend(fontsize=6)
    ax.grid(alpha=0.3)

    ax = axes[1]
    mus = [p["case"]["mu_p"] for p in points]
    mu = [p["level"]["mu_macro"] for p in points]
    ok = [p["level"]["usable"] and not p["level"]["degenerate"] for p in points]
    ax.plot([min(mus), max(mus)], [min(mus), max(mus)], ls=":", c="gray", label="mu_macro = mu_p")
    ax.scatter([m for m, k in zip(mus, ok) if k], [v for v, k in zip(mu, ok) if k],
               c="C0", label="usable steady state")
    ax.scatter([m for m, k in zip(mus, ok) if not k], [v for v, k in zip(mu, ok) if not k],
               c="C3", marker="x", label="rejected by gate")
    ax.axhspan(payload["anchor"]["band"][0], payload["anchor"]["band"][1], color="C2",
               alpha=0.2, label="ref band 0.36-0.40")
    ax.set_xlabel("micro friction mu_p [-]")
    ax.set_ylabel("measured mu_macro [-]")
    ax.set_title("(b) material axis")
    ax.legend(fontsize=6)
    ax.grid(alpha=0.3)

    ax = axes[2]
    lv = [(p["level"]["sigma_pa"], p["level"]["tau_pa"]) for p in points
          if p["case"]["mu_p"] == 0.5 and p["level"]["usable"] and not p["level"]["degenerate"]]
    if lv:
        ax.scatter([a for a, _ in lv], [b for _, b in lv], c="C0", label="steady (sigma_n, tau)")
    env = payload["envelope"]
    if env.get("status") == "ok":
        xs = [env["sigmas_pa"][0], env["sigmas_pa"][-1]]
        ax.plot(xs, [env["cohesion_pa"] + env["tan_phi"] * x for x in xs], c="C1",
                label="fit tan(phi)=%.3f, R2=%.4f" % (env["tan_phi"], env["r_squared"]))
    ax.set_xlabel("normal stress sigma_n [Pa]")
    ax.set_ylabel("shear stress tau [Pa]")
    ax.set_title("(c) Mohr-Coulomb envelope")
    ax.legend(fontsize=6)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    out = os.path.join(REPO, "docs", "figures")
    os.makedirs(out, exist_ok=True)
    path = os.path.join(out, "gap_dem_friction_m15159.png")
    fig.savefig(path, dpi=130)
    print("figure ->", path)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag")
    ap.add_argument("--mu", type=float, default=0.5)
    ap.add_argument("--gamma", type=float, default=1.0)
    ap.add_argument("--sigma", type=float, default=None)
    ap.add_argument("--geom", default="medium")
    ap.add_argument("--tol", type=float, default=0.15)
    ap.add_argument("--seed", type=int, default=6107)
    ap.add_argument("--aggregate", action="store_true")
    args = ap.parse_args()
    if args.sigma is not None:
        tag = args.tag or ("mu%03d_g%03d_s%05d" % (args.mu * 100, args.gamma * 100, args.sigma))
        rec = run_point(tag=tag, mu=args.mu, gamma=args.gamma, sigma=args.sigma,
                        geom=args.geom, tol=args.tol, seed=args.seed)
        print("POINT_RECORD " + json.dumps({k: rec[k] for k in ("tag", "level", "repro_cmd")}))
    return aggregate()


if __name__ == "__main__":
    raise SystemExit(main())