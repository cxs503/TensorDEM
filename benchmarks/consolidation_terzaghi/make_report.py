"""Generate ``docs/IN99_N08_consolidation_terzaghi.md`` from ``metrics.json``.

Every number in the document is read from the machine-readable evidence
(``artifacts/in99-n08/metrics.json``, ``ru_table.json``,
``consumer_assertions.json``) -- nothing is typed by hand, so the report cannot
drift away from the run that produced it.

Usage::

    PYTHONPATH=src python3 benchmarks/consolidation_terzaghi/make_report.py \
        [--metrics artifacts/in99-n08/metrics.json] [--tag NAME]
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
ART = REPO / "artifacts" / "in99-n08"


def _f(x, spec="{:.4g}"):
    if x is None:
        return "–"
    if isinstance(x, float) and (math.isnan(x) or math.isinf(x)):
        return "–"
    return spec.format(x)


def _verdict(flag: bool) -> str:
    return "PASS" if flag else "**FAIL**"


def build(metrics_path: Path, tag: str | None) -> str:
    m = json.loads(metrics_path.read_text())
    consumer_path = ART / (f"consumer_assertions_{tag}.json" if tag else "consumer_assertions.json")
    consumer = json.loads(consumer_path.read_text()) if consumer_path.exists() else None
    suffix = f"_{tag}" if tag else ""
    dem = m["dem"]
    proto = m["prototype"]
    dem_cfg = (m["dem_ensemble"][0].get("config", {}) if m.get("dem_ensemble") else {})
    anchors = m.get("anchors", {})

    L: list[str] = []
    add = L.append

    add("<!-- generated by benchmarks/consolidation_terzaghi/make_report.py "
        f"from artifacts/in99-n08/metrics{'' if not tag else '_' + tag}.json; do not edit by hand -->")
    add("")
    add("# IN99-N08 一维固结与超孔压消散验证面（TensorDEM）")
    add("")
    add(f"**机器裁决：{m['verdict']}**　"
        + "　".join(f"{k}={_verdict(v)}" for k, v in m["gates"].items()))
    add("")

    # ------------------------------------------------------------ 1. 案例
    add("## 1. 案例介绍")
    add("")
    add("**物理背景**：饱和颗粒床（矿砂/粉砂类货堆、海底砂层）在阶跃载荷下，超孔压 "
        "`u(z,t)` 按 Terzaghi 一维固结方程 `∂u/∂t = C_v ∂²u/∂z²` 消散，"
        "`C_v = k E_oed / γ_w`。液化判据链（`cargo_liquefaction_effstress`）用超孔压比 "
        "`r_u = u/Δσ` 折减 Terzaghi 有效应力 `σ' = (1-r_u)σ`，但此前 `r_u` 没有时间标度——"
        "本节点把 `r_u(t)` 与沉降-时间曲线做成**有解析锚、可反演、可被下游脚本读取**的确定性量。")
    add("")
    add("**链条**：`DEM 侧限压缩试验 → (E_oed, n, Z, k_hyd) → 组装 C_v = k E_oed/γ_w "
        "→ 两场（骨架+孔隙水）分层柱求解 U(t), s(t) → t50 反演 C_v、s_f "
        "→ 与 Fourier 级数解析锚逐点比对 → 导出 r_u(T_v) JSON → 液化判据脚本端到端断言`。")
    add("")
    add("**参数表**（全部来自 `artifacts/in99-n08/metrics" + suffix + ".json`）")
    add("")
    add("| 量 | 值 | 出处 |")
    add("|---|---|---|")
    add(f"| 颗粒半径 r | {_f(dem_cfg.get('radius'))} m | DEM 配置 |")
    add(f"| 粒径 d | {_f(dem_cfg.get('diameter'))} m | DEM 配置 |")
    add(f"| 颗粒密度 ρ_s | {_f(dem_cfg.get('density'))} kg/m³ | DEM 配置 |")
    add(f"| 接触法向刚度 k_n | {_f(dem_cfg.get('kn'))} N/m | DEM 配置（线性弹簧-阻尼 + Cundall-Strack 切向 + 滚动阻抗）|")
    add(f"| 摩擦/滚动摩擦 | {_f(dem_cfg.get('friction'))} / {_f(dem_cfg.get('mu_rolling'))} | DEM 配置 |")
    add(f"| 时间步 dt | {_f(dem_cfg.get('dt'))} s | 0.05×接触周期 |")
    add(f"| 侧限盒宽×高 | {_f(dem_cfg.get('box_width'))} m × {_f(dem_cfg.get('n_layer'))} 层 | DEM 配置 |")
    add(f"| 载荷级 Δσ | 5 → 15 kPa | DEM 配置 |")
    add(f"| 原型床厚 H | {_f(proto['height'])} m（{proto['drainage']} 排水，H_dr={_f(proto['drainage_path'])} m）| 原型 |")
    add(f"| 原型阶跃载荷 | {_f(proto['stress_step'])} Pa | 原型 |")
    add(f"| γ_w / μ_w | {_f(proto['gamma_w'])} N/m³ / {_f(proto['mu_w'])} Pa·s | 20 °C 水 |")
    add("")

    # ------------------------------------------------------------ 2. 方法
    add("## 2. 怎么做的")
    add("")
    add("1. **解析锚（独立于 DEM）**：`terzaghi.py` 实现均匀初始超孔压 + 单面排水/双面排水的 Fourier 级数 "
        "`U(T_v)=1-Σ(2/M²)e^{-M²T_v}`，`u(z,T_v)/Δσ=Σ(2/M)sin(Mz/H_dr)e^{-M²T_v}`，"
        "以及 `U<53%` 的短时分支 `√(4T_v/π)`。自检锚点："
        f"`T_v(U=0.5)={_f(anchors.get('T_v(U=0.5)'))}`（文献 0.197）、"
        f"`T_v(U=0.9)={_f(anchors.get('T_v(U=0.9)'))}`（文献 0.848）；"
        f"短时分支在全区间 `U<0.53` 与级数的最大相对差 {_f(anchors.get('sqrt_branch_vs_series_max_pct_U_below_0.53'))} %。")
    proto_dem = m.get("protocol", {})
    add("2. **DEM 侧限压缩（颗粒级）**：随机顺序沉积（RSA）+ 重力自由弛豫去重叠，床体制备协议 = "
        f"`{proto_dem.get('dem_bed_preparation', 'as-deposited')}`；随后死重活塞两级加载 5→15 kPa，逐级静力平衡后量测床高，"
        f"得侧限模量 `E_oed = Δσ/Δε_v`、孔隙率 `n`、配位数 `Z`（接触数/颗粒）。"
        "接触律复用仓库既有 3-D 颗粒内核 `granular3d_core`（线性弹簧-阻尼 + Cundall-Strack + 滚动阻抗）。")
    add("3. **渗透系数闭式**：Carman-Kozeny `k_int = n³d²/(180(1-n)²)`、`k_hyd = k_int γ_w/μ_w`，"
        "孔隙率取 DEM 实测值。**这一环是闭式文献关系，不是 DEM 量测**（见 §5 局限）。")
    add("4. **两场分层柱（`C_v` 从不作为输入）**：单元内骨架 `ε=(Δσ-u)/E_oed`、孔隙水 Darcy 通量 "
        "`q=-(k/γ_w)∂u/∂z`，饱和且颗粒不可压缩时质量守恒 `∂ε/∂t=(q_{in}-q_{out})/dz`；"
        "消元后即 `∂u/∂t=C_v∂²u/∂z²`，而 `C_v` 是由 `(k, E_oed)` 组装出来的**后验量**。"
        "显式 FV，两面排水解半床（H_dr=H/2，远端 Neumann），沉降按 `s=∫ε dz` 积分。")
    add("5. **反演**：曲线读取——`t50` 法 `C_v=T_v(U)H_dr²/t_U`（T_v(50%)=0.197，T_v(90%)=0.848，"
        "由级数反解而非查表），以及整条曲线的最小二乘拟合；`s_f` 取曲线尾平台。"
        "置信区间由 DEM 域尺寸扫描的独立实现样本传播（Student-t 95%），不是拟合残差。")
    add("6. **接口导出与下游消费**：`ru_table.py` 输出带 schema/内容 sha256/适用域裁决的 JSON；"
        "`scripts/in99_n08_liquefaction_consumer.py` 作为**独立进程**读取该表，插值 `r_u(T_v)`，"
        "送入既有液化判据 `CargoMatrix.effective_friction_angle`，并与级数锚交叉校验。")
    add("")
    add("**工具链**：Python 3.11 / NumPy / Matplotlib；`pytest tests/test_consolidation_terzaghi.py`（25 项）。")
    add("")

    # ------------------------------------------------------------ 3. 结果
    add("## 3. 计算结果")
    add("")
    add("### 3.1 C1：U(t) 与 Terzaghi 解析五点比对（判据 ≤5%）")
    add("")
    add("| T_v | U（两场柱） | U（Fourier 锚） | 偏差 % | r_u（柱） | r_u（锚） |")
    add("|---|---|---|---|---|---|")
    for p in m["C1"]["points"]:
        add(f"| {p['T_v']:.3f} | {p['U_simulated']:.6f} | {p['U_analytic']:.6f} | "
            f"{p['deviation_pct']:.4f} | {p['r_u_simulated']:.6f} | {p['r_u_analytic']:.6f} |")
    add("")
    add(f"最大偏差 **{m['C1']['max_deviation_pct']:.4f} %** ≤ {m['C1']['threshold_pct']} % → "
        f"{_verdict(m['C1']['pass'])}。")
    add("")
    add("### 3.2 C2：反演 C_v 与 s_f（判据 C_v ≤10%、s_f ≤5%）")
    add("")
    c2 = m["C2"]
    add("| 量 | 值 | 基准/参考 | 偏差 % | 判据 |")
    add("|---|---|---|---|---|")
    add(f"| C_v（t50 反演） | {_f(c2['C_v_inverted_t50'],'{:.6g}')} m²/s | "
        f"{_f(c2['C_v_assembled'],'{:.6g}')} m²/s（k·E_oed/γ_w） | {c2['C_v_deviation_pct']:.4f} | ≤10 % |")
    add(f"| C_v（整曲线拟合） | {_f(c2['C_v_inverted_fit'],'{:.6g}')} m²/s | 同上 | "
        f"{c2['C_v_fit_deviation_pct']:.4f} | ≤10 % |")
    add(f"| s_f（曲线平台） | {_f(c2['s_f_simulated'],'{:.6g}')} m | {_f(c2['s_f_analytic'],'{:.6g}')} m"
        f"（ΔσH/E_oed） | {c2['s_f_deviation_pct']:.4f} | ≤5 % |")
    add(f"| t50 / t90（反演） | {_f(c2['t50_inverted'],'{:.6g}')} / {_f(c2['t90_inverted'],'{:.6g}')} s | "
        f"T_v(50%)=0.197, T_v(90%)=0.848 | – | – |")
    add(f"| 反演残差 RMS | {_f(c2['inversion_residual_rms'],'{:.3g}')} | – | – | – |")
    add("")
    add(f"→ {_verdict(c2['pass'])}。")
    add("")
    add("### 3.3 C3：颗粒数/域尺寸与网格扫描（判据 U 漂移 ≤5%）")
    add("")
    c3 = m["C3"]
    add("**(a) 流体域网格细化**（固定 `C_v`，单元数 20/40/80）")
    add("")
    add("| 单元数 | U 漂移 vs 最细网格 % |")
    add("|---|---|")
    for run in c3["column_refinement"]["runs"]:
        add(f"| {run['n_cells']} | {run['drift_vs_finest_pct']:.5f} |")
    add("")
    add("**(b) DEM 域尺寸（颗粒数）扫描**：同一粒径/床高、加宽侧限盒（相同种子族）")
    add("")
    add("| 颗粒数 | n | Z | E_oed (Pa) | k_hyd (m/s) | C_v (m²/s) | 固定时刻 U 漂移 % | 参考实现 |")
    add("|---|---|---|---|---|---|---|---|")
    for c in c3["dem_particle_scan"]["curves"]:
        add(f"| {c['particle_count']} | {c['porosity']:.4f} | {_f(c.get('coordination'),'{:.2f}')} | "
            f"{_f(c['E_oed'],'{:.4g}')} | {_f(c['k_hyd'],'{:.3g}')} | {_f(c['C_v'],'{:.4g}')} | "
            f"{c['U_drift_vs_reference_pct']:.3f} | {'是' if c.get('is_reference') else ''} |")
    add("")
    add(f"合成漂移 max(网格, DEM) = **{c3['max_drift_pct']:.3f} %**，判据 {c3['threshold_pct']} % → "
        f"{_verdict(c3['pass'])}。")
    add("")
    add(f"扫描几何：`{proto_dem.get('dem_scan_geometry', '-')}`；"
        f"参考实现取颗粒数最大的一档（边界约束份额最小，见 §5）。")
    add("")
    # cross-protocol sensitivity (only tables that exist; never used to re-grade)
    others = []
    for tag_ in ("aspect", "compacted"):
        p_ = ART / f"metrics_{tag_}.json"
        if p_.exists():
            others.append((tag_, json.loads(p_.read_text())))
    if others:
        add("**协议敏感性（不作为事后择优依据）**：同一套代码在另外两种床体制备/扫描几何下的结果，"
            "用来量化 §5 第 4 条的“量级 vs 三位有效数字”：")
        add("")
        add("| 协议/扫描几何 | 参考实现颗粒数 | E_oed (Pa) | C_v (m²/s) | DEM 域尺寸漂移 % | C3 |")
        add("|---|---|---|---|---|---|")
        add(f"| 默认（as-deposited，n_layer=5）| {m['dem']['particle_count']} | "
            f"{_f(m['dem']['E_oed'],'{:.4g}')} | {_f(m['C_v_assembled'],'{:.4g}')} | "
            f"{c3['dem_particle_scan']['drift_pct']:.2f} | {_verdict(c3['pass'])} |")
        for tag_, mm in others:
            add(f"| {tag_} | {mm['dem']['particle_count']} | {_f(mm['dem']['E_oed'],'{:.4g}')} | "
                f"{_f(mm['C_v_assembled'],'{:.4g}')} | "
                f"{mm['C3']['dem_particle_scan']['drift_pct']:.2f} | {_verdict(mm['C3']['pass'])} |")
        add("")
        add("各协议的逐档数值：")
        add("")
        add("| 协议 | 颗粒数 | n | Z | E_oed (Pa) | k_hyd (m/s) |")
        add("|---|---|---|---|---|---|")
        for label, mm in [("default", m)] + list(others):
            for c in mm["C3"]["dem_particle_scan"]["curves"]:
                add(f"| {label} | {c['particle_count']} | {c['porosity']:.4f} | "
                    f"{_f(c.get('coordination'),'{:.2f}')} | {_f(c['E_oed'],'{:.4g}')} | "
                    f"{_f(c['k_hyd'],'{:.3g}')} |")
        add("")
    add("")
    add("### 3.4 DEM 侧限压缩量测（两条载荷级）")
    add("")
    add("| 颗粒数 | n_row×n_layer | 阶段 σ (kPa) | 床高 (mm) | n | Z | 是否平衡 |")
    add("|---|---|---|---|---|---|---|")
    for row in m["dem_ensemble"]:
        spec = row.get("scan_spec", {})
        for st in row.get("stages", []):
            add(f"| {row['particle_count']} | {spec.get('n_row','–')}×{spec.get('n_layer','–')} | "
                f"{st['stress']/1e3:.1f} | {st['height']*1e3:.5f} | {st['porosity']:.4f} | "
                f"{st['coordination']:.2f} | {'是' if st['reached'] else '否'} |")
    add("")
    add(f"参考实现（第一行）：E_oed = {_f(dem['E_oed'],'{:.4g}')} Pa，Δε_v = {_f(dem['strain_increment'],'{:.3e}')}，"
        f"n = {dem['porosity']:.4f}，Z = {dem['coordination']:.2f}，"
        f"k_hyd = {_f(dem['k_hyd'],'{:.4g}')} m/s，组装 C_v = {_f(m['C_v_assembled'],'{:.4g}')} m²/s。")
    add("")
    add("### 3.5 适用域裁决（fail-closed）")
    add("")
    add("| 门 | 值 | 限制 | 结果 | 类型 |")
    add("|---|---|---|---|---|")
    for name, gate in m["applicability"]["gates"].items():
        kind = "阻断" if gate.get("blocking", True) else "建议"
        add(f"| {name} | {gate['value']} | {gate['limit']} | {'通过' if gate['pass'] else '未通过'} | {kind} |")
    add("")
    re_ = m["reynolds"]
    add(f"原型孔流雷诺数：`i = Δσ/(γ_w H_dr) = {re_['gradient']:.4g}`，"
        f"`v_s = k i = {re_['darcy_velocity']:.4g} m/s`，`Re_p = {re_['Re_p']:.4g}`。"
        "（DEM 元胞仅毫米级，其自身水力梯度无物理意义，故达西门在**原型几何**上取证。）")
    add("")
    if m["applicability"].get("advisories"):
        add("建议级提示：" + "；".join(m["applicability"]["advisories"]))
        add("")
    add("### 3.6 导出的 r_u(T_v) 接口表")
    add("")
    tab = m["r_u_table"]
    add(f"- 文件：`{m['r_u_table_file']['path']}`，schema `{tab['schema']}`，"
        f"sha256 `{m['r_u_table_file']['sha256'][:32]}…`（{m['r_u_table_file']['bytes']} B，"
        f"内容哈希自校验={'一致' if m['r_u_table_file']['recomputed_sha256_matches'] else '不一致'}）")
    ci = tab.get("C_v_confidence", {})
    add(f"- `C_v = {_f(tab['C_v_m2_s'],'{:.6g}')} m²/s`，"
        f"95% 置信区间 [{_f(ci.get('ci_low'),'{:.6g}')}, {_f(ci.get('ci_high'),'{:.6g}')}]，"
        f"n={ci.get('n')}，相对标准误 {_f(ci.get('relative_se'),'{:.3%}')}")
    add("- 采样（节选）：")
    add("")
    add("| T_v | U | r_u（深度平均） | r_u（中面/不透水面） |")
    add("|---|---|---|---|")
    idx = [i for i in range(len(tab["T_v"])) if i % max(1, len(tab["T_v"]) // 8) == 0][:8]
    for i in idx:
        add(f"| {tab['T_v'][i]:.4g} | {tab['U_analytic'][i]:.5f} | "
            f"{tab['r_u_average'][i]:.5f} | {tab['r_u_midplane'][i]:.5f} |")
    add("")
    add("### 3.7 C4：下游脚本端到端断言")
    add("")
    c4 = m.get("C4", {})
    if c4.get("ran"):
        add(f"消费脚本 `scripts/in99_n08_liquefaction_consumer.py` 以独立进程读取 `{c4['table_read']}`"
            f"（sha256 前缀 `{str(c4.get('table_sha256'))[:16]}…`），"
            f"断言 {sum(a['passed'] for a in c4['assertions'])}/{len(c4['assertions'])} 通过；"
            f"液化窗口在 `T_v = {_f(c4.get('liquefaction_window_T_v'),'{:.4g}')}` 关闭。")
        add("")
        add("| 断言 | 结果 | 值 |")
        add("|---|---|---|")
        for a in c4["assertions"]:
            val = json.dumps(a.get("value"), ensure_ascii=False)
            if len(val) > 90:
                val = val[:87] + "…"
            add(f"| `{a['name']}` | {'PASS' if a['passed'] else 'FAIL'} | {val} |")
    else:
        add("消费脚本未运行。")
    add("")

    # ------------------------------------------------------------ 4. 图
    add("## 4. 结果图")
    add("")
    for fig in m.get("figures", []):
        name = fig["file"]
        if suffix and suffix not in name:
            continue
        add(f"**{name}** — {fig['caption']}")
        add("")
        add(f"![{name}](artifacts/in99-n08/figures/{name})")
        add("")
    add("图 1：C1 判据——两场柱 `U(T_v)` 与 Fourier 锚逐点对比（左）；右图为负对照：把 `E_oed` 偏 ±20 % 后"
        "在**固定物理时刻**轴上的偏离，用来证明该门不是空门（若 5 % 还不报警，判据就没有鉴别力）。")
    add("")
    add("图 2：C2——沉降-时间曲线与一维压缩解析 `s_f·U(T_v)` 对比。")
    add("")
    add("图 3：超孔压剖面 `r_u(z/H_dr)`（点=两场柱，线=级数锚）。")
    add("")
    add("图 4：DEM 侧限压缩两级状态与域尺寸扫描。")
    add("")
    add("图 5：导出的 `r_u(T_v)` 接口（含 `C_v` 置信区间）。")
    add("")

    # ------------------------------------------------------------ 5. 注意点
    add("## 5. 注意点（踩过的坑、局限、适用范围）")
    add("")
