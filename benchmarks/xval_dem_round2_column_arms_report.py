#!/usr/bin/env python
"""XVAL · CASE-COLUMN-COLLAPSE macro arm: tables + figures from ``column_arms.json``.

Consumes the artefact written by ``benchmarks/xval_dem_round2_column_arms.py``
(module-level column collapse, three rolling-resistance conventions) and emits

    artifacts/xval_dem_round2_column_arms/table_macro.md
    artifacts/xval_dem_round2_column_arms/fig1_runout_arms.png
    artifacts/xval_dem_round2_column_arms/fig2_effective_rolling_cap.png
    artifacts/xval_dem_round2_column_arms/verdict.json

Every number in the markdown/verdict is read from the JSON: nothing is typed by
hand.  The analytic panel (fig2) is the lever/cap arithmetic of
``docs/XVAL_DEM_ROUND2_METHOD_SELECTION.md`` §E3, computed from the frozen
material parameters, not a simulation result.

Usage: PYTHONPATH=src python benchmarks/xval_dem_round2_column_arms_report.py
"""
from __future__ import annotations

import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN = os.path.join(ROOT, "artifacts", "xval_dem_round2_method_selection", "column_arms.json")
OUT = os.path.join(ROOT, "artifacts", "xval_dem_round2_column_arms")
BAND = 0.15          # owner precision standard: |err| > 15 % unacceptable
TARGET = 2.106       # certified legacy runout of the frozen a = 1 column
ARM_ORDER = ("legacy_mu0.5", "oss_naive_mu0.5", "oss_mapped_mu1.0")


def _pct(x: float) -> str:
    return f"{100.0 * x:+.2f} %"


def main() -> None:
    with open(IN) as fh:
        res = json.load(fh)
    os.makedirs(OUT, exist_ok=True)

    ref = res["reference"]["runout_ratio"]
    arms = res["arms"]
    lacking = [a for a in ARM_ORDER if a not in arms]
    if lacking:
        raise SystemExit(f"column_arms.json missing arms: {lacking}")

    verdict = {
        "reference_lube_a1": ref,
        "certified_legacy_runout": TARGET,
        "band_rel": BAND,
        "arms": {},
    }
    for name in ARM_ORDER:
        rec = arms[name]
        verdict["arms"][name] = {
            "rolling_lever": rec["rolling_lever"],
            "mu_rolling": rec["mu_rolling"],
            "runout_ratio": rec["runout_ratio"],
            "err_vs_lube_rel": rec["runout_err_vs_lube"],
            "diff_vs_legacy_rel": rec["runout_rel_diff_vs_legacy"],
            "diff_vs_certified_legacy_rel": (rec["runout_ratio"] - TARGET) / TARGET,
            "within_band_vs_lube": abs(rec["runout_err_vs_lube"]) <= BAND,
            "within_band_vs_certified": abs(rec["runout_ratio"] - TARGET) / TARGET <= BAND,
            "n_particles": rec["n_particles"],
            "elapsed_s": rec["elapsed_s"],
        }

    # --- table -------------------------------------------------------------
    lines = [
        "| arm | lever | mu_r | runout r_inf/r_i | err vs Lube (%.3f) | diff vs legacy | in ±15%% |"
        % ref,
        "|---|---|---|---|---|---|---|",
    ]
    for name in ARM_ORDER:
        v = verdict["arms"][name]
        lines.append(
            f"| `{name}` | {v['rolling_lever']} | {v['mu_rolling']:.2f} | "
            f"{v['runout_ratio']:.4f} | {_pct(v['err_vs_lube_rel'])} | "
            f"{_pct(v['diff_vs_legacy_rel'])} | {'yes' if v['within_band_vs_lube'] else 'NO'} |"
        )
    table = "\n".join(lines)
    with open(os.path.join(OUT, "table_macro.md"), "w") as fh:
        fh.write("# XVAL-DEM-ROUND2-METHOD-SELECTION · macro arm (a = 1 column)\n\n")
        fh.write(table + "\n\n")
        fh.write("Generated by `benchmarks/xval_dem_round2_column_arms_report.py` "
                 "from `column_arms.json`; no hand-typed numbers.\n")
    with open(os.path.join(OUT, "verdict.json"), "w") as fh:
        json.dump(verdict, fh, indent=2, sort_keys=True)

    # --- fig 1: runout per arm vs Lube reference band ----------------------
    fig, ax = plt.subplots(figsize=(6.4, 4.2))
    xs = range(len(ARM_ORDER))
    vals = [verdict["arms"][a]["runout_ratio"] for a in ARM_ORDER]
    ax.axhspan(ref * (1 - BAND), ref * (1 + BAND), color="0.85",
               label=f"Lube 2004 ±15 % ({ref * (1 - BAND):.2f}–{ref * (1 + BAND):.2f})")
    ax.axhline(ref, color="k", ls="--", lw=1.0, label=f"Lube 2004 a=1: {ref:.3f}")
    ax.axhline(TARGET, color="tab:red", ls=":", lw=1.0,
               label=f"certified legacy: {TARGET:.3f}")
    bars = ax.bar(list(xs), vals, width=0.55,
                  color=["tab:blue", "tab:orange", "tab:green"])
    for b, a in zip(bars, ARM_ORDER):
        v = verdict["arms"][a]
        ax.text(b.get_x() + b.get_width() / 2, b.get_height() + 0.02,
                f"{v['runout_ratio']:.3f}\n({_pct(v['err_vs_lube_rel'])})",
                ha="center", va="bottom", fontsize=8)
    ax.set_xticks(list(xs))
    ax.set_xticklabels([a.replace("_", "\n") for a in ARM_ORDER], fontsize=8)
    ax.set_ylabel("runout ratio  $r_\\infty / r_i$")
    ax.set_title("Axisymmetric column collapse (a=1): rolling-lever convention arm")
    ax.set_ylim(0, max(vals + [ref]) * 1.25)
    ax.legend(fontsize=7, loc="lower right")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "fig1_runout_arms.png"), dpi=150)
    plt.close(fig)

    # --- fig 2: analytic lever / cap arithmetic per contact kind -----------
    base = res["base"]
    r, kn, kt_ratio, mu_r = base["radius"], base["kn"], base["kt_ratio"], 0.5
    kt = kt_ratio * kn
    kinds = ("pair", "wall")
    legacy = {"pair": (r, mu_r * r, kt * r ** 2), "wall": (r, mu_r * r, kt * r ** 2)}
    mapped = {"pair": (0.5 * r, 1.0 * 0.5 * r, kt * (0.5 * r) ** 2),
              "wall": (r, 1.0 * r, kt * r ** 2)}
    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.6))
    for ax, idx, title in ((axes[0], 1, "torque cap  $\\mu_r F_n r_{eff}$ [N·m]"),
                           (axes[1], 2, "rolling stiffness  $k_r = k_t r_{eff}^2$ [N·m]")):
        x = range(len(kinds))
        lv = [legacy[k][idx] for k in kinds]
        mv = [mapped[k][idx] for k in kinds]
        w = 0.36
        ax.bar([i - w / 2 for i in x], lv, width=w, label="legacy (mu_r=0.5, r)")
        ax.bar([i + w / 2 for i in x], mv, width=w,
               label="oss_mapped (mu_r=1.0, reduced)")
        for i, (a, b) in enumerate(zip(lv, mv)):
            ax.text(i - w / 2, a, f"{a:.3g}", ha="center", va="bottom", fontsize=7)
            ax.text(i + w / 2, b, f"{b:.3g}", ha="center", va="bottom", fontsize=7)
            ax.text(i, max(a, b) * 1.18, f"{b / a:.2f}×", ha="center", fontsize=8,
                    color="tab:red")
        ax.set_xticks(list(x))
        ax.set_xticklabels(kinds)
        ax.set_title(title, fontsize=9)
        ax.legend(fontsize=7)
        ax.grid(axis="y", alpha=0.3)
    fig.suptitle("Where the mu_r->2mu_r mapping is exact (pair cap) and where it is not "
                 "(stiffness, wall)", fontsize=9)
    fig.tight_layout()
    fig.savefig(os.path.join(OUT, "fig2_effective_rolling_cap.png"), dpi=150)
    plt.close(fig)

    print(table)
    print(json.dumps(verdict, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()