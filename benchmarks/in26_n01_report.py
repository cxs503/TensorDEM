"""IN26-N01 report generator: artifact -> paper-grade results section.

Reads ``artifacts/in26_n01/acceptance.json`` (written by
``benchmarks/in26_n01_compaction_acceptance.py``) and regenerates the results
tables of ``docs/IN26_N01_floe_compaction.md`` between the ``<!-- RESULTS -->``
markers.  Nothing is transcribed by hand: every number below comes from the JSON.

Usage
-----
    PYTHONPATH=src python benchmarks/in26_n01_report.py \
        --artifact artifacts/in26_n01/acceptance.json \
        --doc docs/IN26_N01_floe_compaction.md
"""
from __future__ import annotations

import argparse
import json
import os
from typing import Dict, List


def _table(header: List[str], rows: List[List[str]]) -> str:
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        out.append("| " + " | ".join(row) + " |")
    return "\n".join(out)


def build(payload: Dict[str, object]) -> str:
    sweep = payload["sweep"]
    locks = payload["monodisperse_locks"]
    negative = payload.get("negative_result") or []
    tests = payload.get("tests") or {}
    verdict = payload["verdict"]
    chi = payload["settings"]

    blocks: List[str] = []
    blocks.append(f"*generated by* `benchmarks/in26_n01_report.py` *from* "
                  f"`{payload.get('artifact', 'artifacts/in26_n01/acceptance.json')}` "
                  f"*— git* `{payload['git_rev'][:12]}`*, python* "
                  f"`{payload['environment']['python']}`*, numpy* "
                  f"`{payload['environment']['numpy']}`*, "
                  f"{payload['generated_utc']}*")
    blocks.append("")
    blocks.append(f"Sweep: N = {chi['n_floes']} floes, seeds {chi['seeds']}, "
                  f"phi {chi['phis']}, families {chi['families']}, "
                  f"raster resolution {chi['resolution']}^2, "
                  f"contact threshold {chi['contact_gap']} m.")

    # ---- criterion (a) + (b) table -------------------------------------
    blocks.append("")
    blocks.append("### 3.1 Criteria (a) coverage and (b) no overlap — per field")
    rows = []
    for rec in sweep:
        con = rec["consolidated"]
        rows.append([
            rec["family"], f"{rec['phi']:.2f}", str(rec["seed"]),
            f"{rec['coverage_deviation_nominal']:.2e}",
            f"{rec['coverage_deviation_union']:.2e}",
            f"{con['nominal_coverage']:.9f}",
            f"{con['max_overlap']:.2e}",
            f"{rec['wall_s']['consolidated']:.1f}",
        ])
    blocks.append(_table(
        ["FSD", "phi", "seed", "cov. dev. (nominal)", "cov. dev. (raster union)",
         "realised phi", "max overlap [m]", "wall [s]"], rows))

    # ---- contact network table -----------------------------------------
    blocks.append("")
    blocks.append("### 3.2 The capability this node exists for: a contact network")
    rows = []
    for rec in sweep:
        con = rec["consolidated"]
        buf = rec["buffer"]
        rows.append([
            rec["family"], f"{rec['phi']:.2f}", str(rec["seed"]),
            str(buf["contacts"]), str(con["contacts"]),
            f"{buf['coordination']:.2f}", f"{con['coordination']:.2f}",
            f"{rec['construction']['coordination_consolidated']:.2f}",
            str(con["clusters"]), "yes" if con["percolating"] else "no",
            f"{rec['construction']['consolidated_area_fraction']:.3f}",
            f"{rec['construction']['lead_coverage_realised']:.4f}",
        ])
    blocks.append(_table(
        ["FSD", "phi", "seed", "contacts (buffered)", "contacts (consolidated)",
         "Z buffered", "Z", "Z consolidated zone", "clusters", "percolating",
         "consolidated area frac.", "lead phi (realised)"], rows))

    # ---- criterion (c) --------------------------------------------------
    blocks.append("")
    blocks.append("### 3.3 Criterion (c): monodisperse / H1 regression lock")
    mono = locks["monodisperse_consolidated"]
    h1 = locks["h1_lattice"]
    rows = [
        ["bit-for-bit vs IN32-N01 generator (arrays + SHA-256)",
         "identical", "yes" if locks["bit_for_bit_vs_in32_generator"] else "NO"],
        ["frozen monodisperse field digest",
         f"`{locks['monodisperse_field_digest'][:16]}…"
         f"{locks['monodisperse_field_digest'][-8:]}`", "recorded in the test-suite"],
        ["H1 single-dispersion field", f"method `{h1['method']}`, "
         f"N={h1['floe_count']}, digest `{h1['field_digest'][:12]}…`",
         "deterministic" if h1["deterministic"] else "NO"],
        ["monodisperse consolidated field: r_eq mean / relative spread",
         f"{mono['r_eq_mean']:.9f} m / {mono['r_eq_rel_spread']:.2e}",
         "yes" if mono["r_eq_rel_spread"] < 5e-3 else "NO"],
        ["monodisperse consolidated field: contacts / Z / percolating",
         f"{mono['contacts']} / {mono['coordination']:.2f} / "
         f"{'yes' if mono['percolating'] else 'no'}",
         "yes" if mono["contacts"] > 0 and mono["percolating"] else "NO"],
    ]
    blocks.append(_table(["item", "measured", "verdict"], rows))

    # ---- criterion (d) --------------------------------------------------
    blocks.append("")
    blocks.append("### 3.4 Criterion (d): pytest")
    if tests.get("skipped") or not tests:
        blocks.append("_not run in this invocation_")
    else:
        blocks.append(_table(
            ["quantity", "value"],
            [["command", f"`{tests['command']}`"],
             ["exit code", str(tests["returncode"])],
             ["passed cases", str(tests["passed"])],
             ["summary line", f"`{tests['summary']}`"],
             ["wall [s]", f"{tests['wall_s']:.1f}"]]))

    # ---- negative result ------------------------------------------------
    blocks.append("")
    blocks.append("### 3.5 Honest negative result: homogeneous compaction does not work")
    if negative:
        rows = []
        for rec in negative:
            rows.append([
                f"{rec['phi']:.2f}", str(rec["steps"]),
                f"{rec['energy_initial']:.4f}", f"{rec['energy_final']:.4f}",
                f"{rec['coordination']:.2f}", str(rec["clusters"]),
                "yes" if rec["percolating"] else "no",
                f"{rec['largest_cluster_fraction']:.3f}",
                f"{rec['residual_overlap']:.2e}", f"{rec['wall_s']:.1f}",
            ])
        blocks.append(_table(
            ["phi", "iterations", "E initial", "E final", "Z", "clusters",
             "percolating", "largest cluster frac.", "residual overlap [m]",
             "wall [s]"], rows))
        blocks.append("")
        blocks.append("Isotropic pair attraction in a periodic box with fixed floe "
                     "areas cancels by symmetry: the free area cannot migrate into a "
                     "lead, so the field stalls in a lightly-touching, non-percolating "
                     "state. The consolidated-zone construction replaces that drive by "
                     "an area budget — see §2.4.")

    # ---- verdict --------------------------------------------------------
    blocks.append("")
    blocks.append("### 3.6 Verdict")
    rows = [[k, "PASS" if v.get("pass") else "FAIL",
             str({kk: vv for kk, vv in v.items() if kk != "pass"})]
            for k, v in verdict.items() if k != "all_pass"]
    blocks.append(_table(["criterion", "verdict", "threshold / detail"], rows))
    blocks.append("")
    blocks.append(f"**all_pass = {verdict['all_pass']}** "
                  f"(total harness wall time {payload['wall_s']:.1f} s)")
    return "\n".join(blocks)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--artifact", default="artifacts/in26_n01/acceptance.json")
    ap.add_argument("--doc", default="docs/IN26_N01_floe_compaction.md")
    ap.add_argument("--section-out", default=None)
    args = ap.parse_args()
    with open(args.artifact) as fh:
        payload = json.load(fh)
    payload["artifact"] = args.artifact
    text = build(payload)
    if args.section_out:
        out = args.section_out
    else:
        out = args.doc
        with open(out) as fh:
            doc = fh.read()
        start = doc.index("<!-- RESULTS:START -->")
        end = doc.index("<!-- RESULTS:END -->")
        head, tail = doc[:start], doc[end:]
        doc = (head + "<!-- RESULTS:START -->\n" + text + "\n"
               + "<!-- RESULTS:END -->" + tail)
        with open(out, "w") as fh:
            fh.write(doc)
        print(f"results injected into {out}")
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(out)) or ".", exist_ok=True)
    with open(out, "w") as fh:
        fh.write(text + "\n")
    print(f"results written to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())