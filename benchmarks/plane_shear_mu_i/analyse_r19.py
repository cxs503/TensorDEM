"""Round 19 (m21228) analysis + figures for the higher-N resolution study.

Reads ``runs/high_n/result.json`` (written by ``high_n_sweep.py --assemble``)
and writes, next to it:

* ``tables.md``   -- every number in the round-19 report, programmatically
* ``fig_mu_i_r19.png``  -- mu(I): simulation vs reference, both abscissae
* ``fig_phi_i_r19.png`` -- phi(I): three estimators vs reference band

No number in the report is hand-copied: the markdown tables are generated by
this script and the report injects them.

Usage::

    PYTHONPATH=src python benchmarks/plane_shear_mu_i/analyse_r19.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
for p in (HERE, HERE.parents[1] / "src"):
    if str(p) not in sys.path:
        sys.path.insert(0, str(p))

import numpy as np  # noqa: E402
from reference_law import I_0, MU_2, MU_S, PHI_MAX, PHI_MIN, ref_mu, ref_phi  # noqa: E402

RUNS = HERE / "runs" / "high_n"
TOL_PCT = 10.0


def _sci(v):
    if v is None:
        return "n/a"
    try:
        return f"{float(v):.2e}"
    except (TypeError, ValueError):
        return str(v)


def _f(v, nd=4):
    if v is None:
        return "n/a"
    try:
        f = float(v)
    except (TypeError, ValueError):
        return str(v)
    if np.isnan(f):
        return "n/a"
    return f"{f:.{nd}f}"


def main() -> int:
    res = json.loads((RUNS / "result.json").read_text())
    rows = sorted(res["rows"], key=lambda r: r["I_target"])

    # ---------------- tables -------------------------------------------
    lines = ["# Round 19 (m21228) — higher-N plane shear: injected tables", ""]
    lines += [
        f"* point files: {len(rows)}   tolerance band: {TOL_PCT:g} %",
        f"* P1 noise floor: **{res['P1_noise_floor']}**   "
        f"P2 mu convergence: **{res['P2_mu_convergence']}**   "
        f"mu within 10 % (full curve): **{res['mu_within_10pct_full']}**   "
        f"phi within 10 % (full curve): **{res.get('phi_within_10pct_full')}**",
        f"* worst |err mu|: {_f(res['worst_mu_err_pct'], 1)} %   "
        f"worst |err phi|: {_f(res.get('worst_phi_err_pct'), 1)} %",
        "",
        "## mu(I), measured-rate abscissa (primary)", "",
        "| I_target | I_imposed | I_measured | N | mu_meas | mu_ref | err \\[%\\] "
        "| mu std \\[%\\] |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {_f(r['I_target'], 3)} | {_f(r.get('I_imposed_rate'))} "
            f"| {_f(r.get('I_measured_rate'))} | {_f(r.get('n_particles'), 0)} "
            f"| {_f(r['mu_meas'])} | {_f(r['mu_ref'])} "
            f"| {_f(r['err_mu_pct'], 1)} | {_f(r['mu_std_rel_pct'], 1)} |")
    lines += ["", "## mu(I), platen-rate abscissa (what rounds 12-18 reported)", "",
              "| I_target | mu_meas | mu_ref | err \\[%\\] |", "|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {_f(r['I_target'], 3)} | {_f(r['mu_meas'])} "
                     f"| {_f(r.get('mu_ref_at_imposed_I'))} "
                     f"| {_f(r.get('err_mu_pct_at_imposed_I'), 1)} |")
    lines += ["", "## phi(I): estimators and reference", "",
              "| I_target | phi_bed_steady | phi_extent | phi_container "
              "| phi_ref | err \\[%\\] |", "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| {_f(r['I_target'], 3)} | {_f(r['phi_meas'])} "
            f"| {_f(r.get('phi_extent_final'))} "
            f"| {_f(r.get('phi_container_final'))} "
            f"| {_f(r['phi_ref'])} | {_f(r['err_phi_pct'], 1)} |")
    lines += ["", "## control / kinematics", "",
              "| I_target | P err \\[%\\] | shear-rate ratio | strain | dt | "
              "shear steps | servo valid |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(
            f"| {_f(r['I_target'], 3)} | {_f(100.0 * (r.get('pressure_control_error') or 0.0), 2)} "
            f"| {_f(r.get('shear_rate_ratio'), 3)} | {_f(r.get('shear_strain_achieved'), 3)} "
            f"| {_sci(r.get('dt'))} "
            f"| {_f(r.get('shear_steps'), 0)} "
            f"| {r.get('servo_valid')} |")
    (RUNS / "tables.md").write_text("\n".join(lines) + "\n")

    # ---------------- figure 1: mu(I) ----------------------------------
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12.4, 4.8))
    Icurve = np.logspace(-3, 0, 300)
    ax1.plot(Icurve, ref_mu(Icurve), "k-", lw=1.6,
             label=rf"ref: $\mu_s$={MU_S}, $\mu_2$={MU_2}, $I_0$={I_0}")
    ax1.plot(Icurve, ref_mu(Icurve) * (1 + TOL_PCT / 100), "k--", lw=0.9,
             label="ref $\\pm$10 %")
    ax1.plot(Icurve, ref_mu(Icurve) * (1 - TOL_PCT / 100), "k--", lw=0.9)
    ax1.fill_between(Icurve, ref_mu(Icurve) * 0.9, ref_mu(Icurve) * 1.1,
                     color="0.85", zorder=0)
    xs = [r.get("I_measured_rate") or r["I_target"] for r in rows]
    ax1.errorbar(xs, [r["mu_meas"] for r in rows],
                 yerr=[r["mu_meas"] * r["mu_std_rel_pct"] / 100.0 for r in rows],
                 fmt="o", ms=7, color="tab:red", capsize=3,
                 label="N$\\approx$1300, measured-$I$ abscissa")
    xi = [r.get("I_imposed_rate") or r["I_target"] for r in rows]
    ax1.plot(xi, [r["mu_meas"] for r in rows], "s", ms=6, mfc="none",
             color="tab:blue", label="same points, platen-$I$ abscissa")
    for r, x, y in zip(rows, xs, [r["mu_meas"] for r in rows]):
        ax1.annotate(f"{r['err_mu_pct']:+.0f}%", (x, y),
                     textcoords="offset points", xytext=(6, 6), fontsize=8)
    ax1.set_xscale("log")
    ax1.set_xlabel("inertial number $I$")
    ax1.set_ylabel(r"effective friction $\mu$")
    ax1.set_title("(a) $\\mu(I)$ vs da Cruz 2005 / GDR MiDi")
    ax1.grid(alpha=0.3, which="both")
    ax1.legend(fontsize=8, loc="lower right")

    # residual panel: both abscissae
    labels = [f"{r['I_target']:g}" for r in rows]
    idx = np.arange(len(rows))
    ax2.axhspan(-TOL_PCT, TOL_PCT, color="0.85", label="$\\pm$10 % band")
    ax2.axhline(0, color="k", lw=0.8)
    ax2.plot(idx, [r["err_mu_pct"] for r in rows], "o-", color="tab:red",
             label="measured-$I$ abscissa")
    ax2.plot(idx, [r.get("err_mu_pct_at_imposed_I", np.nan) for r in rows],
             "s--", color="tab:blue", label="platen-$I$ abscissa")
    ax2.set_xticks(idx, labels)
    ax2.set_xlabel("$I_{target}$")
    ax2.set_ylabel("$\\mu$ residual [%]")
    ax2.set_title("(b) residual: does the abscissa explain the deficit?")
    ax2.grid(alpha=0.3)
    ax2.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(RUNS / "fig_mu_i_r19.png", dpi=150)
    plt.close(fig)

    # ---------------- figure 2: phi(I) ---------------------------------
    fig, ax = plt.subplots(figsize=(7.4, 4.8))
    Icurve = np.logspace(-3, 0, 300)
    ax.plot(Icurve, ref_phi(Icurve), "k-", lw=1.6,
            label=rf"ref: $\phi_{{max}}$={PHI_MAX}, $\phi_{{min}}$={PHI_MIN} "
                  "(provenance-unverified)")
    xs = [r.get("I_measured_rate") or r["I_target"] for r in rows]
    for key, style, lab in (("phi_meas", "o-", "phi_bed_steady (container)"),
                            ("phi_extent_final", "s--", "phi_extent"),
                            ("phi_container_final", "^:", "phi_container final")):
        ys = [r.get(key) for r in rows]
        if any(v is None for v in ys):
            continue
        ax.plot(xs, ys, style, ms=6, label=lab)
    ax.set_xscale("log")
    ax.set_xlabel("inertial number $I$ (measured rate)")
    ax.set_ylabel(r"solid fraction $\phi$")
    ax.set_title("$\\phi(I)$: estimator spread vs unverified reference")
    ax.grid(alpha=0.3, which="both")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(RUNS / "fig_phi_i_r19.png", dpi=150)
    plt.close(fig)

    print((RUNS / "tables.md").read_text())
    print("wrote", RUNS / "fig_mu_i_r19.png", RUNS / "fig_phi_i_r19.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())