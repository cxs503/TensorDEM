"""Axial capillary (liquid-bridge) force between two equal spheres.

Three force laws live here, in increasing order of fidelity:

1. ``seeded_campaign_force`` -- the closed form *as written in the P35-N2 task
   brief*::

       F = 2 pi R gamma cos(theta) [ 1/(1 + s/(2h)) - 1/sqrt(1 + s/h) ]

   It is kept in the code base **on purpose** and is falsified in
   ``tests/test_wet_ice_cohesion.py``: the bracket vanishes at ``s = 0``, so the
   expression predicts *zero* capillary force for two touching spheres and has an
   interior maximum, whereas the exact Young-Laplace solution gives the largest
   attraction at contact (``F(0) ~ 0.74-0.90 * 2 pi gamma R cos(theta)``) and
   decreases monotonically with separation.  The campaign records this as an
   honest FAIL of the seeded formula (criterion g) and ships law 3 instead.

2. ``small_bridge_limit`` -- the classical asymptotic anchor
   ``F -> 2 pi gamma R cos(theta)`` for ``V/R^3 -> 0``, ``s -> 0``
   (Lian/Thornton/Adams 1993; Willett et al. 2000).

3. ``capillary_force`` -- the DEM-grade closed form actually used by the
   cohesion model::

       F = 2 pi gamma R cos(theta) * f(theta) * K(u) * D(x)
       u = (V/R^3)^(1/3),          x = (s/R)/u
       K(u) = (1 + a u) / (1 + b u)              bridge-volume reduction
       D(x) = 1 / (1 + p x + q x^2)              separation decay
       f(theta) = cos(theta) (1 - c theta^2)     contact-angle reduction

   The five constants are calibrated on the ``train`` split of
   ``artifacts/wet_ice_cohesion/capillary_reference.json`` (generated by
   ``scripts/gen_wet_ice_capillary_reference.py``) and are *validated on a
   disjoint held-out split*; the measured errors are printed by
   ``scripts/wet_ice_cohesion_study.py`` and asserted in the test suite.

Reference (the judge)
---------------------
``exact_force`` wraps :func:`tensordem.liquid_bridge.solve_axisymmetric_bridge`.
That solver is independently validated by its own first integral (the axial
force evaluated at the neck and at the contact line must agree, see
``tests/test_liquid_bridge.py``); the campaign repeats that check on every row.

Cohesive-zone (Maugis-Dugdale) equivalence
------------------------------------------
DEM contact laws need a *cohesive zone*: a constant tensile capacity ``F_c``
that stays active up to a rupture distance ``delta_c``.  The Maugis-Dugdale /
Dugdale idealisation (Maugis 2000, ch. 5) is exactly that idealisation, and its
two defining numbers are matched here by construction against the resolved
bridge:

* equal peak:            ``F_c  = F(s = 0)``
* equal work of rupture: ``W = int_0^{s_r} F ds``, hence ``delta_c = W / F_c``

``dugdale_equivalent`` returns ``(F_c, W, delta_c)``.  Note the deliberate
limitation: Maugis-Dugdale is *not* used as a liquid-bridge solution (it is an
elastic adhesive-contact solution); it is used only as the constant-traction
representation of the resolved bridge work, which is what a DEM cohesion law
needs.

Sign convention: all forces returned here are *magnitudes of attraction* (> 0).
Gaps ``s`` are surface-to-surface separations.  SI units.
"""
from __future__ import annotations

import math
from typing import Optional

__all__ = [
    "CONTACT_ANGLE_MAX_DEG",
    "MODEL_CONSTANTS",
    "capillary_force",
    "capillary_force_array",
    "cutoff_separation",
    "dugdale_equivalent",
    "exact_force",
    "model_curve",
    "seeded_campaign_force",
    "small_bridge_limit",
]

#: upper bound of the calibrated contact-angle range of :func:`capillary_force`
CONTACT_ANGLE_MAX_DEG = 45.0

#: calibrated closed-form constants (see module docstring for the fit protocol)
MODEL_CONSTANTS = {
    "a": 0.165041,   # K(u) numerator
    "b": 0.789773,   # K(u) denominator
    "p": 0.821491,   # D(x) linear
    "q": 6.612248,   # D(x) quadratic
    "c": 0.174236,   # f(theta) quadratic correction
}


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _check(radius: float, gamma: float, volume: float, gap: float, theta_deg: float) -> None:
    if radius <= 0.0:
        raise ValueError("particle radius must be positive")
    if gamma < 0.0:
        raise ValueError("surface tension must be non-negative")
    if volume <= 0.0:
        raise ValueError("liquid-bridge volume must be positive")
    if gap < 0.0:
        raise ValueError("gap must be non-negative")
    if not (-90.0 <= theta_deg <= 90.0):
        raise ValueError("contact angle must lie in [-90, 90] deg")


def _angle_factor(theta_deg: float) -> float:
    """``cos(theta) (1 - c theta^2)`` with ``theta`` in radians, clipped at 0."""
    theta = math.radians(theta_deg)
    return max(0.0, math.cos(theta) * (1.0 - MODEL_CONSTANTS["c"] * theta * theta))


# ---------------------------------------------------------------------------
# 1. the seeded campaign formula (falsified, kept for audit)
# ---------------------------------------------------------------------------

def seeded_campaign_force(
    radius: float,
    gamma: float,
    gap: float,
    bridge_height: float,
    contact_angle_deg: float = 0.0,
) -> float:
    """Literal implementation of the closed form quoted in the P35-N2 brief.

    ``F = 2 pi R gamma cos(theta) * [1/(1 + s/(2h)) - 1/sqrt(1 + s/h)]``

    Physically this cannot be a liquid-bridge law: it vanishes at ``s = 0``
    (two *touching* spheres would feel no capillary attraction) and peaks at an
    interior separation.  The exact axisymmetric solution does the opposite.
    Kept so that the falsification is reproducible; see
    ``docs/wet_ice_cohesion_P35N2.md`` section 5.
    """
    if radius <= 0.0 or bridge_height <= 0.0:
        raise ValueError("radius and bridge height must be positive")
    if gamma < 0.0 or gap < 0.0:
        raise ValueError("gamma and gap must be non-negative")
    cos_t = math.cos(math.radians(contact_angle_deg))
    if cos_t <= 0.0:
        return 0.0
    shape = 1.0 / (1.0 + gap / (2.0 * bridge_height)) - 1.0 / math.sqrt(
        1.0 + gap / bridge_height
    )
    return 2.0 * math.pi * radius * gamma * cos_t * shape


# ---------------------------------------------------------------------------
# 2. classical anchor
# ---------------------------------------------------------------------------

def small_bridge_limit(
    radius: float, gamma: float, contact_angle_deg: float = 0.0
) -> float:
    """``V -> 0, s -> 0`` asymptote ``2 pi gamma R cos(theta)`` (attraction)."""
    cos_t = math.cos(math.radians(contact_angle_deg))
    return max(0.0, 2.0 * math.pi * radius * gamma * cos_t)


# ---------------------------------------------------------------------------
# 3. DEM-grade closed form
# ---------------------------------------------------------------------------

def capillary_force(
    radius: float,
    gamma: float,
    volume: float,
    gap: float = 0.0,
    contact_angle_deg: float = 0.0,
) -> float:
    """Axial pendular-bridge force (attraction magnitude, N).

    Args:
        radius: sphere radius ``R`` (m).
        gamma: liquid surface tension (N/m).  ``gamma = 0`` returns exactly
            ``0.0`` (the dry-ice negative control, bit-identical to no cohesion).
        volume: liquid volume of one bridge (m^3).
        gap: surface-to-surface separation (m).
        contact_angle_deg: contact angle inside the liquid (deg, 0 = perfectly
            wetting ice/water).
    """
    _check(radius, gamma, volume, gap, contact_angle_deg)
    if gamma == 0.0:
        return 0.0
    u = (volume / radius ** 3) ** (1.0 / 3.0)
    k = (1.0 + MODEL_CONSTANTS["a"] * u) / (1.0 + MODEL_CONSTANTS["b"] * u)
    x = (gap / radius) / u
    d = 1.0 / (1.0 + MODEL_CONSTANTS["p"] * x + MODEL_CONSTANTS["q"] * x * x)
    return 2.0 * math.pi * gamma * radius * _angle_factor(contact_angle_deg) * k * d


def cutoff_separation(
    radius: float, volume: float, contact_angle_deg: float = 0.0, fraction: float = 0.10
) -> float:
    """Separation at which the bridge force has decayed to ``fraction`` of its peak.

    Used as the DEM rupture distance (beyond it the bridge is assumed to snap).
    Calibrated on the same closed form, so it is consistent with
    :func:`capillary_force`; it is *not* an independent measurement of the
    rupture distance.
    """
    if not (0.0 < fraction < 1.0):
        raise ValueError("fraction must be in (0, 1)")
    u = (volume / radius ** 3) ** (1.0 / 3.0)
    # solve 1/(1+p x + q x^2) = fraction
    target = 1.0 / fraction - 1.0
    disc = MODEL_CONSTANTS["p"] ** 2 + 4.0 * MODEL_CONSTANTS["q"] * target
    x = (-MODEL_CONSTANTS["p"] + math.sqrt(disc)) / (2.0 * MODEL_CONSTANTS["q"])
    return x * u * radius


def model_curve(
    radius: float,
    gamma: float,
    volume: float,
    gaps,
    contact_angle_deg: float = 0.0,
) -> list:
    """``capillary_force`` sampled on ``gaps`` (convenience for reporting)."""
    return [capillary_force(radius, gamma, volume, g, contact_angle_deg) for g in gaps]


# ---------------------------------------------------------------------------
# reference + cohesive-zone equivalence
# ---------------------------------------------------------------------------

def exact_force(
    radius: float,
    gamma: float,
    volume: float,
    gap: float = 0.0,
    contact_angle_deg: float = 0.0,
    *,
    n_steps: int = 200,
):
    """Exact axisymmetric Young-Laplace bridge solution (the judge).

    Returns the :class:`tensordem.liquid_bridge.BridgeSolution`; ``None`` when
    the shooting solver fails (it is brittle for very small bridges and near
    ``theta = 90 deg``).  Failures are reported, never silently replaced.
    """
    if gamma <= 0.0:
        raise ValueError(
            "the Young-Laplace reference needs gamma > 0; use gamma = 0 to test "
            "the dry limit (capillary_force returns exactly 0 there)"
        )
    from ..liquid_bridge import solve_axisymmetric_bridge

    try:
        return solve_axisymmetric_bridge(
            radius, gamma, volume, gap, contact_angle_deg, n_steps=n_steps
        )
    except Exception:  # pragma: no cover - solver brittleness is data
        return None


def dugdale_equivalent(
    radius: float,
    gamma: float,
    volume: float,
    contact_angle_deg: float = 0.0,
    *,
    n_samples: int = 24,
    n_steps: int = 120,
) -> dict:
    """Constant-traction (Maugis-Dugdale) equivalent of the resolved bridge.

    The rupture work is integrated from the *exact* Young-Laplace solution on a
    geometric grid of separations ``0 .. cutoff``.  Rows where the solver fails
    are dropped and counted, and ``coverage`` reports how much of the sampled
    grid contributed, so the integral cannot be silently biased.

    Returns a dict with ``peak_force``, ``work_of_separation``,
    ``delta_c`` (= ``work / peak``), ``cutoff``, ``n_used``, ``coverage`` and the
    per-sample table.
    """
    s_cut = cutoff_separation(radius, volume, contact_angle_deg)
    gaps = [s_cut * (k / (n_samples - 1)) for k in range(n_samples)]
    samples = []
    for g in gaps:
        sol = exact_force(radius, gamma, volume, g, contact_angle_deg, n_steps=n_steps)
        if sol is None or not math.isfinite(sol.force):
            samples.append({"gap": g, "force": None})
            continue
        samples.append({"gap": g, "force": float(sol.force), "residual": float(sol.residual),
                        "converged": bool(sol.converged)})
    good = [s for s in samples if s["force"] is not None]
    work = 0.0
    for a, b in zip(good[:-1], good[1:]):
        work += 0.5 * (a["force"] + b["force"]) * (b["gap"] - a["gap"])
    peak = good[0]["force"] if good else float("nan")
    return {
        "peak_force": peak,
        "work_of_separation": work,
        "delta_c": (work / peak) if peak and peak > 0 else float("nan"),
        "cutoff": s_cut,
        "n_used": len(good),
        "n_samples": len(gaps),
        "coverage": len(good) / len(gaps),
        "samples": samples,
    }

# ---------------------------------------------------------------------------
# vectorised form (DEM inner loop)
# ---------------------------------------------------------------------------

def capillary_force_array(
    radius,
    gamma: float,
    volume,
    gap,
    contact_angle_deg: float = 0.0,
):
    """Vectorised :func:`capillary_force` (numpy arrays for ``radius``/``volume``/``gap``).

    ``gamma == 0`` returns ``numpy.zeros_like`` so the dry negative control is
    bit-identical to "no cohesion code path" (no floating-point residue).
    """
    import numpy as np

    r = np.asarray(radius, dtype=float)
    v = np.asarray(volume, dtype=float)
    s = np.asarray(gap, dtype=float)
    if gamma == 0.0:
        return np.zeros(np.broadcast(r, v, s).shape)
    if np.any(r <= 0.0) or np.any(v <= 0.0) or np.any(s < 0.0):
        raise ValueError("radius, volume > 0 and gap >= 0 are required")
    u = (v / r ** 3) ** (1.0 / 3.0)
    k = (1.0 + MODEL_CONSTANTS["a"] * u) / (1.0 + MODEL_CONSTANTS["b"] * u)
    x = (s / r) / u
    d = 1.0 / (1.0 + MODEL_CONSTANTS["p"] * x + MODEL_CONSTANTS["q"] * x * x)
    return 2.0 * math.pi * gamma * r * _angle_factor(contact_angle_deg) * k * d
