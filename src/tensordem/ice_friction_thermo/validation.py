# ---------------------------------------------------------------------------
# calibration
# ---------------------------------------------------------------------------
def calibrate_from_barnes_sweep(t_ref_c: float = -10.0) -> tuple[ContactFrictionModel, dict[str, Any]]:
    """Fit ``(mu_ref, beta)`` on the Barnes temperature sweep, return the model.

    The sweep is the subset of the calibration anchors whose source names
    Barnes, Tabor & Walker (1971): a speed of 0.01 m/s at 0.2 MPa with the
    temperature varied.  Only that source is used, so the subsequent prediction
    of the Riska/Poirier rows is a genuine holdout.
    """
    rows = [row for row in CALIBRATION_ANCHORS if "Barnes" in row.source]
    if len(rows) < 4:
        raise RuntimeError("Barnes temperature sweep not found in the anchor set")
    fit = fit_exponential_temperature_law(rows, t_ref_c=t_ref_c)
    model = ContactFrictionModel(
        mu_ref=fit["mu_ref"],
        beta_per_k=fit["beta_per_k"],
        t_ref_c=fit["t_ref_c"],
    )
    residuals = [
        {
            "temperature_c": row.temperature_c,
            "mu_literature": row.mu,
            "mu_fit": model.mu_dry(row.temperature_c),
            "rel_error": model.mu_dry(row.temperature_c) / row.mu - 1.0,
        }
        for row in rows
    ]
    return model, {**fit, "source": rows[0].source, "rows": residuals}


# ---------------------------------------------------------------------------
# validation against independent literature rows
# ---------------------------------------------------------------------------
def predict_anchor(anchor: Any, model: ContactFrictionModel,
                   spot_radius_m: float = 1.0e-4,
                   nominal_area_m2: float = 1.0,
                   hardness_pa: float | None = None) -> dict[str, Any]:
    """Predict the coefficient of friction of one literature row.

    The row supplies only ``(v, T, p_nominal)``; the coefficient is *predicted*.
    """
    pressure = float(anchor.pressure_mpa) * 1.0e6
    law = model if hardness_pa is None else ContactFrictionModel(
        mu_ref=model.mu_ref, beta_per_k=model.beta_per_k, t_ref_c=model.t_ref_c,
        wet_ratio=model.wet_ratio, onset_width_k=model.onset_width_k,
        hardness_pa=hardness_pa, allow_melting=model.allow_melting,
        mu_floor=model.mu_floor)
    conditions = ContactConditions(
        normal_force_n=pressure * nominal_area_m2,
        nominal_area_m2=nominal_area_m2,
        slip_velocity_m_s=float(anchor.v_m_per_s),
        bulk_temperature_c=float(anchor.temperature_c),
        contact_spot_radius_m=spot_radius_m,
    )
    state = solve_contact_state(conditions, law)
    predicted = state.mu
    measured = float(anchor.mu)
    return {
        "label": anchor.label,
        "source": anchor.source,
        "v_m_per_s": float(anchor.v_m_per_s),
        "temperature_c": float(anchor.temperature_c),
        "pressure_mpa": float(anchor.pressure_mpa),
        "mu_literature": measured,
        "mu_predicted": predicted,
        "rel_error": predicted / measured - 1.0,
        "within_gate": abs(predicted / measured - 1.0) <= ERROR_GATE,
        "interface_temperature_c": state.interface_temperature_c,
        "real_pressure_mpa": state.real_pressure_pa / 1.0e6,
        "melting_temperature_c": state.melting_temperature_c,
        "melt_fraction": state.melt_fraction,
        "regime": state.regime,
        "iterations": state.iterations,
        "converged": state.converged,
    }


def validation_table(model: ContactFrictionModel,
                     spot_radius_m: float = 1.0e-4) -> list[dict[str, Any]]:
    """Predicted vs literature on the independent (holdout) anchor set."""
    return [predict_anchor(row, model, spot_radius_m) for row in VALIDATION_ANCHORS]


def baseline_table() -> list[dict[str, Any]]:
    """The constant-coefficient baseline scored on the same holdout rows."""
    rows = []
    for row in VALIDATION_ANCHORS:
        error = MU_CONSTANT_BASELINE / float(row.mu) - 1.0
        rows.append({
            "label": row.label,
            "mu_literature": float(row.mu),
            "mu_predicted": MU_CONSTANT_BASELINE,
            "rel_error": error,
            "within_gate": abs(error) <= ERROR_GATE,
        })
    return rows


def _error_stats(rows: Iterable[dict[str, Any]]) -> dict[str, Any]:
    errors = [abs(row["rel_error"]) for row in rows]
    if not errors:
        raise ValueError("no rows")
    return {
        "n_rows": len(errors),
        "n_within_gate": sum(1 for row in rows if row["within_gate"]),
        "max_abs_rel_error": max(errors),
        "mean_abs_rel_error": sum(errors) / len(errors),
        "rmse_rel": math.sqrt(sum(e * e for e in errors) / len(errors)),
    }


