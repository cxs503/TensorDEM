# pressure melting (Clausius-Clapeyron) sweep
# ---------------------------------------------------------------------------
def pressure_melting_map(model: ContactFrictionModel,
                         temperatures_c: Sequence[float] = (-15.0, -10.0, -5.0, -3.0, -2.0, -1.0, -0.3),
                         hardnesses_mpa: Sequence[float] = (10.0, 20.0, 50.0, 100.0),
                         velocity_m_s: float = 1.0,
                         nominal_pressure_mpa: float = 1.0,
                         spot_radius_m: float = 1.0e-4) -> dict[str, Any]:
    """Where the Clausius-Clapeyron branch actually switches friction off.

    Two things decide whether an ice-structure contact is pressure-melted:

    * the **real** contact pressure ``p_real = min(H, p_nominal/phi)``, i.e. the
      ice hardness for a plastic contact at engineering loads, and
    * the bulk temperature: pressure melting needs
      ``p_real > |T| / |dT_m/dp|`` -- 68 MPa for ice at -5 degC, 135 MPa at
      -10 degC.

    The map therefore sweeps hardness (the only way to reach the threshold at
    nominal loads of order 1 MPa) against temperature and reports, for every
    point, the melting point implied by ``p_real``, the melt fraction that
    follows from the film balance, and ``mu``.  The nominal-pressure sweep is
    included as an **Amontons check**: for a plastic contact the real pressure
    saturates at ``H``, so ``mu`` must be independent of the nominal pressure --
    which is exactly why the classical "pressure weakening" of ice friction
    (Oksanen & Keinonen 1982) is *not* reproduced here and must come from
    real-area growth, not from phase change.  That negative result is reported
    rather than tuned away.
    """
    threshold = [
        {
            "temperature_c": temperature,
            "pressure_melting_threshold_mpa":
                pressure_melting_threshold_pa(temperature) / 1.0e6,
        }
        for temperature in temperatures_c
    ]
    grid = []
    for hardness_mpa in hardnesses_mpa:
        law = ContactFrictionModel(
            mu_ref=model.mu_ref, beta_per_k=model.beta_per_k, t_ref_c=model.t_ref_c,
            wet_ratio=model.wet_ratio, onset_width_k=model.onset_width_k,
            hardness_pa=hardness_mpa * 1.0e6, allow_melting=model.allow_melting,
            mu_floor=model.mu_floor)
        for temperature in temperatures_c:
            conditions = ContactConditions(
                normal_force_n=nominal_pressure_mpa * 1.0e6,
                nominal_area_m2=1.0,
                slip_velocity_m_s=velocity_m_s,
                bulk_temperature_c=temperature,
                contact_spot_radius_m=spot_radius_m,
            )
            state = solve_contact_state(conditions, law)
            grid.append({
                "hardness_mpa": hardness_mpa,
                "temperature_c": temperature,
                "real_pressure_mpa": state.real_pressure_pa / 1.0e6,
                "area_fraction": state.area_fraction,
                "melting_temperature_c": state.melting_temperature_c,
                "interface_temperature_c": state.interface_temperature_c,
                "melt_fraction": state.melt_fraction,
                "mu": state.mu,
                "mu_dry": state.mu_dry,
                "mu_reduction": 1.0 - state.mu / max(state.mu_dry, 1e-12),
                "regime": state.regime,
            })
    amontons = []
    for pressure_mpa in (0.05, 0.1, 0.2, 0.5, 1.0, 2.0, 5.0, 10.0):
        conditions = ContactConditions(
            normal_force_n=pressure_mpa * 1.0e6, nominal_area_m2=1.0,
            slip_velocity_m_s=velocity_m_s, bulk_temperature_c=-2.0,
            contact_spot_radius_m=spot_radius_m)
        state = solve_contact_state(conditions, model)
        amontons.append({
            "nominal_pressure_mpa": pressure_mpa,
            "real_pressure_mpa": state.real_pressure_pa / 1.0e6,
            "mu": state.mu,
            "muxnominal_pressure": state.mu * pressure_mpa,
        })
    return {
        "velocity_m_s": velocity_m_s,
        "nominal_pressure_mpa": nominal_pressure_mpa,
        "hardness_mpa": model.hardness_pa / 1.0e6,
        "threshold_curve": threshold,
        "grid": grid,
        "amontons_check": amontons,
        "amontons_mu_spread":
            (max(row["mu"] for row in amontons) - min(row["mu"] for row in amontons))
            / max(row["mu"] for row in amontons),
        "n_pressure_melted": sum(1 for row in grid if row["regime"] == "pressure"),
        "max_mu_reduction": max(row["mu_reduction"] for row in grid),
    }


