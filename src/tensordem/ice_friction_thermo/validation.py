def conductor_evidence(flux: float = 1.0e6) -> dict[str, Any]:
    """Numerical vs analytic checks of the 1D conductor (independent of friction).

    Two references with no free parameters:

    * **Blok semi-infinite** rise ``2 q sqrt(t/pi)/(e_i + e_s)`` at early time,
      refined in ``dt`` (the scheme is first-order, so the deviation must fall
      with the step, which is what the table shows);
    * **steady series resistance** ``q (d_i/k_i + d_s/k_s)`` after the diffusion
      time ``d^2/alpha`` -- the discretisation is exact for the linear steady
      profile, so the residual is round-off.

    Every row also carries the energy ledger ``int q dt = sensible + outflow``.
    """
    early = []
    depth = 2.0e-3
    for dt in (2.0e-3, 1.0e-3, 2.5e-4):
        steps = int(round(5.0e-3 / dt))
        conductor = TwoBodyContactConductor(ice_depth_m=depth, steel_depth_m=depth,
                                            ice_cells=200, steel_cells=200,
                                            initial_temperature_c=-10.0)
        for _ in range(steps):
            conductor.commit(dt, flux)
        numerical = conductor.interface_temperature_c + 10.0
        analytic = blok_interface_rise_k(steps * dt, flux)
        early.append({
            "dt_s": dt,
            "time_s": steps * dt,
            "cells": 200,
            "dx_m": conductor.dx_ice,
            "numerical_rise_k": numerical,
            "blok_rise_k": analytic,
            "rel_error": numerical / analytic - 1.0,
            "energy_relative_residual": abs(conductor.energy_residual_j_m2())
            / conductor.heat_in_j_m2,
        })
    conductor = TwoBodyContactConductor(ice_depth_m=depth, steel_depth_m=depth,
                                        ice_cells=100, steel_cells=100,
                                        initial_temperature_c=-10.0)
    dt_steady = 1.0e-2
    for _ in range(6000):          # 60 s >> d^2/alpha = 3.5 s
        conductor.commit(dt_steady, flux)
    numerical = conductor.interface_temperature_c + 10.0
    analytic = flux * steady_state_resistance_m2_k_w(depth, depth)
    return {
        "flux_w_m2": flux,
        "early_time": early,
        "steady_state": {
            "depth_m": depth,
            "time_s": conductor.time_s,
            "numerical_rise_k": numerical,
            "series_resistance_rise_k": analytic,
            "rel_error": numerical / analytic - 1.0,
            "energy_relative_residual": abs(conductor.energy_residual_j_m2())
            / conductor.heat_in_j_m2,
        },
        "blok_partition_ice": blok_partition(ICE, STEEL),
        "clapeyron": {
            "slope_k_per_mpa": CC_SLOPE_K_PER_MPA,
            "tabulated_deviation": clapeyron_slope_check(),
            "melting_temperature_at_20mpa_c": melting_temperature_c(2.0e7),
            "pressure_melting_threshold_at_minus5c_mpa":
                pressure_melting_threshold_pa(-5.0) / 1.0e6,
        },
    }


