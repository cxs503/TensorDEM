def acceptance_report(model: ContactFrictionModel | None = None,
                      spot_radius_m: float = 1.0e-4) -> dict[str, Any]:
    """Run every acceptance criterion and return the payload + SHA-256."""
    if model is None:
        model, calibration = calibrate_from_barnes_sweep()
    else:
        calibration = {"note": "user-supplied model; calibration block omitted"}
    core = _payload_core(model, calibration, spot_radius_m)
    # The digest covers everything *except* this block, so it can be recomputed
    # from the file itself: any hand edit of a number invalidates it.
    digest = canonical_digest(core)
    core["C6_provenance"] = {
        "requirement": "no hand-typed numbers: artifact regenerated with a digest",
        "pass": True,
        "sha256_scheme": "sha256 over canonical json (sort_keys, separators, no "
                         "spaces) of this payload with the C6_provenance block removed",
        "generator": "benchmarks/ice_friction_thermo_evidence.py",
        "digest": digest,
    }
    return core


def write_evidence(path: str | Path, model: ContactFrictionModel | None = None,
                   spot_radius_m: float = 1.0e-4) -> dict[str, Any]:
    """Compute the acceptance report and write it to ``path`` as JSON."""
    payload = acceptance_report(model, spot_radius_m)
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    return payload


def verify_evidence(path: str | Path,
                    model: ContactFrictionModel | None = None) -> dict[str, Any]:
    """Recompute the report and compare numbers and digest with the file.

    Returns ``{"digest_matches": bool, "numbers_match": bool, "mismatches": [...]}``.
    A hand-edited artifact fails this, which is the point of criterion C6.
    """
    stored = json.loads(Path(path).read_text())
    stored_without = {k: v for k, v in stored.items() if k != "C6_provenance"}
    stored_digest = stored.get("C6_provenance", {}).get("digest")
    # integrity of the file as stored (catches a hand edit of any number)
    digest_matches = canonical_digest(stored_without) == stored_digest
    # reproducibility: a fresh computation must reproduce the stored numbers
    recomputed = acceptance_report(model)
    recomputed_without = {k: v for k, v in recomputed.items() if k != "C6_provenance"}
    mismatches: list[str] = []
    _diff(stored_without, recomputed_without, "", mismatches)
    return {
        "digest_matches": bool(digest_matches),
        "numbers_match": not mismatches,
        "mismatches": mismatches[:20],
        "stored_digest": stored_digest,
        "recomputed_digest": recomputed.get("C6_provenance", {}).get("digest"),
    }


def _diff(a: Any, b: Any, path: str, out: list[str], tolerance: float = 1e-9) -> None:
    if isinstance(a, dict) and isinstance(b, dict):
        for key in sorted(set(a) | set(b)):
            if key not in a or key not in b:
                out.append(f"{path}/{key}: key mismatch")
            else:
                _diff(a[key], b[key], f"{path}/{key}", out, tolerance)
        return
    if isinstance(a, list) and isinstance(b, list):
        if len(a) != len(b):
            out.append(f"{path}: length {len(a)} != {len(b)}")
            return
        for index, (item_a, item_b) in enumerate(zip(a, b)):
            _diff(item_a, item_b, f"{path}[{index}]", out, tolerance)
        return
    if isinstance(a, bool) or isinstance(b, bool):
        if bool(a) != bool(b):
            out.append(f"{path}: {a} != {b}")
        return
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        scale = max(abs(a), abs(b), 1e-30)
        if abs(a - b) / scale > tolerance:
            out.append(f"{path}: {a} != {b}")
        return
    if a != b:
        out.append(f"{path}: {a!r} != {b!r}")