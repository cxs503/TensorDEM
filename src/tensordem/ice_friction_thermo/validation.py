"""Acceptance evidence for the thermally self-consistent ice friction model.

Everything the campaign asks to be *measured* is measured here, from the same
public functions the tests call, and written to one JSON file whose numbers
carry a SHA-256 of a canonical serialisation.  No number in the report is typed
by hand: the file is regenerated by

    python benchmarks/ice_friction_thermo_evidence.py

and :func:`verify_evidence` recomputes both the numbers and the digest, so a
hand-edited artifact is detectable (criterion C6).

Validation protocol
-------------------
The two friction parameters (``mu_ref``, ``beta``) are fitted on the **Barnes,
Tabor & Walker (1971) temperature sweep** only -- one source, one variable --
and then used, unchanged, to predict the five rows of
``tensordem.ice_steel_friction.VALIDATION_ANCHORS`` (Riska 2017 / ISO 19906
compilation and Poirier et al. 2011), which come from different laboratories.
That is a leave-source-out protocol: no validation row contributes to the fit.

The constant-coefficient baseline ``mu = 0.10`` (:data:`tensordem.
ice_steel_friction.MU_CONSTANT_BASELINE`, the number the existing ice-resistance
chain uses) is scored on the same rows, so the improvement is a measured
difference and not an assertion.
"""
