# C5: friction heat identity
# ---------------------------------------------------------------------------
def friction_heat_identity_check(model: ContactFrictionModel,
                                 spot_radius_m: float = 1.0e-4) -> list[dict[str, Any]]:
    """``Q_f = F_friction * v = q * A_real`` computed by two different chains."""
    cases = (
        dict(v=0.01, pressure_mpa=0.2, temperature_c=-10.0),
        dict(v=0.5, pressure_mpa=1.0, temperature_c=-5.0),
        dict(v=2.0, pressure_mpa=2.0, temperature_c=-1.0),
    )
    rows = []
    for case in cases:
        area = 0.1
        conditions = ContactConditions(
            normal_force_n=case["pressure_mpa"] * 1.0e6 * area,
            nominal_area_m2=area,
            slip_velocity_m_s=case["v"],
            bulk_temperature_c=case["temperature_c"],
            contact_spot_radius_m=spot_radius_m,
        )
        state = solve_contact_state(conditions, model)
        # chain A: force x velocity
        heat_a = state.friction_force_n * conditions.slip_velocity_m_s
        # chain B: real-area flux x real contact area
        real_area = state.area_fraction * conditions.nominal_area_m2
        heat_b = state.heat_flux_w_m2 * real_area
        reference = max(abs(heat_a), 1e-30)
        rows.append({
            **case,
            "area_m2": area,
            "mu": state.mu,
            "friction_force_n": state.friction_force_n,
            "heat_from_force_w": heat_a,
            "heat_from_flux_w": heat_b,
            "model_heat_w": state.friction_heat_w,
            "interface_temperature_c": state.interface_temperature_c,
            "rel_error_force_vs_flux": abs(heat_a - heat_b) / reference,
            "rel_error_force_vs_model": abs(heat_a - state.friction_heat_w) / reference,
            "real_pressure_mpa": state.real_pressure_pa / 1.0e6,
            "area_fraction": state.area_fraction,
        })
    return rows


