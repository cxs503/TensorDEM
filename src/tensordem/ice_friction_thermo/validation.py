# C3: fixed-point convergence
# ---------------------------------------------------------------------------
def convergence_table(model: ContactFrictionModel,
                      spot_radius_m: float = 1.0e-4) -> list[dict[str, Any]]:
    """Iteration count and residual of the fixed point over a load/speed grid."""
    cases = (
        dict(v=0.01, pressure_mpa=0.2, temperature_c=-10.0),
        dict(v=0.1, pressure_mpa=0.5, temperature_c=-10.0),
        dict(v=1.0, pressure_mpa=1.0, temperature_c=-5.0),
        dict(v=2.0, pressure_mpa=2.0, temperature_c=-2.0),
        dict(v=1.0, pressure_mpa=0.2, temperature_c=-1.0),
    )
    rows = []
    for case in cases:
        conditions = ContactConditions(
            normal_force_n=case["pressure_mpa"] * 1.0e6,
            nominal_area_m2=1.0,
            slip_velocity_m_s=case["v"],
            bulk_temperature_c=case["temperature_c"],
            contact_spot_radius_m=spot_radius_m,
        )
        picard = solve_contact_state(conditions, model)
        bisect = solve_contact_state_bisection(conditions, model)
        # the campaign's 1 % tolerance is a *stopping* rule, not an accuracy
        # claim: re-run Picard at 1e-10 to compare solvers at their limits.
        tight = solve_contact_state(conditions, model, tolerance=1.0e-10,
                                    max_iterations=200)
        agreement = (abs(tight.mu - bisect.mu) / max(bisect.mu, 1e-12)
                     if bisect.mu > 0.0 else 0.0)
        rows.append({
            **case,
            "iterations": picard.iterations,
            "converged": picard.converged,
            "final_residual": picard.residual_history[-1] if picard.residual_history else 0.0,
            "max_residual": max(picard.residual_history) if picard.residual_history else 0.0,
            "residual_history": list(picard.residual_history),
            "mu_picard": picard.mu,
            "mu_picard_tight": tight.mu,
            "mu_bisection": bisect.mu,
            "iterations_tight": tight.iterations,
            "mu_agreement": agreement,
            "within_iteration_gate": picard.iterations < 10 and picard.converged,
            "gain_k_per_mu": interface_gain_k_per_mu(conditions, model),
            "regime": picard.regime,
        })
    return rows


