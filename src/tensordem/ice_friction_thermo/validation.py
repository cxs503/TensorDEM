# C2: temperature monotonicity
# ---------------------------------------------------------------------------
def temperature_monotonicity_check(model: ContactFrictionModel,
                                   spot_radius_m: float = 1.0e-4) -> list[dict[str, Any]]:
    """Three regimes in which ``mu`` must fall as the ice warms.

    ``slow``  -- 1 cm/s at 0.2 MPa: no heating, the exponential law alone.
    ``fast``  -- 1 m/s at 1 MPa: friction heating raises the interface.
    ``near-melting`` -- 1 m/s at 2 MPa with the bulk temperature approaching
    0 degC: the pressure-melting branch switches the interface from dry to wet.
    """
    sweeps = (
        ("slow", dict(v=0.01, pressure_mpa=0.2, temperatures=(-30.0, -20.0, -10.0, -5.0, -2.0))),
        ("fast", dict(v=1.0, pressure_mpa=1.0, temperatures=(-30.0, -20.0, -10.0, -5.0, -2.0))),
        ("near-melting", dict(v=1.0, pressure_mpa=2.0, temperatures=(-6.0, -4.0, -3.0, -2.0, -0.5))),
    )
    results = []
    for name, spec in sweeps:
        series = []
        for temperature in spec["temperatures"]:
            conditions = ContactConditions(
                normal_force_n=spec["pressure_mpa"] * 1.0e6,
                nominal_area_m2=1.0,
                slip_velocity_m_s=spec["v"],
                bulk_temperature_c=temperature,
                contact_spot_radius_m=spot_radius_m,
            )
            state = solve_contact_state(conditions, model)
            series.append({
                "temperature_c": temperature,
                "mu": state.mu,
                "interface_temperature_c": state.interface_temperature_c,
                "melt_fraction": state.melt_fraction,
                "regime": state.regime,
            })
        decreasing = all(b["mu"] < a["mu"] for a, b in zip(series, series[1:]))
        results.append({
            "case": name,
            "slip_velocity_m_s": spec["v"],
            "nominal_pressure_mpa": spec["pressure_mpa"],
            "series": series,
            "strictly_decreasing": decreasing,
            "mu_first": series[0]["mu"],
            "mu_last": series[-1]["mu"],
            "total_reduction": 1.0 - series[-1]["mu"] / series[0]["mu"],
        })
    return results


