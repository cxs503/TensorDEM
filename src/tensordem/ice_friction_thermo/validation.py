# parameter sensitivity
# ---------------------------------------------------------------------------
def sensitivity_table(model: ContactFrictionModel) -> dict[str, Any]:
    """How much the un-measured parameters move the answers.

    Three parameters are *not* fitted to the friction data:

    * ``contact_spot_radius_m`` -- geometric (asperity size);
    * ``film_reference_m`` -- the film thickness that counts as separated;
    * ``hardness_pa`` -- the ice hardness that sets the real contact pressure.

    For each, the table reports (a) the holdout validation error -- which must be
    inert because those rows are dry -- and (b) the coefficient of a *wet* case,
    where all three matter.  Reporting both separates "the validation does not
    depend on a knob" from "the knob does not matter".
    """
    wet_pressure_mpa = 2.0
    wet_temperature_c = -1.0
    wet_velocity_m_s = 1.0

    def wet_state(law: ContactFrictionModel, spot_radius_m: float, film: float) -> ContactThermoState:
        conditions = ContactConditions(
            normal_force_n=wet_pressure_mpa * 1.0e6, nominal_area_m2=1.0,
            slip_velocity_m_s=wet_velocity_m_s,
            bulk_temperature_c=wet_temperature_c,
            contact_spot_radius_m=spot_radius_m)
        return solve_contact_state(conditions, law, film_reference_m=film)

    def law_with(model_in: ContactFrictionModel, **overrides: float) -> ContactFrictionModel:
        fields = dict(mu_ref=model_in.mu_ref, beta_per_k=model_in.beta_per_k,
                      t_ref_c=model_in.t_ref_c, wet_ratio=model_in.wet_ratio,
                      onset_width_k=model_in.onset_width_k,
                      hardness_pa=model_in.hardness_pa,
                      allow_melting=model_in.allow_melting,
                      mu_floor=model_in.mu_floor)
        fields.update(overrides)
        return ContactFrictionModel(**fields)

    rows: list[dict[str, Any]] = []
    for spot_radius in (2.0e-5, 1.0e-4, 5.0e-4):
        validation_rows = [predict_anchor(row, model, spot_radius_m=spot_radius)
                           for row in VALIDATION_ANCHORS]
        state = wet_state(model, spot_radius, DEFAULT_FILM_REFERENCE_M)
        rows.append({"parameter": "contact_spot_radius_m", "value": spot_radius,
                     **_sensitivity_row(validation_rows, state)})
    for film in (2.0e-7, 1.0e-6, 5.0e-6):
        validation_rows = [predict_anchor(row, model) for row in VALIDATION_ANCHORS]
        state = wet_state(model, DEFAULT_SPOT_RADIUS_M, film)
        rows.append({"parameter": "film_reference_m", "value": film,
                     **_sensitivity_row(validation_rows, state)})
    for hardness_mpa in (10.0, 20.0, 50.0, 100.0):
        law = law_with(model, hardness_pa=hardness_mpa * 1.0e6)
        validation_rows = [predict_anchor(row, law) for row in VALIDATION_ANCHORS]
        state = wet_state(law, DEFAULT_SPOT_RADIUS_M, DEFAULT_FILM_REFERENCE_M)
        rows.append({"parameter": "hardness_mpa", "value": hardness_mpa,
                     **_sensitivity_row(validation_rows, state)})
    return {
        "rows": rows,
        "wet_case": {
            "nominal_pressure_mpa": wet_pressure_mpa,
            "temperature_c": wet_temperature_c,
            "velocity_m_s": wet_velocity_m_s,
        },
        "film_rows_leave_dry_validation_unchanged": all(
            row["validation_max_abs_rel_error"] == rows[3]["validation_max_abs_rel_error"]
            for row in rows[3:6]),
        "wet_case_mu_range": [min(row["wet_case_mu"] for row in rows),
                             max(row["wet_case_mu"] for row in rows)],
    }


def _sensitivity_row(validation_rows: Iterable[dict[str, Any]],
                     state: ContactThermoState) -> dict[str, Any]:
    stats = _error_stats(validation_rows)
    return {
        "validation_max_abs_rel_error": stats["max_abs_rel_error"],
        "validation_n_within_gate": stats["n_within_gate"],
        "wet_case_mu": state.mu,
        "wet_case_melt_fraction": state.melt_fraction,
        "wet_case_regime": state.regime,
    }


