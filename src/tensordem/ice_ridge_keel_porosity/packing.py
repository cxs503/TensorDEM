"""Initial rubble packing: polydisperse spheres in the keel geometry.

The keel rubble is modelled as a collection of spherical ice blocks with
a polydisperse size distribution. The initial packing is generated by:

1. Sampling radii from a power-law or uniform distribution
2. Placing spheres sequentially inside the keel geometry
3. Checking for overlaps (RSA - Random Sequential Absorption)
4. Computing the initial porosity

The target initial porosity is n_0 ≈ 0.4 (loose random packing).
For monodisperse spheres, random loose packing gives n ≈ 0.36–0.40.
For polydisperse mixtures, smaller particles fill voids, potentially
reducing porosity. We target n_0 ∈ [0.35, 0.45].

Physical parameters:
- Ice density: ρ_ice ≈ 917 kg/m³
- Sphere diameters: d ∈ [0.2, 0.5] m (representing ice blocks)
- Number of spheres: N ≈ 1000 (for computational tractability)
"""
from __future__ import annotations

from dataclasses import dataclass
import math
from typing import Tuple

import numpy as np
from scipy.spatial import cKDTree

from .geometry import KeelGeometry, keel_volume, random_point_in_keel

__all__ = [
    "KeelPackingConfig",
    "generate_rubble_packing",
    "initial_porosity",
    "polydisperse_radii",
    "PackingResult",
]

ICE_DENSITY = 917.0  # kg/m³


@dataclass(frozen=True)
class KeelPackingConfig:
    """Configuration for keel rubble packing generation.

    Attributes
    ----------
    n_particles : int
        Target number of spheres. Default 1000.
    d_min : float
        Minimum sphere diameter (m). Default 0.2.
    d_max : float
        Maximum sphere diameter (m). Default 0.5.
    distribution : str
        Size distribution: "uniform" or "power_law". Default "uniform".
    power_law_exponent : float
        Exponent for power-law distribution (negative = more small). Default -2.0.
    target_porosity : float
        Target initial porosity. Default 0.4.
    rsa_max_attempts : int
        Maximum placement attempts per particle. Default 1000.
    rsa_min_gap : float
        Minimum gap between spheres (fraction of smaller radius). Default 0.02.
    seed : int
        Random seed for reproducibility. Default 42.
    """
    n_particles: int = 1000
    d_min: float = 0.2
    d_max: float = 0.5
    distribution: str = "uniform"
    power_law_exponent: float = -2.0
    target_porosity: float = 0.4
    rsa_max_attempts: int = 1000
    rsa_min_gap: float = 0.02
    seed: int = 42


@dataclass
class PackingResult:
    """Result of packing generation.

    Attributes
    ----------
    positions : np.ndarray
        Sphere center positions, shape (N, 3).
    radii : np.ndarray
        Sphere radii, shape (N,).
    n_placed : int
        Number of spheres successfully placed.
    porosity : float
        Initial porosity of the packing.
    solid_volume : float
        Total solid volume (m³).
    container_volume : float
        Volume of the keel container (m³).
    """
    positions: np.ndarray
    radii: np.ndarray
    n_placed: int
    porosity: float
    solid_volume: float
    container_volume: float


def polydisperse_radii(
    n: int,
    d_min: float,
    d_max: float,
    distribution: str = "uniform",
    power_law_exponent: float = -2.0,
    rng: np.random.Generator = None,
) -> np.ndarray:
    """Generate polydisperse sphere radii.

    Parameters
    ----------
    n : int
        Number of radii to generate.
    d_min, d_max : float
        Min/max diameter (m).
    distribution : str
        "uniform" or "power_law".
    power_law_exponent : float
        Exponent α for p(d) ∝ d^α. Negative means more small particles.
    rng : np.random.Generator
        Random number generator.

    Returns
    -------
    radii : np.ndarray
        Array of radii (m), shape (n,).
    """
    if rng is None:
        rng = np.random.default_rng()

    r_min = d_min / 2
    r_max = d_max / 2

    if distribution == "uniform":
        diameters = rng.uniform(d_min, d_max, size=n)
    elif distribution == "power_law":
            # p(d) ∝ d^α, CDF inversion
            α = power_law_exponent
            if abs(α + 1) < 1e-10:
                # α = -1: log-uniform
                u = rng.random(n)
                diameters = d_min * (d_max / d_min) ** u
            else:
                u = rng.random(n)
                β = α + 1
                diameters = (d_min**β + u * (d_max**β - d_min**β)) ** (1 / β)
    else:
        raise ValueError(f"Unknown distribution: {distribution}")

    return diameters / 2


def generate_rubble_packing(
    geom: KeelGeometry,
    config: KeelPackingConfig = None,
) -> PackingResult:
    """Generate initial rubble packing via Random Sequential Absorption (RSA).

    Places spheres one by one inside the keel geometry, rejecting overlaps.
    The process continues until n_particles are placed or max attempts exhausted.

    Parameters
    ----------
    geom : KeelGeometry
        Keel container geometry.
    config : KeelPackingConfig
        Packing configuration.

    Returns
    -------
    PackingResult
        Positions, radii, porosity, and volumes.
    """
    if config is None:
        config = KeelPackingConfig()

    rng = np.random.default_rng(config.seed)
    container_vol = keel_volume(geom)

    # Generate candidate radii (oversample to account for placement failures)
    n_try = int(config.n_particles * 1.5)
    all_radii = polydisperse_radii(
        n_try,
        config.d_min,
        config.d_max,
        config.distribution,
        config.power_law_exponent,
        rng,
    )

    # RSA placement
    positions = []
    radii = []

    for i in range(n_try):
        if len(positions) >= config.n_particles:
            break

        r = all_radii[i]
        success = False

        for _ in range(config.rsa_max_attempts):
            # Random point inside keel (with margin for sphere radius)
            pt = random_point_in_keel(geom, rng)
            # Ensure sphere is fully inside (approximate: check center is inside
            # a shrunken keel)
            z = pt[2]
            L, W = geom.cross_section(z)
            margin = r * 1.1
            if (abs(pt[0]) > L / 2 - margin or
                abs(pt[1]) > W / 2 - margin or
                z < r or z > geom.depth - r):
                continue

            # Check overlap with existing spheres
            if len(positions) > 0:
                pos_arr = np.array(positions)
                dists = np.linalg.norm(pos_arr - pt, axis=1)
                min_sep = np.array(radii) + r + config.rsa_min_gap * np.minimum(r, np.array(radii))
                if np.any(dists < min_sep):
                    continue

            positions.append(pt)
            radii.append(r)
            success = True
            break

    positions = np.array(positions) if positions else np.empty((0, 3))
    radii = np.array(radii) if radii else np.empty(0)
    n_placed = len(radii)

    # Compute porosity
    solid_vol = np.sum(4 / 3 * np.pi * radii**3)
    porosity = 1.0 - solid_vol / container_vol

    return PackingResult(
        positions=positions,
        radii=radii,
        n_placed=n_placed,
        porosity=porosity,
        solid_volume=solid_vol,
        container_volume=container_vol,
    )


def initial_porosity(packing: PackingResult) -> float:
    """Return the initial porosity of a packing."""
    return packing.porosity
