"""Conditional simulation of ice abrasion depth fields.

Why this module exists
----------------------
The ice-abrasion module (:mod:`tensordem.ice_abrasion`) produces a *single
deterministic depth field* per season and reports its P95 as the design
statistic.  The previous uncertainty treatment used a naive iid bootstrap on
contact statistics, which ignores the spatial correlation of the wear field and
therefore underestimates the P95 variance.  This module upgrades the uncertainty
quantification to a **conditional simulator** that:

1. Decomposes the depth field into a deterministic activity profile and a
   spatially correlated residual: ``q(x,z) = a(h(x)) * r(x,z)``.
2. Estimates the 2D autocorrelation and power spectrum of the residual.
3. Generates equiprobable realizations by phase randomization (FFT-based) that
   preserve the power spectrum and column structure.
4. Provides a variance estimate for P95 that can be validated against
   independent-repeat "truth" fields.
5. Decomposes the resolution-dependent P95 difference (19.47%) into
   activity-profile discretization and extreme-value sampling components.

Method
------
**Field decomposition.**  The activity profile ``a(h)`` is the column-mean depth
as a function of longitudinal position ``h`` (fraction of hull length).  The
residual ``r(x,z) = q(x,z) / a(h(x))`` is normalized to unit column mean.

**Phase randomization.**  For each realization:
  (a) 2D FFT of the residual field.
  (b) Extract amplitudes.
  (c) Generate random phases for independent frequency pairs.
  (d) Construct Hermitian-symmetric spectrum with original amplitudes.
  (e) Inverse FFT, clip to non-negative, re-normalize column means to 1.

**Truth channel.**  Independent fields are generated by running the wear-season
pipeline with different random seeds (different initial contact ensembles and
cell placements).  The P95 variance across these fields is the "truth" variance.

**Resolution decomposition.**  The P95 difference between coarse and fine grids
is split into:
  - *Activity-profile discretization*: difference in the column-mean profile
    due to grid coarsening.
  - *Extreme-value sampling*: the remaining difference attributable to
    finite-sample effects in the tail.

Conventions
-----------
* All depths in metres internally; summaries in micrometres.
* ``n_realizations`` = N (default 200) for the conditional simulator.
* ``n_truth`` = K (default 20) for the independent-repeat truth channel.
* Torch-based for consistency with the ice_abrasion module.
"""
from __future__ import annotations

import math
