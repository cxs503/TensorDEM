# 6. Truth channel
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class TruthChannelResult:
    """Result of the truth channel (independent repeat fields)."""

    fields: list[torch.Tensor]
    p95_values: list[float]
    p95_mean: float
    p95_std: float
    p95_cv: float
    n_truth: int
    seeds: list[int]

    def summary(self) -> dict[str, Any]:
        return {
            "n_truth": self.n_truth,
            "p95_mean_m": self.p95_mean,
            "p95_std_m": self.p95_std,
            "p95_cv": self.p95_cv,
            "p95_values_m": self.p95_values,
        }


def truth_channel(
    grid: ab.WaterlineGrid,
    *,
    n_truth: int = 20,
    seed_base: int = 100,
    source: ab.WearSourceConfig | None = None,
    voyage: ab.VoyageProfile | None = None,
    material: ab.TargetMaterial = ab.ICE_CLASS_EPOXY,
) -> TruthChannelResult:
    """Generate K independent wear fields for P95 truth variance."""
    source = ab.WearSourceConfig() if source is None else source
    voyage = ab.reference_baltic_voyage() if voyage is None else voyage

    fields, p95_values, seeds = [], [], []

    for k in range(n_truth):
        seed = seed_base + k * 7919
        seeds.append(seed)

        src = ab.WearSourceConfig(spec_rate=source.spec_rate,
                                  n_events_per_leg=source.n_events_per_leg, seed=seed)
        ens_cfg = ab.ContactEnsembleConfig(n_samples=1024, steps=32, seed=seed)

        season = ab.run_wear_season(grid=grid, voyage=voyage, material=material,
                                    source=src, ensemble_config=ens_cfg)

        depth = season.field_per_year.depth_m
        fields.append(depth)
        p95_values.append(float(torch.quantile(depth.flatten(), 0.95)))

    p95_arr = torch.tensor(p95_values, dtype=DTYPE)
    return TruthChannelResult(
        fields=fields, p95_values=p95_values,
        p95_mean=float(p95_arr.mean()), p95_std=float(p95_arr.std()),
        p95_cv=float(p95_arr.std()) / float(p95_arr.mean()) if float(p95_arr.mean()) > 0 else 0,
        n_truth=n_truth, seeds=seeds,
    )


# ---------------------------------------------------------------------------
# 7. Resolution decomposition
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ResolutionDecomposition:
    """Decomposition of P95 resolution difference."""

    coarse_p95: float
    fine_p95: float
    total_difference: float
    total_relative_pct: float
    activity_profile_discretization: float
    extreme_sampling_residual: float
    decomposition_closure_pct: float

    def summary(self) -> dict[str, Any]:
        return {
            "coarse_p95_m": self.coarse_p95, "fine_p95_m": self.fine_p95,
            "total_difference_m": self.total_difference,
            "total_relative_pct": self.total_relative_pct,
            "activity_profile_discretization_m": self.activity_profile_discretization,
            "extreme_sampling_residual_m": self.extreme_sampling_residual,
            "decomposition_closure_pct": self.decomposition_closure_pct,
        }


def resolution_decomposition(
    coarse_field: torch.Tensor, fine_field: torch.Tensor,
    coarse_grid: ab.WaterlineGrid, fine_grid: ab.WaterlineGrid,
) -> ResolutionDecomposition:
    """Decompose the P95 difference between coarse and fine resolution fields."""
    coarse = torch.as_tensor(coarse_field, dtype=DTYPE)
    fine = torch.as_tensor(fine_field, dtype=DTYPE)

    coarse_p95 = float(torch.quantile(coarse.flatten(), 0.95))
    fine_p95 = float(torch.quantile(fine.flatten(), 0.95))
    total_diff = coarse_p95 - fine_p95
    total_rel_pct = 100.0 * abs(total_diff) / fine_p95 if fine_p95 > 0 else 0.0

    coarse_activity, _ = decompose_field(coarse, coarse_grid)
    fine_activity, _ = decompose_field(fine, fine_grid)

    coarse_max = float(coarse_activity.max())
    fine_max = float(fine_activity.max())

    if coarse_max + fine_max > 0:
        activity_ratio = abs(coarse_max - fine_max) / (coarse_max + fine_max)
    else:
        activity_ratio = 0.0

    activity_contribution = total_diff * activity_ratio
    extreme_residual = total_diff - activity_contribution

    reconstructed = activity_contribution + extreme_residual
    closure_pct = 100.0 * abs(reconstructed - total_diff) / (abs(total_diff) + 1e-15)

    return ResolutionDecomposition(
        coarse_p95=coarse_p95, fine_p95=fine_p95,
        total_difference=total_diff, total_relative_pct=total_rel_pct,
        activity_profile_discretization=activity_contribution,
        extreme_sampling_residual=extreme_residual,
        decomposition_closure_pct=closure_pct,
    )


# ---------------------------------------------------------------------------
# 8. Validation helpers
# ---------------------------------------------------------------------------


def validate_autocorrelation_fidelity(
    source_residual: torch.Tensor, realizations: list[torch.Tensor],
    max_lag: int = 3, tolerance: float = 0.05,
) -> dict[str, Any]:
    """Validate ensemble average ACF fidelity."""
    source_acf = estimate_autocorrelation_2d(source_residual, max_lag=max_lag)
    center = max_lag

    ensemble_acf = torch.zeros_like(source_acf)
    for real in realizations:
        _, res = decompose_field(real)
        ensemble_acf += estimate_autocorrelation_2d(res, max_lag=max_lag)
    ensemble_acf /= len(realizations)

    region = slice(center - max_lag, center + max_lag + 1)
    src = source_acf[region, region].clone()
    ens = ensemble_acf[region, region].clone()
    src[max_lag, max_lag] = 0
    ens[max_lag, max_lag] = 0

    mag = src.abs().max()
    dev = float(((ens - src).abs() / (mag + 1e-15)).max())
    return {"criterion": "C1_autocorrelation_fidelity", "max_lag": max_lag,
            "tolerance": tolerance, "max_relative_deviation": dev, "passed": dev < tolerance}


def validate_power_spectrum_conservation(
    source_residual: torch.Tensor, realizations: list[torch.Tensor],
    tolerance: float = 0.02,
) -> dict[str, Any]:
    """Validate power spectrum energy conservation."""
    source_energy = float(estimate_power_spectrum(source_residual).sum())
    ratios = []
    for real in realizations:
        _, res = decompose_field(real)
        real_energy = float(estimate_power_spectrum(res).sum())
        ratios.append(abs(real_energy - source_energy) / (source_energy + 1e-15))
    max_ratio = max(ratios)
    return {"criterion": "C1_power_spectrum_conservation", "tolerance": tolerance,
            "max_energy_deviation": max_ratio, "passed": max_ratio < tolerance}


def validate_p95_variance_ratio(
    sim_result: ConditionalSimulatorResult, truth_result: TruthChannelResult,
    lower: float = 0.7, upper: float = 1.4,
) -> dict[str, Any]:
    """Validate P95 variance ratio."""
    sim_var = sim_result.p95_std ** 2
    truth_var = truth_result.p95_std ** 2
    ratio = sim_var / truth_var if truth_var > 0 else float("inf")
    return {"criterion": "C2_p95_variance_ratio", "ratio": ratio,
            "acceptable_range": [lower, upper], "passed": lower <= ratio <= upper}


def validate_profile_fidelity(
    source_field: torch.Tensor, realizations: list[torch.Tensor],
    tolerance: float = 1e-2,
) -> dict[str, Any]:
    """Validate column mean fidelity."""
    source_col = source_field.mean(dim=0)
    max_dev = 0.0
    for real in realizations:
        dev = float((real.mean(dim=0) - source_col).abs().max())
        max_dev = max(max_dev, dev / (float(source_col.max()) + 1e-15))
    return {"criterion": "C3_profile_fidelity", "tolerance": tolerance,
            "max_col_mean_deviation": max_dev, "passed": max_dev < tolerance}


def validate_reproducibility(
    depth_field: torch.Tensor, grid: ab.WaterlineGrid | None = None,
    *, n_realizations: int = 10, seed_base: int = 42,
) -> dict[str, Any]:
    """Validate bitwise reproducibility and cross-seed CV."""
    r1 = conditional_simulator(depth_field, grid, n_realizations=n_realizations, seed_base=seed_base)
    r2 = conditional_simulator(depth_field, grid, n_realizations=n_realizations, seed_base=seed_base)
    bitwise = all(torch.equal(a, b) for a, b in zip(r1.realizations, r2.realizations))
    r3 = conditional_simulator(depth_field, grid, n_realizations=n_realizations, seed_base=seed_base + 99999)
    cv = abs(r3.p95_mean - r1.p95_mean) / (r1.p95_mean + 1e-15)
    return {"criterion": "C6_reproducibility", "bitwise_identical": bitwise,
            "cross_seed_cv": cv, "passed": bitwise and cv < 0.05}
