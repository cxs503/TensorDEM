# ---------------------------------------------------------------------------
# 1. Field decomposition
# ---------------------------------------------------------------------------


def decompose_field(
    depth_m: torch.Tensor,
    grid: ab.WaterlineGrid | None = None,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Decompose a depth field into activity profile and normalized residual."""
    depth = torch.as_tensor(depth_m, dtype=DTYPE)
    if depth.dim() != 2:
        raise ValueError("depth_m must be 2D (n_z, n_x)")

    activity_profile = depth.mean(dim=0)
    safe_profile = torch.where(activity_profile > 0, activity_profile,
                               activity_profile.max() * 1e-12)
    residual = depth / safe_profile.unsqueeze(0)

    return activity_profile, residual


# ---------------------------------------------------------------------------
# 2. 2D autocorrelation estimation
# ---------------------------------------------------------------------------


def estimate_autocorrelation_2d(
    field_2d: torch.Tensor,
    max_lag: int = 10,
) -> torch.Tensor:
    """Estimate the 2D autocorrelation function of a field."""
    f = torch.as_tensor(field_2d, dtype=DTYPE)
    f = f - f.mean()
    n_z, n_x = f.shape

    variance = float((f ** 2).sum())
    if variance < 1e-30:
        return torch.ones(2 * max_lag + 1, 2 * max_lag + 1, dtype=DTYPE)

    pad_z = max_lag
    pad_x = max_lag
    f_padded = torch.zeros(n_z + 2 * pad_z, n_x + 2 * pad_x, dtype=DTYPE)
    f_padded[pad_z:pad_z + n_z, pad_x:pad_x + n_x] = f

    F = torch.fft.fft2(f_padded)
    acf_full = torch.fft.ifft2(F * F.conj()).real / variance
    acf_shifted = torch.fft.fftshift(acf_full)

    center_z = acf_shifted.shape[0] // 2
    center_x = acf_shifted.shape[1] // 2
    return acf_shifted[center_z - max_lag:center_z + max_lag + 1,
                       center_x - max_lag:center_x + max_lag + 1]


# ---------------------------------------------------------------------------
# 3. Power spectrum estimation
# ---------------------------------------------------------------------------


def estimate_power_spectrum(field_2d: torch.Tensor) -> torch.Tensor:
    """Estimate the 2D power spectral density of a field."""
    f = torch.as_tensor(field_2d, dtype=DTYPE)
    f = f - f.mean()
    F = torch.fft.fft2(f)
    return (F * F.conj()).real / float(f.numel())


# ---------------------------------------------------------------------------
# 4. Phase randomization (FFT-based conditional simulation)
# ---------------------------------------------------------------------------


def phase_randomize(
    field_2d: torch.Tensor,
    seed: int,
    *,
    preserve_column_structure: bool = True,
) -> torch.Tensor:
    """Generate one phase-randomized realization of a 2D field.

    Preserves the power spectrum exactly by constructing a Hermitian-symmetric
    spectrum with the original amplitudes and random phases.
    """
    f = torch.as_tensor(field_2d, dtype=DTYPE)
    n_z, n_x = f.shape

    col_means = f.mean(dim=0)
    f_detrended = f - col_means.unsqueeze(0)

    F = torch.fft.fft2(f_detrended)
    amplitude = F.abs()

    # Generate random phases
    g = torch.Generator().manual_seed(seed)
    phases = torch.rand(n_z, n_x, generator=g, dtype=DTYPE) * 2 * math.pi

    # Build Hermitian-symmetric spectrum
    # For real output: F[k,l] = conj(F[-k,-l])
    # We set phases for the "upper" half and mirror to the "lower" half
    
    F_new = torch.zeros_like(F, dtype=torch.complex128)
    
    # Create index arrays
    kz = torch.arange(n_z)
    kx = torch.arange(n_x)
    KZ, KX = torch.meshgrid(kz, kx, indexing='ij')
    
    # Conjugate indices
    NKZ = (-KZ) % n_z
    NKX = (-KX) % n_x
    
    # Linear index for comparison
    idx = KZ * n_x + KX
    nidx = NKZ * n_x + NKX
    
    # Independent frequencies: where idx <= nidx (upper triangle including diagonal)
    independent = idx <= nidx
    
    # Set random phases for independent frequencies
    F_new[independent] = amplitude[independent] * torch.exp(1j * phases[independent])
    
    # Mirror to dependent frequencies with conjugate
    dependent = ~independent
    F_new[dependent] = F_new[NKZ[dependent], NKX[dependent]].conj()
    
    # DC component (0,0) must be real
    F_new[0, 0] = amplitude[0, 0]  # Phase doesn't matter for DC
    
    # Nyquist frequencies (if even dimensions) must be real
    if n_z % 2 == 0:
        F_new[n_z // 2, :] = amplitude[n_z // 2, :] * torch.cos(phases[n_z // 2, :])
    if n_x % 2 == 0:
        F_new[:, n_x // 2] = amplitude[:, n_x // 2] * torch.cos(phases[:, n_x // 2])

    # Inverse FFT
    f_new = torch.fft.ifft2(F_new).real

    # Re-add column means
    f_new = f_new + col_means.unsqueeze(0)

    # Clip to non-negative
    return f_new.clamp(min=0.0)


# ---------------------------------------------------------------------------
# 5. Conditional simulator
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class ConditionalSimulatorResult:
    """Result of conditional simulation of an ice abrasion field."""

    source_field: torch.Tensor
    activity_profile: torch.Tensor
    residual: torch.Tensor
    realizations: list[torch.Tensor]
    p95_values: list[float]
    p95_mean: float
    p95_std: float
    p95_cv: float
    n_realizations: int
    seed_base: int
    autocorrelation: torch.Tensor | None = None
    power_spectrum: torch.Tensor | None = None

    def summary(self) -> dict[str, Any]:
        return {
            "n_realizations": self.n_realizations,
            "p95_mean_m": self.p95_mean,
            "p95_std_m": self.p95_std,
            "p95_cv": self.p95_cv,
            "p95_values_m": self.p95_values,
            "source_p95_m": float(torch.quantile(self.source_field.flatten(), 0.95)),
        }


def conditional_simulator(
    depth_field: torch.Tensor,
    grid: ab.WaterlineGrid | None = None,
    *,
    n_realizations: int = 200,
    seed_base: int = 42,
    max_lag: int = 10,
) -> ConditionalSimulatorResult:
    """Run conditional simulation of an ice abrasion depth field."""
    depth = torch.as_tensor(depth_field, dtype=DTYPE)

    activity_profile, residual = decompose_field(depth, grid)
    acf = estimate_autocorrelation_2d(residual, max_lag=max_lag)
    psd = estimate_power_spectrum(residual)

    realizations = []
    p95_values = []
    for i in range(n_realizations):
        seed = seed_base + i * 1000
        sim_residual = phase_randomize(residual, seed=seed)
        sim_field = activity_profile.unsqueeze(0) * sim_residual
        sim_field = sim_field.clamp(min=0.0)
        realizations.append(sim_field)
        p95 = float(torch.quantile(sim_field.flatten(), 0.95))
        p95_values.append(p95)

    p95_arr = torch.tensor(p95_values, dtype=DTYPE)
    p95_mean = float(p95_arr.mean())
    p95_std = float(p95_arr.std())
    p95_cv = p95_std / p95_mean if p95_mean > 0 else 0.0

    return ConditionalSimulatorResult(
        source_field=depth,
        activity_profile=activity_profile,
        residual=residual,
        realizations=realizations,
        p95_values=p95_values,
        p95_mean=p95_mean,
        p95_std=p95_std,
        p95_cv=p95_cv,
        n_realizations=n_realizations,
        seed_base=seed_base,
        autocorrelation=acf,
        power_spectrum=psd,
    )


