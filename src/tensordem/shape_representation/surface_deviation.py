def complete_elliptic_KE(e: float) -> Tuple[float, float]:
    """Complete elliptic integrals ``K(e)``, ``E(e)`` by AGM (machine accuracy).

    ``K = int_0^{pi/2} (1 - e^2 sin^2 t)^{-1/2} dt`` and
    ``E = int_0^{pi/2} (1 - e^2 sin^2 t)^{1/2} dt`` with modulus ``0 <= e < 1``.
    """
    e = float(min(max(e, 0.0), 1.0 - 1.0e-15))
    b2 = math.sqrt(max(1.0 - e * e, 1.0e-30))
    a2 = 1.0
    c2sum = 0.0
    cn = 0.5 * (a2 - b2)
    for n in range(1, 60):
        if abs(cn) < 1.0e-19:
            break
        c2sum += (2.0 ** (n - 1)) * cn * cn
        a2, b2 = 0.5 * (a2 + b2), math.sqrt(a2 * b2)
        cn = 0.5 * (a2 - b2)
    K = math.pi / (2.0 * a2)
    E = K * (1.0 - c2sum)
    return K, E


