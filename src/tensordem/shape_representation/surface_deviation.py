def ellipticity_closure(curvature_ratio: float) -> Tuple[float, float]:
    """Map ``A/B`` -> ``(e, f_a)`` by interpolation of the closure table.

    Three-point Lagrange interpolation in ``log(A/B)`` (the table is
    geometrically graded in the curvature ratio).  Max closure error over
    ``A/B in [1, 224]`` is 0.3 % (verified against the quadrature by
    ``scripts/p40_n10_shape_verdict.py``).
    """
    r = float(max(curvature_ratio, 1.0))
    tab = _HERTZ_CLOSURE
    n = len(tab)
    if r <= tab[0][1]:
        return tab[0][0], tab[0][2]
    lr = math.log(r)
    logs = [math.log(row[1]) for row in tab]
    if r >= tab[-1][1]:
        i = n - 1
        idx = (i - 1, i, i - 1)  # linear extrapolation guard on the last span
        idx = (i - 2, i - 1, i)
    else:
        for j in range(1, n):
            if r <= tab[j][1]:
                i = j
                break
        idx = (max(i - 2, 0), i - 1, i) if i >= 2 else (0, 1, 2)
    e = _lagrange3(lr, [logs[k] for k in idx], [tab[k][0] for k in idx])
    fa = _lagrange3(lr, [logs[k] for k in idx], [tab[k][2] for k in idx])
    return e, fa


def _lagrange3(x: float, xs: Sequence[float], ys: Sequence[float]) -> float:
    """Quadratic Lagrange interpolation (or linear extrapolation at the ends)."""
    x0, x1, x2 = xs
    y0, y1, y2 = ys
    if x2 == x1 or x1 == x0:
        return y1
    t = (x - x1) / (x2 - x1)
    if x1 == x0:
        return y1 + t * (y2 - y1)
    u = (x - x0) / (x1 - x0)
    # Newton form on three nodes
    d1 = (y1 - y0) / (x1 - x0)
    d2 = ((y2 - y1) / (x2 - x1) - d1) / (x2 - x0)
    return y0 + d1 * (x - x0) + d2 * (x - x0) * (x - x1)


@dataclass
class EllipticHertzResult:
    """Normal contact of an ellipsoid on a rigid plane (load control)."""

    a_tight: float     # contact semi-axis along the larger-curvature direction (A)
    a_flat: float      # contact semi-axis along the smaller-curvature direction (B)
    p0: float          # peak pressure
    delta: float       # approach (overlap)
    force: float       # normal force
    stiffness: float   # dF/ddelta
    eccentricity: float
    method: str = "closed-form"

    @property
    def area(self) -> float:
        return math.pi * self.a_tight * self.a_flat


def elliptic_hertz(A: float, B: float, E_star: float, force: float) -> EllipticHertzResult:
    """Elliptical Hertz solution in elliptic-integral form + tabulated closure.

    ``A >= B >= 0`` are the relative principal curvatures of the gap
    ``g = 0.5 (A x**2 + B y**2)``.  For an ellipsoid ``(a, b, c)`` pressed along
    ``c``: ``A = c/a**2``, ``B = c/b**2`` (so ``A >= B`` when ``a <= b``).
    """
    A = float(A)
    B = float(max(B, 1.0e-12 * max(A, 1e-30)))
    if A < B:
        A, B = B, A
    force = float(force)
    e, f_a = ellipticity_closure(A / B)
    K, _ = complete_elliptic_KE(e)

    a_tight = f_a * (3.0 * force / (4.0 * E_star * A)) ** (1.0 / 3.0)
    a_flat = a_tight / math.sqrt(max(1.0 - e * e, 1.0e-18))
    # verified against the quadrature: delta = (p0 a_flat/E*) K(e)
    delta = 3.0 * force * K / (2.0 * math.pi * E_star * a_flat)
    stiffness = 1.5 * force / delta if delta > 0 else 0.0
    p0 = 3.0 * force / (2.0 * math.pi * a_tight * a_flat)
    return EllipticHertzResult(a_tight, a_flat, p0, delta, force, stiffness, e, "closed-form")


def _ellipse_ray_length(x: float, y: float, a: float, b: float,
                        cf: float, sf: float) -> float:
    """Distance from an interior point to the ellipse boundary along (cf, sf)."""
    qa = cf * cf / (a * a) + sf * sf / (b * b)
    qb = 2.0 * (x * cf / (a * a) + y * sf / (b * b))
    qc = x * x / (a * a) + y * y / (b * b) - 1.0
    disc = qb * qb - 4.0 * qa * qc
    if disc <= 0.0:
        return 0.0
    return max((-qb + math.sqrt(disc)) / (2.0 * qa), 0.0)


def _displacement_scaled(x: float, y: float, a: float, b: float,
                         n_phi: int = 96, n_u: int = 64) -> float:
    """``int int sqrt(1 - x'^2/a^2 - y'^2/b^2) / |r - r'| dA'`` (Boussinesq kernel).

    Integrated in polar coordinates centred on the evaluation point, which
    removes the ``1/rho`` singularity analytically (``dA' = rho drho dphi``);
    the residual square-root edge singularity is regularised by
    ``u = 1 - (1 - v)**2``.
    """
    gv, wv = np.polynomial.legendre.leggauss(n_u)
    v = 0.5 * (gv + 1.0)
    wv = 0.5 * wv
    u = 1.0 - (1.0 - v) ** 2
    du_dv = 2.0 * (1.0 - v)
    dphi = 2.0 * math.pi / n_phi
    total = 0.0
    for k in range(n_phi):
        ang = k * dphi
        c, s = math.cos(ang), math.sin(ang)
        rmax = _ellipse_ray_length(x, y, a, b, c, s)
        if rmax <= 0.0:
            continue
        r = rmax * u
        xp = x + r * c
        yp = y + r * s
        val = np.sqrt(np.clip(1.0 - xp * xp / (a * a) - yp * yp / (b * b), 0.0, None))
        total += dphi * rmax * float(np.sum(wv * du_dv * val))
    return total


def _fit_quadratic(w: np.ndarray, xs: np.ndarray, ys: np.ndarray) -> Tuple[float, float, float]:
    """Least-squares fit ``w = w0 - alpha x^2 - beta y^2`` (no cross term)."""
    M = np.column_stack([np.ones_like(xs), xs * xs, ys * ys])
    coef, *_ = np.linalg.lstsq(M, w, rcond=None)
    return float(coef[0]), float(-coef[1]), float(-coef[2])


_QUAD_PTS = np.array([(r * math.cos(t), r * math.sin(t))
                      for r in (0.15, 0.35, 0.55) for t in (0.0, math.pi / 2.0)])


def elliptic_hertz_quadrature(A: float, B: float, E_star: float, force: float,
                              n_phi: int = 96, n_u: int = 64) -> EllipticHertzResult:
    """Same problem solved from the half-space integral equation (independent).

    No elliptic integral is used.  For a trial contact ellipse
    ``(a_tight, kappa * a_tight)`` the half-space displacement under the
    ellipsoidal pressure ``p0 sqrt(1 - x^2/a^2 - y^2/b^2)`` is obtained by
    direct quadrature of the Boussinesq kernel.  Inside the contact the
    compatibility condition ``w = delta - 0.5 (A x^2 + B y^2)`` requires the
    fitted coefficients to satisfy ``alpha/beta = A/B`` (fixes ``kappa``
    independently of the load) and ``alpha = A/2`` (fixes the semi-axes at the
    given load).
    """
    A = float(A)
    B = float(max(B, 1.0e-12 * max(A, 1e-30)))
    if A < B:
        A, B = B, A
    force = float(force)
    pts = _QUAD_PTS

    def fit(kappa: float) -> Tuple[float, float, float]:
        w = np.array([_displacement_scaled(x, y, 1.0, kappa, n_phi, n_u) / math.pi
                      for x, y in pts])
        return _fit_quadratic(w, pts[:, 0], pts[:, 1])

    target = A / B
    if abs(target - 1.0) < 1.0e-12:
        kappa = 1.0
    else:
        lo, hi = 1.0, 4.0e3
        for _ in range(80):
            mid = math.sqrt(lo * hi)
            _, al, be = fit(mid)
            if al / be < target:
                lo = mid
            else:
                hi = mid
            if abs(hi - lo) < 1.0e-6 * lo:
                break
        kappa = math.sqrt(lo * hi)

    w0_u, al_u, be_u = fit(kappa)
    # scaling: w_phys = (p0 a_tight/E*) * w_hat(x/a_tight, y/a_tight), so the
    # x^2 coefficient is alpha = p0 al_u /(E* a_tight) = A/2
    #   => p0 = A E* a_tight /(2 al_u)
    # and F = (2/3) pi a_tight a_flat p0 = (2/3) pi kappa a_tight^2 p0
    #   => a_tight^3 = 3 F al_u /(pi kappa A E*)
    a_tight = (3.0 * force * al_u / (math.pi * kappa * A * E_star)) ** (1.0 / 3.0)
    a_flat = kappa * a_tight
    p0 = 0.5 * A * E_star * a_tight / al_u
    delta = w0_u * p0 * a_tight / E_star
    stiffness = 1.5 * force / delta if delta > 0 else 0.0
    e = math.sqrt(max(1.0 - 1.0 / (kappa * kappa), 0.0))
    return EllipticHertzResult(a_tight, a_flat, p0, delta, force, stiffness, e, "quadrature")


def equivalent_radius_hertz(A: float, B: float, E_star: float,
                            force: float) -> EllipticHertzResult:
    """Isotropic shortcut used by curvature-collapsed DEM contact laws.

    Replaces the elliptical contact by a circular Hertz contact with the
    geometric-mean equivalent radius ``R_eq = 1/sqrt(A B)``.  Its deviation from
    the elliptical solution *is* the representation error bounded by criterion
    (a).
    """
    A = float(A)
    B = float(max(B, 1.0e-12 * max(A, 1e-30)))
    if A < B:
        A, B = B, A
    R_eq = 1.0 / math.sqrt(A * B)
    delta = (9.0 * force * force / (16.0 * E_star * E_star * R_eq)) ** (1.0 / 3.0)
    a_c = math.sqrt(R_eq * delta)
    p0 = 3.0 * force / (2.0 * math.pi * a_c * a_c)
    return EllipticHertzResult(a_c, a_c, p0, delta, force,
                               1.5 * force / delta, 0.0, "equivalent-radius")


