@dataclass(frozen=True)
class Superquadric:
    """``(|x/a|^n2 + |y/b|^n2)^(n1/n2) + |z/c|^n1 = 1`` (n1=n2=2 -> ellipsoid)."""

    a: float
    b: float
    c: float
    n1: float = 2.0
    n2: float = 2.0

    @property
    def is_ellipsoid(self) -> bool:
        return abs(self.n1 - 2.0) < 1e-12 and abs(self.n2 - 2.0) < 1e-12


def sample_superquadric_surface(sq: Superquadric, n_u: int = 64, n_v: int = 32) -> np.ndarray:
    """Surface points via the ``|cos|**(2/n)`` parameterisation."""
    u = np.linspace(-math.pi, math.pi, n_u, endpoint=False)
    v = np.linspace(-0.5 * math.pi, 0.5 * math.pi, n_v, endpoint=False)
    uu, vv = np.meshgrid(u, v, indexing="ij")
    uu, vv = uu.ravel(), vv.ravel()
    cu, su, cv, sv = np.cos(uu), np.sin(uu), np.cos(vv), np.sin(vv)
    eu = 2.0 / sq.n2
    ev = 2.0 / sq.n1
    x = sq.a * np.sign(cv) * np.abs(cv) ** ev * np.sign(cu) * np.abs(cu) ** eu
    y = sq.b * np.sign(cv) * np.abs(cv) ** ev * np.sign(su) * np.abs(su) ** eu
    z = sq.c * np.sign(sv) * np.abs(sv) ** ev
    return np.column_stack([x, y, z])


def union_balls_signed_distance(points: np.ndarray, centers: np.ndarray,
                                radii: np.ndarray) -> np.ndarray:
    """Exact signed distance to a union of balls (negative inside)."""
    p = np.atleast_2d(points)
    d = np.linalg.norm(p[:, None, :] - centers[None, :, :], axis=2) - radii[None, :]
    return d.min(axis=1)


def _implicit_sq(points: np.ndarray, sq: Superquadric) -> np.ndarray:
    x = np.abs(points[:, 0] / sq.a) ** sq.n2
    y = np.abs(points[:, 1] / sq.b) ** sq.n2
    z = np.abs(points[:, 2] / sq.c) ** sq.n1
    return (x + y) ** (sq.n1 / sq.n2) + z - 1.0


def sq_signed_distance_estimate(points: np.ndarray, sq: Superquadric,
                                h: float = 1.0e-6) -> np.ndarray:
    """First-order signed-distance estimate ``F / |grad F|`` (%-level accurate)."""
    F = _implicit_sq(points, sq)
    grad = np.empty_like(points)
    for i in range(3):
        dp = np.zeros(3)
        dp[i] = h
        grad[:, i] = (_implicit_sq(points + dp, sq) - _implicit_sq(points - dp, sq)) / (2 * h)
    gn = np.linalg.norm(grad, axis=1)
    gn = np.where(gn < 1e-12, 1e-12, gn)
    return F / gn


def _radial_hit(direction: np.ndarray, sq: Superquadric) -> float:
    lo, hi = 0.0, max(sq.a, sq.b, sq.c) * 3.0
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        if _implicit_sq((mid * direction)[None, :], sq)[0] < 0.0:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def _max_inscribed_radius(center: np.ndarray, sq: Superquadric,
                          n_dirs: int = 96) -> float:
    """Exact inscribed radius of a ball centred at ``center`` (body interior).

    The radius must be the *minimum* distance from the centre to the body
    boundary over all directions -- using the radial direction alone (the naive
    construction) lets the ball poke out of the body tangentially and inflates
    the two-sided geometric error by an order of magnitude.  The minimum is
    obtained by a vectorised bisection over a Fibonacci direction set.
    """
    idx = np.arange(n_dirs) + 0.5
    z = 1.0 - 2.0 * idx / n_dirs
    r = np.sqrt(np.clip(1.0 - z * z, 0.0, None))
    th = math.pi * (1.0 + 5.0 ** 0.5) * idx
    dirs = np.column_stack([r * np.cos(th), r * np.sin(th), z])
    lo = np.zeros(n_dirs)
    hi = np.full(n_dirs, float(max(sq.a, sq.b, sq.c)) * 2.0)
    for _ in range(70):
        mid = 0.5 * (lo + hi)
        pts = center[None, :] + mid[:, None] * dirs
        inside = _implicit_sq(pts, sq) <= 0.0
        lo = np.where(inside, mid, lo)
        hi = np.where(inside, hi, mid)
    return float(np.min(0.5 * (lo + hi)))


def fit_inscribed_clump(sq: Superquadric, n_spheres: int,
                        shell_scales: Sequence[float] = (0.55, 0.72, 0.86, 0.95)
                        ) -> Tuple[np.ndarray, np.ndarray]:
    """Deterministic inscribed N-sphere clump for a superquadric body.

    The ``N`` centres are a Fibonacci (quasi-uniform) point set pushed onto
    concentric *scaled copies* of the body (``shell_scales``) so that the clump
    fills the volume instead of only its skin; each radius is the largest one
    that keeps the ball inside the body (bisection on the implicit function).
    No random numbers and no grid, so the N-scan is monotone and repeatable,
    which is what a convergence study needs.

    Returns ``(centers (N,3), radii (N,))`` in the body frame.
    """
    n = int(n_spheres)
    if n < 1:
        raise ValueError("n_spheres must be >= 1")
    idx = np.arange(n) + 0.5
    zdir = 1.0 - 2.0 * idx / n
    rdir = np.sqrt(np.clip(1.0 - zdir * zdir, 0.0, None))
    theta = math.pi * (1.0 + 5.0 ** 0.5) * idx
    dirs = np.column_stack([rdir * np.cos(theta), rdir * np.sin(theta), zdir])

    scales = np.asarray(shell_scales, dtype=float)
    centers = np.empty((n, 3))
    radii = np.empty(n)
    for i in range(n):
        s = scales[i % len(scales)]
        t = _radial_hit(dirs[i], sq) * s
        c = t * dirs[i]
        centers[i] = c
        radii[i] = _max_inscribed_radius(c, sq)
    return centers, radii


@dataclass
class SurfaceDeviation:
    """Two-sided geometric error of a clump approximation."""

    n_spheres: int
    max_outward: float      # true surface outside the clump (under-fill)
    max_inward: float       # clump skin outside the body (over-fill)
    mean_abs: float
    rms: float
    rel_max: float          # max(|out|, |in|) / equivalent radius
    volume_ratio: float     # clump volume / body volume (Monte-Carlo)


def clump_surface_deviation(sq: Superquadric, centers: np.ndarray, radii: np.ndarray,
                            n_samples: int = 4000, seed: int = 7) -> SurfaceDeviation:
    """Two-sided surface deviation between a superquadric and an N-sphere clump.

    * outward: signed distance of *true-surface* samples to the clump union
      (positive => the true surface lies outside the clump, i.e. under-fill);
    * inward: signed distance of *clump-skin* samples to the true body
      (positive => the clump sticks out of the body, i.e. over-fill).
    """
    rng = np.random.default_rng(seed)
    surf = sample_superquadric_surface(sq, 200, 100)
    if len(surf) > n_samples:
        sel = rng.choice(len(surf), size=n_samples, replace=False)
        surf = surf[sel]

    d_true = union_balls_signed_distance(surf, centers, radii)
    outward = np.clip(d_true, 0.0, None)

    m = max(int(3000 / max(len(radii), 1)), 20)
    dirs = rng.normal(size=(len(radii) * m, 3))
    dirs /= np.linalg.norm(dirs, axis=1)[:, None]
    rep = np.repeat(np.arange(len(radii)), m)
    cl_pts = centers[rep] + radii[rep][:, None] * dirs
    d_union = union_balls_signed_distance(cl_pts, centers, radii)
    on_skin = d_union > -1e-6
    # Over-fill is only meaningful for skin points in the surface band: the
    # first-order distance estimate F/|grad F| is unusable deep inside the body
    # (|grad F| -> 0 near the centre), and inner skin cannot be over-fill.
    band = on_skin & (_implicit_sq(cl_pts, sq) > -0.25)
    if band.any():
        d_clump = sq_signed_distance_estimate(cl_pts[band], sq)
        inward = np.clip(-d_clump, 0.0, None)
    else:
        inward = np.zeros(1)

    nn = 40000
    box = np.array([sq.a, sq.b, sq.c]) * 1.02
    probe = (rng.random((nn, 3)) * 2.0 - 1.0) * box
    inside_body = _implicit_sq(probe, sq) <= 0.0
    inside_clump = union_balls_signed_distance(probe, centers, radii) <= 0.0
    nb = int(inside_body.sum())
    vol_ratio = float((inside_body & inside_clump).sum() / nb) if nb else 0.0

    err = np.concatenate([outward, inward])
    r_eq = (sq.a * sq.b * sq.c) ** (1.0 / 3.0)
    return SurfaceDeviation(
        n_spheres=int(len(radii)),
        max_outward=float(outward.max()) if len(outward) else 0.0,
        max_inward=float(inward.max()) if len(inward) else 0.0,
        mean_abs=float(np.mean(np.abs(err))),
        rms=float(math.sqrt(np.mean(err ** 2))),
        rel_max=float(max(outward.max() if len(outward) else 0.0,
                          inward.max() if len(inward) else 0.0) / r_eq),
        volume_ratio=vol_ratio,
    )

