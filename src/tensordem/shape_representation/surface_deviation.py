@dataclass
class PileConfig2D:
    """Configuration of the 2-D pile (angle-of-repose) experiment."""

    channel: str = "sphere"        # "sphere" | "clump" | "superellipse"
    n_particles: int = 200
    radius: float = 0.02           # equivalent-volume radius (m)
    shape_factor: float = 2.0      # superellipse exponent n (n=2 -> ellipse)
    aspect: float = 1.0            # long/short axis ratio
    n_sub: int = 32               # sub-disks per clump
    density: float = 2500.0        # kg/m^3 (per metre thickness)
    young_modulus: float = 5.0e7   # Pa
    poisson_ratio: float = 0.25
    mu_slide: float = 0.55         # Coulomb friction
    mu_roll: float = 0.10          # rolling-resistance coefficient (x r_eff)
    restitution: float = 0.1       # normal restitution coefficient
    viscous_damp: float = 0.999    # global velocity factor per step (quasi-static)
    dt: float = 4.0e-5             # s
    n_steps: int = 9000
    n_settle: int = 6000           # steps before the repose window
    n_iter: int = 3                # position-based contact iterations / step
    box_width: float = 0.55        # m; particles are released inside this width
    drop_height: float = 0.45      # m
    seed: int = 11
    gravity: float = 9.81
    record_every: int = 200
    side_walls: bool = False       # walls only needed for filling from a hopper


@dataclass
class PileResult:
    """Outputs of one pile run."""

    channel: str
    shape_factor: float
    aspect: float
    n_sub: int
    n_particles: int
    repose_deg: float
    repose_deg_std: float
    pseudo_dissipation: float      # |dE|/E per step in the static window
    kinetic_energy_final: float
    potential_energy_final: float
    contacts_final: int
    history: List[Dict[str, float]] = field(default_factory=list)


def _superellipse_support(a: float, b: float, n: float, theta: np.ndarray) -> np.ndarray:
    """Boundary point of ``|x/a|^n + |y/b|^n = 1`` along direction ``theta``."""
    c, s = np.cos(theta), np.sin(theta)
    r = (np.abs(c / a) ** n + np.abs(s / b) ** n) ** (-1.0 / n)
    return np.column_stack([r * c, r * s])


def superellipse_curve_radius(a: float, b: float, n: float, theta: float) -> float:
    """Local radius of curvature of a superellipse at parameter ``theta``."""
    h = 1.0e-4
    t = np.array([theta - h, theta, theta + h])
    p = _superellipse_support(a, b, n, t)
    d1 = (p[2] - p[0]) / (2 * h)
    d2 = (p[2] - 2 * p[1] + p[0]) / (h * h)
    kappa = abs(d1[0] * d2[1] - d1[1] * d2[0]) / max(np.linalg.norm(d1) ** 3, 1e-30)
    return 1.0 / max(kappa, 1e-12)


class _Pile:
    """2-D soft-particle pile: rigid bodies, position-based contacts, friction.

    Contacts are resolved positionally (XPBD style): a normal correction removes
    a fraction of the overlap, a tangential velocity clamp limited by
    ``mu_slide * overlap / dt`` supplies static friction (hence a finite angle of
    repose), and a rolling clamp limited by ``mu_roll * overlap * r / dt``
    supplies rolling resistance.  Neighbour search is a k-d tree on the bounding
    circles, so the cost is O(N log N) per iteration.
    """

    def __init__(self, cfg: PileConfig2D):
        from scipy.spatial import cKDTree  # local import: optional dependency

        self._KDTree = cKDTree
        self.cfg = cfg
        rng = np.random.default_rng(cfg.seed)
        n = int(cfg.n_particles)
        self.n = n
        self.channel = cfg.channel
        self.pos = np.zeros((n, 2))
        # compact lattice block (no initial overlap, reproducible) that slumps
        # into a free pile once the run starts
        dx = 2.02 * cfg.radius
        # tall narrow block -> the slump test produces a genuine triangular pile
        cols = max(4, int(round(0.5 * math.sqrt(n))))
        amp = 1.0 + 0.3 * (1.0 - 2.0 / max(cfg.shape_factor, 2.0))
        for i in range(n):
            r_, c_ = divmod(i, cols)
            self.pos[i] = ((c_ - cols / 2.0) * dx * amp,
                           cfg.radius * 1.01 + r_ * dx)
        # tiny jitter breaks the lattice symmetry so the block slumps instead of
        # standing as a perfectly balanced crystal
        self.pos += rng.normal(scale=0.02 * cfg.radius, size=(n, 2))
        self.ang = rng.uniform(0.0, 2.0 * math.pi, n)
        self.vel = np.zeros((n, 2))
        self.omega = np.zeros(n)

        if cfg.channel == "superellipse":
            th = np.linspace(0.0, 2.0 * math.pi, 721)
            unit = _superellipse_support(cfg.aspect, 1.0, cfg.shape_factor, th)
            unit_area = 0.5 * abs(np.sum(unit[:-1, 0] * unit[1:, 1]
                                         - unit[1:, 0] * unit[:-1, 1]))
            scale = math.sqrt(math.pi * cfg.radius ** 2 / max(unit_area, 1e-12))
            self.sq_b = float(scale)
            self.sq_a = float(cfg.aspect * scale)
            self.sq_n = float(cfg.shape_factor)
            area = math.pi * cfg.radius ** 2
            self.mass = np.full(n, cfg.density * area)
            self.inertia = np.full(n, 0.5 * cfg.density * area * cfg.radius ** 2)
            self.r_circ = np.full(n, math.hypot(self.sq_a, self.sq_b))
        elif cfg.channel == "clump":
            k = max(int(cfg.n_sub), 1)
            idx = np.arange(k) + 0.5
            ang = math.pi * (1.0 + 5.0 ** 0.5) * idx
            shell = np.sqrt(idx / k)
            loc = np.column_stack([0.62 * cfg.radius * shell * np.cos(ang),
                                   0.62 * cfg.radius * shell * np.sin(ang)])
            sub_r = np.full(k, 0.85 * cfg.radius / math.sqrt(k))
            area_sub = math.pi * sub_r ** 2
            area_target = math.pi * cfg.radius ** 2
            s = math.sqrt(area_target / area_sub.sum())
            self.sub_local = loc * s
            self.sub_r = sub_r * s
            self.sub_local[:, 0] *= cfg.aspect
            self.sub_r /= math.sqrt(cfg.aspect)
            m_sub = cfg.density * math.pi * self.sub_r ** 2
            self.mass = np.full(n, float(m_sub.sum()))
            i_loc = float(np.sum(m_sub * (self.sub_local ** 2).sum(axis=1))
                          + np.sum(0.5 * m_sub * self.sub_r ** 2))
            self.inertia = np.full(n, i_loc)
            self.r_circ = np.full(n, float(np.linalg.norm(self.sub_local, axis=1).max()
                                           + self.sub_r.max()))
        else:
            area = math.pi * cfg.radius ** 2
            self.mass = np.full(n, cfg.density * area)
            self.inertia = np.full(n, 0.5 * cfg.density * area * cfg.radius ** 2)
            self.r_circ = np.full(n, cfg.radius)
        self.radius = np.full(n, cfg.radius)
        self._tree = None
        self._xi: Dict[Tuple[int, int], np.ndarray] = {}

    # -- neighbour search -------------------------------------------------
    def _pairs(self) -> np.ndarray:
        if self._tree is None:
            self._tree = self._KDTree(self.pos)
            self._tree_r = 2.0 * float(self.r_circ.max()) * 1.02
        else:
            if len(self.pos) != self._tree.n:
                self._tree = self._KDTree(self.pos)
        rmax = float(self.r_circ.max())
        r = 2.0 * rmax * 1.02
        if abs(getattr(self, "_tree_r", 0.0) - r) > 1e-12 or self._tree.n != len(self.pos):
            self._tree = self._KDTree(self.pos)
            self._tree_r = r
        else:
            self._tree = self._KDTree(self.pos)
        pr = self._tree.query_pairs(r, output_type="ndarray")
        if len(pr) == 0:
            return np.zeros((0, 2), dtype=np.int64)
        return np.sort(pr, axis=1)

    # -- contacts ---------------------------------------------------------
    def contacts(self):
        pairs = self._pairs()
        if len(pairs) == 0:
            return None
        if self.channel == "superellipse":
            return self._contacts_superellipse(pairs)
        return self._contacts_disks(pairs)

    def _contacts_disks(self, pairs: np.ndarray):
        bi, bj = pairs[:, 0], pairs[:, 1]
        if self.channel == "sphere":
            d = self.pos[bj] - self.pos[bi]
            dist = np.linalg.norm(d, axis=1)
            overlap = self.radius[bi] + self.radius[bj] - dist
            m = overlap > 1e-12
            if not m.any():
                return None
            nrm = d[m] / np.maximum(dist[m, None], 1e-15)
            pi = self.pos[bi][m] - nrm * self.radius[bi][m, None]
            pj = self.pos[bj][m] + nrm * self.radius[bj][m, None]
            return bi[m], bj[m], pi, pj, nrm, overlap[m]

        ca, sa = np.cos(self.ang), np.sin(self.ang)
        k = len(self.sub_r)
        locx, locy = self.sub_local[:, 0], self.sub_local[:, 1]
        # world-frame sub-disk centres, shape (n, k, 2)
        wx = np.outer(ca, locx) - np.outer(sa, locy)
        wy = np.outer(sa, locx) + np.outer(ca, locy)
        sub = np.stack([wx, wy], axis=2)
        sub += self.pos[:, None, :]
        r_sub = self.sub_r
        out = []
        chunk = max(1, int(2.0e6 / (k * k)))  # keep the pair x sub-pair block small
        for s0 in range(0, len(bi), chunk):
            ia = bi[s0:s0 + chunk]
            ja = bj[s0:s0 + chunk]
            d = sub[ja][:, None, :, :] - sub[ia][:, :, None, :]     # (m, k, k, 2)
            dist = np.sqrt((d ** 2).sum(axis=3))
            overlap = (r_sub[:, None] + r_sub[None, :])[None, :, :] - dist
            msk = overlap > 1e-12
            if not msk.any():
                continue
            idx = np.nonzero(msk.reshape(-1))[0]
            n_pair = idx // (k * k)
            a_sub = (idx % (k * k)) // k
            b_sub = idx % k
            ov = overlap.reshape(-1)[idx]
            dv = d.reshape(-1, 2)[idx]
            dd = dist.reshape(-1)[idx]
            nrm = dv / np.maximum(dd[:, None], 1e-15)
            out.append((ia[n_pair], ja[n_pair],
                        sub[ia[n_pair], a_sub] - nrm * r_sub[a_sub][:, None],
                        sub[ja[n_pair], b_sub] + nrm * r_sub[b_sub][:, None],
                        nrm, ov))
        if not out:
            return None
        return tuple(np.concatenate([o[i] for o in out]) for i in range(6))

    def _support_world(self, body_idx: np.ndarray, nrm: np.ndarray) -> np.ndarray:
        """World support point of superellipse bodies along world direction nrm."""
        ca, sa = np.cos(self.ang[body_idx]), np.sin(self.ang[body_idx])
        nx = ca * nrm[:, 0] + sa * nrm[:, 1]
        ny = -sa * nrm[:, 0] + ca * nrm[:, 1]
        local = _superellipse_support(self.sq_a, self.sq_b, self.sq_n, np.arctan2(ny, nx))
        world = np.column_stack([ca * local[:, 0] - sa * local[:, 1],
                                 sa * local[:, 0] + ca * local[:, 1]])
        return self.pos[body_idx] + world

    def _gap_along(self, bi, bj, nrm) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
        pi = self._support_world(bi, -nrm)
        pj = self._support_world(bj, nrm)
        g = (nrm[:, 0] * (self.pos[bj, 0] - self.pos[bi, 0])
             + nrm[:, 1] * (self.pos[bj, 1] - self.pos[bi, 1])
             - np.einsum('ij,ij->i', pi - self.pos[bi], -nrm)
             - np.einsum('ij,ij->i', pj - self.pos[bj], nrm))
        return g, pi, pj

    def _contacts_superellipse(self, pairs: np.ndarray):
        bi, bj = pairs[:, 0], pairs[:, 1]
        best_th = np.zeros(len(bi))
        best_g = np.full(len(bi), -1e18)
        for th in np.linspace(0.0, 2.0 * math.pi, 16, endpoint=False):
            nrm = np.column_stack([np.full(len(bi), math.cos(th)),
                                   np.full(len(bi), math.sin(th))])
            g, _, _ = self._gap_along(bi, bj, nrm)
            m = g > best_g
            if m.any():
                best_g[m] = g[m]
                best_th[m] = th
        # two parabolic refinements of the contact normal
        for _ in range(2):
            dth = 0.20
            gs = []
            for off in (-dth, 0.0, dth):
                th = best_th + off
                nrm = np.column_stack([np.cos(th), np.sin(th)])
                g, _, _ = self._gap_along(bi, bj, nrm)
                gs.append(g)
            g0, g1, g2 = gs
            den = g0 - 2.0 * g1 + g2
            shift = np.where(np.abs(den) > 1e-18, 0.5 * (g0 - g2) / np.where(
                np.abs(den) > 1e-18, den, 1.0), 0.0)
            best_th = best_th + np.clip(shift, -1.0, 1.0) * dth
            best_g = g1
        nrm = np.column_stack([np.cos(best_th), np.sin(best_th)])
        g, pi, pj = self._gap_along(bi, bj, nrm)
        overlap = -g
        m = overlap > 1e-12
        if not m.any():
            return None
        return bi[m], bj[m], pi[m], pj[m], nrm[m], overlap[m]

    # -- floor / walls ----------------------------------------------------
    def _lowest_offset(self) -> np.ndarray:
        """Signed lowest point of each body relative to its centre (y)."""
        if self.channel == "superellipse":
            nrm = np.tile(np.array([0.0, -1.0]), (self.n, 1))
            sup = self._support_world(np.arange(self.n), nrm)
            return sup[:, 1] - self.pos[:, 1]
        if self.channel == "clump":
            ca, sa = np.cos(self.ang), np.sin(self.ang)
            wx = np.outer(ca, self.sub_local[:, 0]) - np.outer(sa, self.sub_local[:, 1])
            wy = np.outer(sa, self.sub_local[:, 0]) + np.outer(ca, self.sub_local[:, 1])
            return (wy - self.sub_r[None, :]).min(axis=1)
        return -self.radius

    # -- one time step ----------------------------------------------------
    def _floor_contacts(self):
        """Floor contacts as pseudo body pairs (bj = -1 means the rigid floor)."""
        low = self._lowest_offset()
        delta = -(self.pos[:, 1] + low)
        m = delta > 0.0
        if not m.any():
            return None
        idx = np.nonzero(m)[0]
        # nrm must point from the body towards the floor (i -> j convention),
        # i.e. downwards; with +y the compressive force would push the body
        # *into* the floor and the overlap grows without bound.
        nrm = np.tile(np.array([0.0, -1.0]), (len(idx), 1))
        pc = np.column_stack([self.pos[idx, 0], np.zeros(len(idx))])
        return idx, np.full(len(idx), -1, dtype=np.int64), pc, nrm, delta[idx]

    def step(self):
        """Explicit DEM step: Hertz normal, Coulomb tangential spring, rolling torque.

        Tangential springs are the only history in the model (keyed by body
        pair), which is what gives static friction and therefore a finite angle
        of repose; the rolling torque adds the shape-independent resistance that
        2-D disks would otherwise lack.
        """
        cfg = self.cfg
        dt = cfg.dt
        nu = cfg.poisson_ratio
        e_star = cfg.young_modulus / (2.0 * (1.0 - nu * nu))
        inv_m = 1.0 / self.mass
        inv_i = 1.0 / self.inertia
        force = np.zeros_like(self.pos)
        torque = np.zeros(self.n)

        c = self.contacts()
        f = self._floor_contacts()
        parts = []
        if c is not None:
            bi, bj, pi, pj, nrm, delta = c
            parts.append((bi, bj, 0.5 * (pi + pj), nrm, delta))
        if f is not None:
            parts.append(f)
        if not parts:
            self.vel[:, 1] -= cfg.gravity * dt
            self.pos += self.vel * dt
            self.ang += self.omega * dt
            return

        bi = np.concatenate([q[0] for q in parts])
        bj = np.concatenate([q[1] for q in parts])
        pc = np.concatenate([q[2] for q in parts])
        nrm = np.concatenate([q[3] for q in parts])
        delta = np.concatenate([q[4] for q in parts])

        r_eff = np.where(bj >= 0,
                         0.5 * (self.r_circ[bi] + self.r_circ[np.maximum(bj, 0)]),
                         self.r_circ[bi])
        kn = (4.0 / 3.0) * e_star * np.sqrt(r_eff) * np.sqrt(np.maximum(delta, 1e-18))
        fn = kn * delta

        # relative velocity at the contact point
        ri = pc - self.pos[bi]
        vi = self.vel[bi] + self.omega[bi, None] * np.column_stack([-ri[:, 1], ri[:, 0]])
        vj = np.zeros_like(vi)
        rj = np.zeros_like(ri)
        real = bj >= 0
        if real.any():
            bjr = bj[real]
            rj[real] = pc[real] - self.pos[bjr]
            vj[real] = self.vel[bjr] + self.omega[bjr, None] * np.column_stack(
                [-rj[real][:, 1], rj[real][:, 0]])
        vrel = vj - vi
        vn = np.einsum('ij,ij->i', vrel, nrm)
        t = np.column_stack([-nrm[:, 1], nrm[:, 0]])
        vt = np.einsum('ij,ij->i', vrel, t)

        # normal damping from the restitution coefficient (critical-damping form)
        m_eff = np.where(bj >= 0, 1.0 / (inv_m[bi] + inv_m[np.maximum(bj, 0)]), self.mass[bi])
        e_rest = min(max(cfg.restitution, 1e-3), 1.0)
        ln_e = math.log(e_rest)
        zeta = -ln_e / math.sqrt(math.pi ** 2 + ln_e ** 2)   # ~0.67 for e = 0.1
        gamma = 2.0 * zeta * np.sqrt(m_eff * 1.5 * np.maximum(kn, 1e-30))
        fn = np.maximum(fn - gamma * vn, 0.0)

        # tangential spring (static friction) with Coulomb cap
        key_i = bi
        key_j = np.where(bj >= 0, bj + self.n, -1)
        kt = 0.6 * kn
        xi = np.empty((len(bi), 2))
        keys = list(zip(key_i.tolist(), key_j.tolist()))
        for idx_k, (a, b) in enumerate(keys):
            v = self._xi.get((a, b))
            if v is None:
                v = np.zeros(2)
            v = v + vt[idx_k] * dt * t[idx_k]
            xi[idx_k] = v
        # spring force on body *j* is -kt*xi, so the force applied to body i
        # (and negated for j below) is +kt*xi; the opposite sign is anti-damping.
        ft_vec = kt[:, None] * xi
        ft = np.linalg.norm(ft_vec, axis=1)
        cap = cfg.mu_slide * fn
        scale = np.where(ft > np.maximum(cap, 1e-30), np.maximum(cap, 1e-30) / np.maximum(ft, 1e-30), 1.0)
        ft_vec *= scale[:, None]
        xi *= scale[:, None]
        self._xi = {k: xi[i] for i, k in enumerate(keys)}

        # rolling resistance torque (opposes relative spin)
        w_rel = np.where(bj >= 0, self.omega[bj] - self.omega[bi], -self.omega[bi])
        tau_roll = cfg.mu_roll * r_eff * fn * np.tanh(w_rel / 1.0)

        # assemble forces: nrm points from i to j, so the compressive force on
        # body i is along -nrm (getting the sign wrong makes contacts attractive
        # and the overlap grows exponentially -- verified during development)
        fvec = -fn[:, None] * nrm + ft_vec
        np.add.at(force, bi, fvec)
        np.add.at(torque, bi, ri[:, 0] * fvec[:, 1] - ri[:, 1] * fvec[:, 0] + tau_roll)
        if real.any():
            bjr = bj[real]
            np.add.at(force, bjr, -fvec[real])
            np.add.at(torque, bjr,
                      rj[real][:, 0] * (-fvec[real][:, 1]) - rj[real][:, 1] * (-fvec[real][:, 0])
                      - tau_roll[real])

        # semi-implicit Euler
        self.vel += force * inv_m[:, None] * dt
        self.vel[:, 1] -= cfg.gravity * dt
        self.omega += torque * inv_i * dt
        self.omega *= cfg.viscous_damp
        # global quasi-static damping: keeps the relaxation monotone and removes
        # any residual jitter injected by the tangential-history model
        self.vel *= cfg.viscous_damp
        speed = np.linalg.norm(self.vel, axis=1)
        fast = speed > 20.0
        if fast.any():   # numerical safeguard; never active in a healthy run
            self.vel[fast] *= (20.0 / speed[fast])[:, None]
        self.pos += self.vel * dt
        self.ang += self.omega * dt

    # -- diagnostics ------------------------------------------------------
    def energy(self) -> Tuple[float, float]:
        ke = 0.5 * float(np.sum(self.mass * (self.vel ** 2).sum(axis=1)
                                + self.inertia * self.omega ** 2))
        pe = float(np.sum(self.mass * self.cfg.gravity * self.pos[:, 1]))
        return ke, pe

    def n_contacts(self) -> int:
        c = self.contacts()
        return 0 if c is None else int(len(c[0]))


def repose_angle_from_pile(pos: np.ndarray, radius: float, n_bins: int = 12,
                           percentile: float = 100.0, half_frac: float = 0.5,
                           skip: int = 1) -> Tuple[float, float]:
    """Angle of repose from a 2-D pile's free surface.

    The upper envelope of the particle centres is binned in ``x`` (the
    ``percentile``-th height per bin, 100 = the free surface itself) and a
    straight line is fitted to each flank, skipping ``skip`` bins around the
    apex; the reported angle is the mean of the two flank slopes with their
    spread.  The settings are validated against a synthetic 32 deg triangular
    pile in ``tests/test_shape_representation.py`` (recovered to within 1 deg).
    """
    x, y = pos[:, 0], pos[:, 1]
    hw = half_frac * (x.max() - x.min())
    edges = np.linspace(-hw, hw, n_bins + 1)
    cx, cy = [], []
    for lo, hi in zip(edges[:-1], edges[1:]):
        m = (x >= lo) & (x < hi)
        if m.sum() >= 2:
            cx.append(0.5 * (lo + hi))
            cy.append(float(np.percentile(y[m], percentile)))
    if len(cx) < 5:
        return float("nan"), float("nan")
    cx, cy = np.array(cx), np.array(cy)
    apex = int(np.argmax(cy))
    slopes = []
    sides = (slice(0, max(apex - skip + 1, 2)),
             slice(min(apex + skip, len(cx) - 1), len(cx)))
    for side in sides:
        if len(cx[side]) >= 2:
            A = np.column_stack([cx[side], np.ones(len(cx[side]))])
            coef, *_ = np.linalg.lstsq(A, cy[side], rcond=None)
            slopes.append(float(coef[0]))
    if not slopes:
        return float("nan"), float("nan")
    angs = [math.degrees(math.atan(abs(s))) for s in slopes]
    return float(np.mean(angs)), float(np.std(angs))


def run_pile(cfg: PileConfig2D, verbose: bool = False) -> PileResult:
    """Integrate one pile experiment; return repose angle and pseudo-dissipation."""
    pile = _Pile(cfg)
    history: List[Dict[str, float]] = []
    prev_e = None
    diss: List[float] = []
    for step in range(cfg.n_steps):
        pile.step()
        if step >= cfg.n_settle:
            ke, pe = pile.energy()
            e = ke + pe
            if prev_e is not None and abs(e) > 1e-12:
                diss.append(abs(e - prev_e) / abs(e))
            prev_e = e
        if cfg.record_every and step % cfg.record_every == 0:
            ke, pe = pile.energy()
            history.append({"step": float(step), "ke": ke, "pe": pe,
                            "contacts": float(pile.n_contacts())})
            if verbose and step % (cfg.record_every * 10) == 0:
                print(f"  step {step:6d} ke={ke:.3e} pe={pe:.3e}"
                      f" contacts={history[-1]['contacts']:.0f}")
    ke, pe = pile.energy()
    phi, phi_std = repose_angle_from_pile(pile.pos, cfg.radius)
    return PileResult(
        channel=cfg.channel,
        shape_factor=float(cfg.shape_factor),
        aspect=float(cfg.aspect),
        n_sub=int(cfg.n_sub),
        n_particles=int(cfg.n_particles),
        repose_deg=float(phi),
        repose_deg_std=float(phi_std),
        pseudo_dissipation=float(np.mean(diss)) if diss else float("nan"),
        kinetic_energy_final=ke,
        potential_energy_final=pe,
        contacts_final=pile.n_contacts(),
        history=history,
    )
