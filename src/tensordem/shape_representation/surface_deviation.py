"""Non-spherical particle representation: error bounds for clump vs. true shape.

Campaign node **P40-N10** (TensorDEM).  The question answered here is
quantitative, not qualitative:

    *How far can an N-sphere clump (or an equivalent-radius Hertz law) be pushed
    before the shape error contaminates a macroscopic observable (angle of
    repose), and what is the error bound?*

Three building blocks live in this module.

1. **Ellipsoid-plane normal contact (analytic anchor).**
   An ellipsoid pressed on a rigid plane is the classical *elliptical* Hertz
   problem: the relative curvatures at the contact point are ``A = c/a**2`` and
   ``B = c/b**2`` (for ``x**2/a**2 + y**2/b**2 + z**2/c**2 = 1`` pressed along
   ``z``).  Two independent routes are implemented:

   * :func:`elliptic_hertz_quadrature` -- solves the half-space integral
     equation (Boussinesq kernel) numerically, without using any elliptic
     integral.  It is the independent reference.
   * :func:`elliptic_hertz` -- the elliptical Hertz solution written with the
     complete elliptic integrals ``K(e)``, ``E(e)`` for the approach law plus a
     tabulated ellipticity closure (the classical "Hertz coefficient" table,
     computed here from first principles rather than copied).

   Their agreement (< 2 %) and the exact circular limit (``A = B`` reduces to
   Hertz ``F = (4/3) E* sqrt(R*) delta**1.5``) is acceptance criterion (a).

   Relations used below, each verified against the quadrature in
   ``tests/test_shape_representation.py``::

       delta   = 3 P K(e) / (2 pi E* a_flat)         (approach law; a_flat = major axis)
       a_tight = f_a(e) * (3 P / (4 E* A))**(1/3)    (semi-axis along A)
       a_flat  = a_tight / sqrt(1 - e**2)
       k_n     = 3 P / (2 delta)                     (since F ~ delta**1.5)

   ``e`` is not free: it follows from the curvature ratio ``A/B`` through a
   transcendental relation, so ``(e, f_a)`` are tabulated on ``A/B`` by the
   quadrature and interpolated here (closure error < 0.3 %).

2. **N-sphere clump geometry.**  :func:`fit_inscribed_clump` builds a
   deterministic inscribed N-sphere clump for a superquadric and
   :func:`clump_surface_deviation` reports the *two-sided* surface error using
   the exact union-of-balls signed distance.

3. **2-D pile test bed (three channels).**  :class:`PileConfig2D` /
   :func:`run_pile` is a compact 2-D soft-particle DEM: disks (``"sphere"``),
   rigid disk clusters (``"clump"``) and superellipses (``"superellipse"``)
   share one contact-law family (Hertz normal spring, Coulomb tangential
   friction, rolling-resistance torque), so repose angles are comparable
   across representations.  The same run yields the *static pile
   pseudo-dissipation* (criterion d).

Scope note (honest): 3-D superquadric contact iteration is **not** re-solved
here -- :mod:`tensordem.superquadric_kernel` already provides it -- and the
campaign degradation rule allows narrowing to the 2-D superellipse plus the 3-D
ellipsoid analytic anchor, which is what is delivered.
"""
