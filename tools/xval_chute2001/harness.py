#!/usr/bin/env python3
"""Cross-validation harness: inclined-plane (chute) granular flow.

One case specification (:mod:`tensordem.chute_flow.spec`) is rendered into
* three inputs: TensorDEM (native), LIGGGHTS and LAMMPS decks;
* one neutral dump schema ``t,id,x,y,z,vx,vy,vz``;
* one analysis path (:mod:`tensordem.chute_flow.analysis`) for all three tools.

Subcommands
-----------
``build``    write case_spec dirs (+ LIGGGHTS/LAMMPS data files and decks)
``run``      run one tool on one case (``--tool ours|liggghts|lammps``)
``analyze``  neutral post-processing of one finished run
``table``    aggregate every finished run into the cross-validation table

Everything is deterministic from the case spec; the OSS decks read the *same*
particle and base-sphere coordinate files as our engine, so no code gets to
invent its own initial condition.
"""
